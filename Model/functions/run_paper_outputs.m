function write_bundle_readme(paper_dir,manifest,options)
path = fullfile(paper_dir,'README.md');
fid = fopen(path,'w');
assert(fid>=0,'FullPaperRun:Readme','Could not write %s.',path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'# Full Paper Replication %s\n\n',manifest.run_id);
fprintf(fid,'Generated by MAIN_REPLICATION in MATLAB %s.\n\n',version('-release'));
fprintf(fid,'Figures and Tables contain the paper exhibits. Run_Reports records numerical checks.\n');
fprintf(fid,'The regular scenarios use 800 quarters; Figure 7 uses 7,000 quarters.\n');
fprintf(fid,'Resume this run with MAIN_REPLICATION(''%s'').\n',manifest.run_id);

end


function write_failure_readme(paper_dir,manifest,ME)
path = fullfile(paper_dir,'README.md');
fid = fopen(path,'w');
if fid < 0
    return
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'# Incomplete Full Paper Replication %s\n\n',manifest.run_id);
fprintf(fid,'The workflow stopped before producing a complete bundle.\n\n');
fprintf(fid,'Error: `%s`\n\n%s\n',ME.identifier,ME.message);
fprintf(fid,'See `full_run_manifest.json` and the run diary under Results.\n');
end


function inventory_path = write_inventory(paper_dir)
files = dir(fullfile(paper_dir,'**','*'));
files = files(~[files.isdir]);
excluded = {'MANIFEST_SHA256.csv','full_run_manifest.json'};
relative = strings(0,1);
bytes = zeros(0,1);
sha256 = strings(0,1);
for i = 1:numel(files)
    path = fullfile(files(i).folder,files(i).name);
    rel = erase(path,[paper_dir filesep]);
    if any(strcmp(files(i).name,excluded))
        continue
    end
    relative(end+1,1) = string(strrep(rel,filesep,'/')); %#ok<AGROW>
    bytes(end+1,1) = files(i).bytes; %#ok<AGROW>
    sha256(end+1,1) = string(paper_bundle_sha256(path)); %#ok<AGROW>
end
inventory = table(relative,bytes,sha256, ...
    'VariableNames',{'RelativePath','Bytes','SHA256'});
inventory = sortrows(inventory,'RelativePath');
inventory_path = fullfile(paper_dir,'MANIFEST_SHA256.csv');
writetable(inventory,inventory_path);
end


function copy_if_present(source,destination)
if isfile(source)
    ensure_directory(fileparts(destination));
    copyfile(source,destination,'f');
end
end


function ensure_directory(path)
if ~isfolder(path)
    [created,message] = mkdir(path);
    assert(created,'FullPaperRun:Directory', ...
        'Could not create %s: %s',path,message);
end
end


function write_json(path,value)
fid = fopen(path,'w');
assert(fid>=0,'FullPaperRun:JSON','Could not write %s.',path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));
end


function output = ternary(condition,true_value,false_value)
if condition
    output = true_value;
else
    output = false_value;
end
end
