function [pass,message,status_table] = assess_suite(suite_result, ...
        require_horizon)
ids = strings(numel(suite_result.outcomes),1);
run_dirs = strings(size(ids));
resumed = false(size(ids));
steady = false(size(ids));
transition = false(size(ids));
accounting = false(size(ids));
bargaining = false(size(ids));
horizon = false(size(ids));
for i = 1:numel(suite_result.outcomes)
    outcome = suite_result.outcomes{i};
    ids(i) = string(suite_result.scenarios{i}.scenario_id);
    run_dirs(i) = string(outcome.result.run_dir);
    resumed(i) = logical(outcome.resumed);
    steady(i) = logical(outcome.status.steady_state_solved);
    transition(i) = logical(outcome.status.transition_solved);
    accounting(i) = logical(outcome.status.accounting_pass);
    bargaining(i) = logical(outcome.status.bargaining_identity_pass);
    horizon(i) = logical(outcome.status.horizon_pass);
end
numerical = steady & transition & accounting & bargaining;
if require_horizon
    numerical = numerical & horizon;
end
status_table = table(ids,run_dirs,resumed,steady,transition, ...
    accounting,bargaining,horizon,numerical, ...
    'VariableNames',{'ScenarioID','RunDir','Resumed','SteadyStateSolved', ...
    'TransitionSolved','AccountingPass','BargainingIdentityPass', ...
    'HorizonPass','RequiredNumericalGatesPass'});
calibration_pass = logical( ...
    suite_result.wage_selection.target_pass) ...
    && logical(suite_result.immediate_separation_selection.target_pass);
pass = all(numerical) && calibration_pass;
if pass
    if require_horizon
        message = 'All required numerical, accounting, horizon, and calibration gates passed.';
    else
        message = ['All required numerical, accounting, and calibration gates passed. ' ...
            'Extended-horizon checks were not required in paper-output mode.'];
    end
else
    failed = cellstr(ids(~numerical));
    message = sprintf( ...
        'Required suite gates failed. Numerical scenarios: %s; calibration pass=%d.', ...
        strjoin(failed,', '),calibration_pass);
end
end


function outcome = outcome_by_id(suite_result,id)
ids = cellfun(@(x) char(string(x.scenario_id)), ...
    suite_result.scenarios,'UniformOutput',false);
index = find(strcmp(ids,id),1);
assert(~isempty(index),'FullPaperRun:ScenarioMissing', ...
    'Scenario %s is missing from the full run ledger.',id);
outcome = suite_result.outcomes{index};
end


function record = stage_record(pass,message,output_dir,resumed)
record = struct('status',char(string(ternary(pass,'pass','failed'))), ...
    'message',char(string(message)), ...
    'output_dir',char(string(output_dir)), ...
    'resumed',logical(resumed));
end


function pass = required_stages_pass(stages)
names = fieldnames(stages);
pass = true;
for i = 1:numel(names)
    status = char(string(stages.(names{i}).status));
    pass = pass && any(strcmp(status,{'pass','skipped'}));
end
end


