function result = run_paper_outputs(options)
% Compute the main-paper and online-appendix model outputs.

if nargin < 1 || isempty(options)
    options = struct();
end
code_dir = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(code_dir,'functions'));
options = full_run_options(options,code_dir);
assert_matlab_release(options);

run_root = fullfile(code_dir,'Results','full_paper_replication', ...
    options.run_id);
suite_dir = fullfile(run_root,'paper_replication_suite');
model_run_dir = fullfile(run_root,'model_runs');
paper_run_dir = fullfile(code_dir,'paper_outputs','Full_Runs', ...
    options.run_id);
report_dir = fullfile(paper_run_dir,'Run_Reports');
robustness_dir = fullfile(paper_run_dir,'Robustness');
if isfolder(run_root) && ~options.resume
    error('FullPaperRun:ExistingRun', ...
        ['Run %s already exists. Set resume_run_id to this identifier ' ...
         'in MAIN_REPLICATION.m to continue it.'],options.run_id);
end
ensure_directory(run_root);
ensure_directory(suite_dir);
ensure_directory(model_run_dir);
ensure_directory(paper_run_dir);
ensure_directory(report_dir);
ensure_directory(robustness_dir);

log_path = fullfile(run_root,'replication.log');
diary(log_path);
diary_cleanup = onCleanup(@() diary('off')); %#ok<NASGU>
started = datestr(now,30);
fprintf('\nFULL PAPER REPLICATION START %s\n',started);
fprintf('Run identifier: %s\n',options.run_id);
fprintf('Run root: %s\n',run_root);
fprintf('Paper output root: %s\n',paper_run_dir);
fprintf('MATLAB release: %s\n',version('-release'));
fprintf('Dynare command: %s\n',which('dynare'));

manifest = initial_manifest(options,code_dir,run_root,paper_run_dir,started);
manifest_path = fullfile(paper_run_dir,'full_run_manifest.json');
write_json(manifest_path,manifest);

suite_result = struct();
try
    complete_seed = seed_complete_insurance_checkpoint( ...
        options,code_dir,suite_dir,model_run_dir);
    manifest.complete_insurance_short_path = complete_seed;
    % The run root is new or explicitly selected above. Enable checkpoint
    % reads here so the just-seeded short-path result is consumed even on a
    % fresh full run; no checkpoint from another run can enter this tree.
    suite_options = struct( ...
        'output_dir',suite_dir, ...
        'result_parent_dir',model_run_dir, ...
        'short_result_parent_dir',fullfile( ...
            code_dir,'Results','pr',options.run_id), ...
        'paper_output_dir',paper_run_dir, ...
        'resume',true, ...
        'force',false, ...
        'reuse_existing_horizon_checkpoints', ...
            options.reuse_existing_horizon_checkpoints, ...
        'paper_outputs_only',options.paper_outputs_only, ...
        'main_paper_only',options.main_paper_only, ...
        'final_horizon_check',~options.paper_outputs_only);
    [~,suite_result] = run_paper_scenarios( ...
        0.001,suite_options);
    [suite_pass,suite_message,status_table] = ...
        assess_suite(suite_result,~options.paper_outputs_only);
    status_path = fullfile(report_dir,'scenario_status.csv');
    writetable(status_table,status_path);
    manifest.stages.paper_suite = stage_record( ...
        suite_pass,suite_message,suite_dir,false);
    if ~suite_pass
        error('FullPaperRun:SuiteGates','%s',suite_message);
    end
    baseline = outcome_by_id(suite_result,'preferred_baseline');
    generate_paper_baseline_outputs( ...
        char(baseline.result.run_dir),code_dir, ...
        options.figures_visible,paper_run_dir);
    % Figure 7 uses the horizon of its accepted source; other exhibits use 800.
    long_scenario = suite_result.scenarios{1};
    long_scenario.scenario_id = 'figure7_baseline';
    long_scenario.config.simulation_periods = 7000;
    long_scenario.config.horizon_check = false;
    long_scenario.config.result_parent_dir = fullfile(code_dir,'Results','f7',options.run_id);
    long_context = struct('output_dir',suite_dir,'resume',true,'force',false, ...
        'master_log_path',log_path,'cache_dir',fullfile(suite_dir,'steady_state_cache'), ...
        'scenario_mat_dir',fullfile(suite_dir,'scenario_mat'));
    long_outcome = run_scenario(long_scenario,long_context);
    assert(long_outcome.status.steady_state_solved ...
        && long_outcome.status.transition_solved ...
        && long_outcome.status.accounting_pass ...
        && long_outcome.status.bargaining_identity_pass, ...
        'PaperReplication:Figure7','The Figure 7 baseline did not solve.');
    figure7_dir = fullfile(run_root,'figure7');
    ensure_directory(fullfile(figure7_dir,'figures'));
    ensure_directory(fullfile(figure7_dir,'tables'));
    figure7 = write_current_calibration_exhibit( ...
        char(long_outcome.result.run_dir),figure7_dir,false);
    target = fullfile(paper_run_dir,'Figures', ...
        'Figure_2_Savings_And_Production_Unit_Labor_Costs_Only');
    copyfile(figure7.savings_ulc_only_png,[target '.png'],'f');
    copyfile(figure7.savings_ulc_only_eps,[target '.eps'],'f');
    copyfile(figure7.savings_ulc_only_fig,[target '.fig'],'f');
    fig = openfig([target '.fig'],'invisible');
    exportgraphics(fig,[target '.pdf'],'ContentType','vector'); close(fig);
    manifest.figure7 = struct('simulation_periods',7000, ...
        'run_dir',char(long_outcome.result.run_dir),'figure',target);
    baseline_manifest_path = fullfile(paper_run_dir,'baseline_output_manifest.json');
    baseline_manifest = jsondecode(fileread(baseline_manifest_path));
    baseline_manifest.figure7 = manifest.figure7;
    write_json(baseline_manifest_path,baseline_manifest);
    manifest.stages.figure7 = stage_record(true, ...
        'The 7,000-quarter baseline solved.',char(long_outcome.result.run_dir), ...
        long_outcome.resumed);
catch ME
    manifest.status = 'incomplete';
    manifest.stages.paper_suite = stage_record( ...
        false,getReport(ME,'basic','hyperlinks','off'),suite_dir,false);
    manifest.finished = datestr(now,30);
    write_json(manifest_path,manifest);
    write_failure_readme(paper_run_dir,manifest,ME);
    fprintf(2,'FULL PAPER REPLICATION STOPPED: %s\n',ME.message);
    rethrow(ME)
end

diary off
copyfile(log_path,fullfile(report_dir,'replication.log'),'f');
diary(log_path);
copy_if_present(fullfile(suite_dir, ...
    'requested_paper_robustness_manifest.json'), ...
    fullfile(report_dir,'requested_paper_robustness_manifest.json'));
write_bundle_readme(paper_run_dir,manifest,options);

[required_pass,missing] = required_artifact_check( ...
    paper_run_dir,options);
stages_pass = required_stages_pass(manifest.stages);
manifest.required_artifacts_pass = required_pass;
manifest.missing_required_artifacts = missing;
manifest.status = char(string( ...
    ternary(stages_pass && required_pass,'complete','incomplete')));
manifest.finished = datestr(now,30);
manifest.paper_output_dir = paper_run_dir;
write_json(manifest_path,manifest);

inventory_path = write_inventory(paper_run_dir);
manifest.sha256_inventory = inventory_path;
bundle_name = sprintf('Overleaf_Bundle_%s.zip',options.run_id);
if ~strcmp(manifest.status,'complete')
    bundle_name = sprintf('INCOMPLETE_Overleaf_Bundle_%s.zip', ...
        options.run_id);
end
bundle_path = fullfile(code_dir,'paper_outputs',bundle_name);
manifest.bundle_zip = bundle_path;
write_json(manifest_path,manifest);
zip_entries = {'Figures','Tables','Robustness','Run_Reports', ...
    'README.md','baseline_output_manifest.json', ...
    'robustness_output_manifest.json','full_run_manifest.json', ...
    'MANIFEST_SHA256.csv'};
zip(bundle_path,zip_entries,paper_run_dir);
manifest.bundle_sha256 = paper_bundle_sha256(bundle_path);
write_json(manifest_path,manifest);

fprintf('FULL PAPER REPLICATION END %s\n',manifest.finished);
fprintf('Status: %s\n',upper(manifest.status));
fprintf('Bundle: %s\n',bundle_path);
result = struct('status',manifest.status,'run_id',options.run_id, ...
    'run_root',run_root,'paper_output_dir',paper_run_dir, ...
    'bundle_zip',bundle_path,'manifest',manifest_path, ...
    'suite_result',suite_result);
if ~strcmp(manifest.status,'complete')
    error('FullPaperRun:Incomplete', ...
        ['The run finished with incomplete required stages or artifacts. ' ...
         'See %s.'],manifest_path);
end
end


function seed = seed_complete_insurance_checkpoint( ...
        options,code_dir,suite_dir,model_run_dir)
% Run the complete-insurance backend below a short Windows path, then seed
% the full suite with its ordinary fingerprinted checkpoint. This changes
% only the temporary execution location; configuration and reported result
% paths remain explicit in the checkpoint.
specification = model_parameters(0.001);
[registry,~] = paper_scenarios(specification);
index = find(strcmp({registry.scenario_id},'complete_insurance'),1);
assert(~isempty(index),'FullPaperRun:CompleteInsuranceRegistry', ...
    'The complete-insurance scenario is missing.');
scenario = registry(index);
scenario.config.horizon_check = ~options.paper_outputs_only ...
    || options.reuse_existing_horizon_checkpoints;
scenario.config.result_parent_dir = model_run_dir;

short_root = fullfile(code_dir,'Results','ci',options.run_id);
short_scenario_dir = fullfile(short_root,'scenario_mat');
short_log_dir = fullfile(short_root,'logs');
ensure_directory(short_scenario_dir);
ensure_directory(short_log_dir);
context = struct( ...
    'output_dir',short_root, ...
    'resume',options.resume, ...
    'force',false, ...
    'master_log_path',fullfile(short_log_dir, ...
        'complete_insurance_short_path.log'), ...
    'cache_dir',fullfile(short_root,'steady_state_cache'), ...
    'scenario_mat_dir',short_scenario_dir, ...
    'target_relative_employment_pct', ...
        specification.targets.relative_tn_employment_pct, ...
    'target_tolerance_pct', ...
        specification.targets.relative_tn_tolerance_pp, ...
    'identity_tolerance', ...
        specification.validation.bargaining_identity_tolerance);
outcome = run_scenario(scenario,context);
assert(logical(outcome.status.steady_state_solved) ...
        && logical(outcome.status.transition_solved) ...
        && logical(outcome.status.accounting_pass) ...
        && logical(outcome.status.bargaining_identity_pass) ...
        && (~scenario.config.horizon_check ...
            || logical(outcome.status.horizon_pass)), ...
    'FullPaperRun:CompleteInsuranceShortPath', ...
    'The short-path complete-insurance run failed a required gate.');

checkpoint_name = 'complete_insurance_complete_insurance.mat';
source_checkpoint = fullfile(short_scenario_dir,checkpoint_name);
target_scenario_dir = fullfile(suite_dir,'scenario_mat');
ensure_directory(target_scenario_dir);
target_checkpoint = fullfile(target_scenario_dir,checkpoint_name);
assert(isfile(source_checkpoint), ...
    'FullPaperRun:CompleteInsuranceCheckpoint', ...
    'The short-path run did not write %s.',source_checkpoint);
copyfile(source_checkpoint,target_checkpoint,'f');

include_path = fullfile(outcome.result.run_dir,'scratch', ...
    'model_equations_general_RA_corrected.m');
seed = struct( ...
    'status','pass', ...
    'reason','Dynare 5.4 Windows MAX_PATH workaround', ...
    'short_output_root',short_root, ...
    'run_dir',char(string(outcome.result.run_dir)), ...
    'include_path_length',strlength(string(include_path)), ...
    'checkpoint',target_checkpoint, ...
    'resumed',logical(outcome.resumed));
assert(seed.include_path_length < 260, ...
    'FullPaperRun:CompleteInsurancePathLength', ...
    'The short-path include still exceeds the Windows 260-character limit.');
end


function options = full_run_options(options,code_dir)
defaults = struct( ...
    'run_id','', ...
    'resume',false, ...
    'figures_visible',false, ...
    'main_paper_only',false, ...
    'paper_outputs_only',true, ...
    'reuse_existing_horizon_checkpoints',false, ...
    'publish_latest',false, ...
    'require_matlab_release',version('-release'));
names = fieldnames(defaults);
for i = 1:numel(names)
    if ~isfield(options,names{i}) || isempty(options.(names{i}))
        options.(names{i}) = defaults.(names{i});
    end
end
if isempty(options.run_id)
    options.run_id = ['full_' datestr(now,'yyyymmddTHHMMSS')];
end
options.run_id = regexprep(char(string(options.run_id)), ...
    '[^A-Za-z0-9_-]','_');
options.resume = logical(options.resume);
options.figures_visible = logical(options.figures_visible);
options.main_paper_only = logical(options.main_paper_only);
options.paper_outputs_only = logical(options.paper_outputs_only);
assert(~options.main_paper_only || options.paper_outputs_only, ...
    'FullPaperRun:MainPaperScope', ...
    'main_paper_only requires paper_outputs_only so no calibration search is launched.');
options.reuse_existing_horizon_checkpoints = logical( ...
    options.reuse_existing_horizon_checkpoints);
options.publish_latest = logical(options.publish_latest);
options.require_matlab_release = char(string( ...
    options.require_matlab_release));
options.code_dir = code_dir;
end


function assert_matlab_release(options)
actual = version('-release');
assert(strcmpi(actual,options.require_matlab_release), ...
    'FullPaperRun:MATLABRelease', ...
    'This workflow requires MATLAB %s; the active session is %s.', ...
    options.require_matlab_release,actual);
assert(~isempty(which('dynare')),'FullPaperRun:DynareMissing', ...
    'Dynare is not available on the active MATLAB path.');
end


