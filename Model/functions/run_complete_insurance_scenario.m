function outcome = run_complete_insurance_scenario(scenario,context)
% Solve complete insurance using the same calibration and SGU closure.
repo_root = fileparts(fileparts(mfilename('fullpath')));
scenario_id = scenario.scenario_id;
scenario_label = scenario.scenario_label;
configuration = scenario.config;
configuration.backend = 'complete';
if ~isfolder(context.scenario_mat_dir), mkdir(context.scenario_mat_dir); end
    [cache_key,~,~] = configuration_hash(configuration);
    checkpoint_path = fullfile(context.scenario_mat_dir, ...
        [scenario_id '_complete_insurance.mat']);
    if logical(field_or(context,'resume',true)) && isfile(checkpoint_path)
        saved = load(checkpoint_path,'outcome');
        if isfield(saved,'outcome') && isfield(saved.outcome,'status') ...
                && logical(field_or(saved.outcome.status, ...
                'transition_solved',false)) ...
                && isfolder(char(saved.outcome.result.run_dir))
            outcome = saved.outcome;
            outcome.resumed = true;
            fprintf('COMPLETE INSURANCE RESUME %s: %s\n', ...
                scenario_id,outcome.result.run_dir);
            return
        end
    end

    run_dir = fullfile(context.output_dir,'complete_insurance',scenario_id, ...
        ['corrected_' short_hash(cache_key)],'artifacts');
    ensure_folder(run_dir);
    started = datestr(now,30);
    model_result = run_complete_insurance_backend( ...
        configuration,run_dir,repo_root);
    status = struct('steady_state_solved', ...
        logical(model_result.steady_state_solved), ...
        'transition_solved',logical(model_result.transition_solved), ...
        'accounting_pass',logical(model_result.accounting_pass), ...
        'bargaining_identity_pass', ...
        logical(model_result.bargaining_identity_pass), ...
        'target_pass',logical(model_result.target_pass), ...
        'horizon_pass',logical(model_result.horizon_pass), ...
        'economic_validation_pass', ...
        logical(model_result.economic_validation_pass), ...
        'relative_employment_pct',NaN,'target_gap_pct',NaN, ...
        'message',model_result.message,'blocked',false, ...
        'phase','corrected_complete_insurance');
    outcome = struct('scenario_id',scenario_id, ...
        'scenario_label',scenario_label,'scenario',scenario, ...
        'configuration',configuration,'result',model_result, ...
        'status',status,'cache_key',cache_key,'cache_hit',false, ...
        'cache_path','','started',started,'finished',datestr(now,30), ...
        'resumed',false,'checkpoint_complete',model_result.complete, ...
        'checkpoint_path',checkpoint_path);
    save(checkpoint_path,'outcome','-v7.3');
    fprintf('COMPLETE INSURANCE END %s: %s\n',scenario_id,run_dir);

end

function ensure_folder(folder)
if ~isfolder(folder), mkdir(folder); end
end
function value = field_or(s,name,default)
value = default;
if isfield(s,name), value = s.(name); end
end
function value = short_hash(value)
value = char(string(value)); value = value(1:min(12,numel(value)));
end
