function diagnostics = validate_baseline_results(run_dir, terminal_tolerance, horizon_tolerance)
%VALIDATE_BASELINE_RESULTS Check interior convergence and home-NFA direction.

if nargin < 3
    horizon_tolerance = 1e-6;
end

names_data = load(fullfile(run_dir, 'Names.mat'));
pre_data = load(fullfile(run_dir, 'SS_init.mat'), 'SS_init');
post_data = load(fullfile(run_dir, 'SS_H42_EB.mat'), 'SS_H42_EB');
sim_data = load(fullfile(run_dir, 'Sim_H42_EB.mat'), 'Sim_H42_EB');
transition_names = load(fullfile(run_dir, 'Names_H42_EB.mat'), 'var_names');
transition_metadata = load(fullfile(run_dir, 'Names_H42_EB.mat'), ...
    'param_names', 'param_values');

pre_names = strtrim(cellstr(names_data.var_names));
post_names = strtrim(cellstr(transition_names.var_names));
pre_ss = pre_data.SS_init(:);
post_ss = post_data.SS_H42_EB(:);
sim = sim_data.Sim_H42_EB;

assert(size(sim, 2) >= 3, 'BaselineModel:ShortPath', ...
    'The transition output does not contain initial, simulated, and terminal columns.');
if ~isreal(pre_ss) || ~isreal(post_ss) || ~isreal(sim)
    error('BaselineModel:ComplexSavedResult', ...
        'A saved steady state or transition value is complex.');
end
if any(~isfinite(pre_ss)) || any(~isfinite(post_ss)) || any(~isfinite(sim(:)))
    error('BaselineModel:NonFiniteSavedResult', ...
        'A saved steady state or transition value is non-finite.');
end

nfa_pre_index = require_name(pre_names, 'NFA_a_t');
nfa_post_index = require_name(post_names, 'NFA_a_t');
nfa_path = sim(nfa_post_index, :);
T = size(sim, 2) - 2;
assert(T >= 160, 'BaselineModel:ShortPath', ...
    'The transition must contain at least 160 simulated periods.');

diagnostics.terminal_tolerance = terminal_tolerance;
diagnostics.horizon_tolerance = horizon_tolerance;
diagnostics.simulation_periods = T;
diagnostics.nfa_initial = nfa_path(1);
diagnostics.nfa_penultimate = nfa_path(end - 1);
diagnostics.nfa_terminal = post_ss(nfa_post_index);
diagnostics.nfa_change = diagnostics.nfa_penultimate - diagnostics.nfa_initial;

window_start = round(0.4 * T);
window_end = round(0.7 * T);
window_t = (window_start:window_end)';
window_path = nfa_path(window_t + 1);
window_path = window_path(:);
signed_gap = diagnostics.nfa_terminal - window_path;
gap = abs(signed_gap);
sign_flip = any(signed_gap == 0) || ...
    any(sign(signed_gap(1:end-1)) ~= sign(signed_gap(2:end)));

diagnostics.interior_window = [window_start, window_end];
diagnostics.interior_path_reached_terminal = sign_flip;
diagnostics.interior_gap_start = gap(1);
diagnostics.interior_gap_end = gap(end);
diagnostics.interior_gap_decrease_pass = gap(end) < gap(1);
if sign_flip
    diagnostics.rho_hat = NaN;
    diagnostics.rho_fit_r2 = NaN;
    diagnostics.interior_convergence_pass = true;
else
    design = [ones(numel(window_t), 1), window_t];
    log_gap = log(gap);
    coefficients = design \ log_gap;
    fitted = design * coefficients;
    residual_ss = sum((log_gap - fitted).^2);
    total_ss = sum((log_gap - mean(log_gap)).^2);
    if total_ss == 0
        diagnostics.rho_fit_r2 = double(residual_ss == 0);
    else
        diagnostics.rho_fit_r2 = 1 - residual_ss / total_ss;
    end
    diagnostics.rho_hat = exp(coefficients(2));
    diagnostics.interior_convergence_pass = all(gap > 0) ...
        && diagnostics.rho_hat > 0 && diagnostics.rho_hat < 1 ...
        && diagnostics.rho_fit_r2 >= 0.99 ...
        && diagnostics.interior_gap_decrease_pass;
end

diagnostics.nfa_change_160 = nfa_path(161) - diagnostics.nfa_initial;
diagnostics.nfa_change_160_pass = diagnostics.nfa_change_160 > 0;
peak_start = 40;
peak_end = window_end;
[peak_value, peak_index] = max(nfa_path(peak_start + 1:peak_end + 1));
diagnostics.nfa_peak_change = peak_value - diagnostics.nfa_initial;
diagnostics.nfa_peak_period = peak_start + peak_index - 1;
diagnostics.nfa_peak_change_pass = diagnostics.nfa_peak_change > 0;
diagnostics.nfa_direction_pass = diagnostics.nfa_change_160_pass ...
    && diagnostics.nfa_peak_change_pass;

early_end = min(40, T);
[early_minimum, early_index] = min(nfa_path(2:early_end + 1));
diagnostics.nfa_early_minimum_change = early_minimum - diagnostics.nfa_initial;
diagnostics.nfa_early_minimum_period = early_index;

[~, turn_index] = max(nfa_path(2:T + 1));
diagnostics.nfa_turn_period = turn_index;
diagnostics.boundary_layer_pass = diagnostics.nfa_turn_period > window_end;

penultimate = sim(:, end - 1);
terminal_scale = 1 + abs(post_ss);
diagnostics.max_absolute_terminal_gap = max(abs(penultimate - post_ss));
diagnostics.scaled_terminal_gap = max(abs(penultimate - post_ss) ./ terminal_scale);

ce_pre = pre_ss(require_name(pre_names, 'Ce_a_t'));
ceu1_pre = pre_ss(require_name(pre_names, 'Ceu1_a_t'));
ce_post = post_ss(require_name(post_names, 'Ce_a_t'));
ceu1_post = post_ss(require_name(post_names, 'Ceu1_a_t'));
diagnostics.pre_existence_gap = ce_pre - ceu1_pre;
diagnostics.post_existence_gap = ce_post - ceu1_post;
diagnostics.existence_pass = diagnostics.pre_existence_gap > 0 ...
    && diagnostics.post_existence_gap > 0;
diagnostics.accounting = audit_repaired_accounting(sim, post_names, ...
    transition_metadata.param_values, transition_metadata.param_names);
raw_tradable_max = max([abs(diagnostics.accounting.goods_T_a), ...
    abs(diagnostics.accounting.goods_T_b)]);
if ~diagnostics.accounting.exact_gate_pass
    diagnostics.walras_closure_status = 'FAIL';
elseif raw_tradable_max > diagnostics.accounting.exact_reconciliation_tolerance
    diagnostics.walras_closure_status = 'PARTIAL PASS';
else
    diagnostics.walras_closure_status = 'PASS';
end

v = @(name, columns) sim(require_name(post_names,name),columns);
q1_4 = 2:5;
q1_40 = 2:41;
q5_40 = 6:41;
pct = @(name,columns) 100*(v(name,columns)/v(name,1)-1);
sector_metrics = sector_response_metrics(sim,post_names);
diagnostics.sector = sector_metrics.summary;
diagnostics.sector.private_value_demand_report_label = ...
    sector_metrics.private_value_demand_report_label;
diagnostics.sector.private_value_demand_definition = ...
    sector_metrics.private_value_demand_definition;
diagnostics.sector.production_measure = sector_metrics.production_measure;
diagnostics.sector.value_output_definition = ...
    sector_metrics.value_output_definition;
diagnostics.sector.nt_impact_pct = diagnostics.sector.NT_a_impact_pct;
diagnostics.sector.nn_impact_pct = diagnostics.sector.NN_a_impact_pct;
diagnostics.sector.n_impact_pct = pct('N_a_t',2);
diagnostics.sector.nt_q1_40_avg_pct = diagnostics.sector.NT_a_q1_40_avg_pct;
diagnostics.sector.nn_q1_40_avg_pct = diagnostics.sector.NN_a_q1_40_avg_pct;
recruiting_moments = recruiting_transition_moments(sim,post_names);
assert(abs(diagnostics.sector.nt_q1_40_avg_pct ...
        -recruiting_moments.tradable_q1_40_avg_pct) <= 1e-10 ...
    && abs(diagnostics.sector.nn_q1_40_avg_pct ...
        -recruiting_moments.nontradable_q1_40_avg_pct) <= 1e-10, ...
    'RecruitingCosts:SectorMomentMismatch', ...
    'Sector-response and recruiting-comparison component moments disagree.');
diagnostics.sector.rel_emp_a_q1_40_avg_pct = ...
    recruiting_moments.relative_q1_40_avg_pct;
diagnostics.sector.relative_employment_definition = recruiting_moments.definition;
diagnostics.sector.n_q1_40_avg_pct = mean(pct('N_a_t',q1_40));
diagnostics.sector.weighted_n_q1_40_avg_pct = ...
    v('NT_a_t',1)/v('N_a_t',1)*diagnostics.sector.nt_q1_40_avg_pct ...
    +v('NN_a_t',1)/v('N_a_t',1)*diagnostics.sector.nn_q1_40_avg_pct;
diagnostics.sector.aggregate_reconciliation_gap = ...
    diagnostics.sector.n_q1_40_avg_pct-diagnostics.sector.weighted_n_q1_40_avg_pct;
diagnostics.sector.target_distance = abs( ...
    diagnostics.sector.rel_emp_a_q1_40_avg_pct-2.7);
diagnostics.sector.rer_cpi_impact_pct = pct('rer_cpi_t',2);
diagnostics.sector.rer_cpi_q1_4_avg_pct = mean(pct('rer_cpi_t',q1_4));
diagnostics.sector.rer_cpi_q1_40_avg_pct = mean(pct('rer_cpi_t',q1_40));
diagnostics.sector.rel_pT_impact_pct = pct('rel_pT_t',2);
diagnostics.sector.rel_pT_q1_4_avg_pct = mean(pct('rel_pT_t',q1_4));
diagnostics.sector.rel_pT_q1_40_avg_pct = mean(pct('rel_pT_t',q1_40));
diagnostics.sector.export_volume_impact_pct = pct('EXVOL_a_t',2);
diagnostics.sector.export_volume_q4_pct = pct('EXVOL_a_t',5);
diagnostics.sector.export_volume_q5_40_avg_pct = mean(pct('EXVOL_a_t',q5_40));
diagnostics.sector.export_volume_q1_40_avg_pct = mean(pct('EXVOL_a_t',q1_40));
diagnostics.sector.nx_impact_pct_annual_output = 100*v('NX_a_t',2)/(4*v('Y_a_t',1));
diagnostics.sector.ca_impact_pct_annual_output = 100*v('CA_a_t',2)/(4*v('Y_a_t',1));
diagnostics.sector.ca_nx_impact_gap = v('CA_a_t',2)-v('NX_a_t',2);
diagnostics.sector.employment_reallocation_pass = ...
    diagnostics.sector.rel_emp_a_q1_40_avg_pct > 0 ...
    && diagnostics.sector.nt_q1_40_avg_pct > ...
       diagnostics.sector.nn_q1_40_avg_pct;
diagnostics.sector.external_adjustment_pass = ...
    diagnostics.sector.rer_cpi_q1_40_avg_pct < 0 ...
    && diagnostics.sector.export_volume_q5_40_avg_pct > 0 ...
    && diagnostics.sector.nx_impact_pct_annual_output > 0 ...
    && diagnostics.sector.ca_impact_pct_annual_output > 0 ...
    && abs(diagnostics.sector.ca_nx_impact_gap) <= 1e-10;
positive_names = {'NT_a_t','NN_a_t','VT_a_t','VN_a_t','KTuse_a_t','KNuse_a_t', ...
    'YT_a_t','YN_a_t','qT_a_t','qN_a_t', ...
    'NT_b_t','NN_b_t','VT_b_t','VN_b_t','KTuse_b_t','KNuse_b_t', ...
    'YT_b_t','YN_b_t','qT_b_t','qN_b_t', ...
    'C_a_t','C_b_t','pH_t','pF_t','pN_a_t','pN_b_t'};
diagnostics.sector.minimum_level = Inf;
diagnostics.sector.minimum_level_name = '';
for positive_index = 1:numel(positive_names)
    candidate_minimum = min(v(positive_names{positive_index},1:size(sim,2)-1));
    if candidate_minimum < diagnostics.sector.minimum_level
        diagnostics.sector.minimum_level = candidate_minimum;
        diagnostics.sector.minimum_level_name = positive_names{positive_index};
    end
end
diagnostics.sector.positivity_pass = diagnostics.sector.minimum_level > 0;
diagnostics.sector.signs_pass = ...
    diagnostics.sector.employment_reallocation_pass ...
    && diagnostics.sector.external_adjustment_pass;
diagnostics.accounting.cohort_csv_home = fullfile(run_dir, ...
    'cohort_accounting_home.csv');
diagnostics.accounting.cohort_csv_foreign = fullfile(run_dir, ...
    'cohort_accounting_foreign.csv');
writetable(cohort_table(diagnostics.accounting.cohort_a), ...
    diagnostics.accounting.cohort_csv_home);
writetable(cohort_table(diagnostics.accounting.cohort_b), ...
    diagnostics.accounting.cohort_csv_foreign);
diagnostics.accounting.sectoral_goods_markets_csv = fullfile(run_dir, ...
    'sectoral_goods_markets.csv');
diagnostics.accounting.walras_reconciliation_csv = fullfile(run_dir, ...
    'walras_reconciliation.csv');
diagnostics.accounting.foreign_nfa_valuation_csv = fullfile(run_dir, ...
    'foreign_nfa_valuation.csv');
writetable(sectoral_goods_markets_table(diagnostics.accounting), ...
    diagnostics.accounting.sectoral_goods_markets_csv);
writetable(walras_reconciliation_table(diagnostics.accounting), ...
    diagnostics.accounting.walras_reconciliation_csv);
writetable(foreign_nfa_valuation_table(diagnostics.accounting), ...
    diagnostics.accounting.foreign_nfa_valuation_csv);

fprintf('\nBaseline Validation\n');
fprintf('  Walras closure classification: %s\n', ...
    diagnostics.walras_closure_status);
fprintf('  Gate 1 interior window: [%d, %d]\n', window_start, window_end);
fprintf('  Gate 1 rho_hat: %.12g, fit R^2: %.12g\n', ...
    diagnostics.rho_hat, diagnostics.rho_fit_r2);
fprintf('  Gate 1 gap: %.12g -> %.12g, reached terminal: %d\n', ...
    diagnostics.interior_gap_start, diagnostics.interior_gap_end, ...
    diagnostics.interior_path_reached_terminal);
fprintf('  Gate 2 NFA_a change at t=160: %.12g\n', diagnostics.nfa_change_160);
fprintf('  Gate 2 NFA_a peak change through t=%d: %.12g at t=%d\n', ...
    peak_end, diagnostics.nfa_peak_change, diagnostics.nfa_peak_period);
fprintf('  Early NFA_a minimum change: %.12g at t=%d\n', ...
    diagnostics.nfa_early_minimum_change, diagnostics.nfa_early_minimum_period);
fprintf('  Gate 3 NFA_a turn: t=%d (must exceed %d)\n', ...
    diagnostics.nfa_turn_period, window_end);
fprintf('  Truncation boundary artifact, scaled penultimate gap: %.12g\n', ...
    diagnostics.scaled_terminal_gap);
fprintf('  Gate 5 maximum repaired-identity residual: %.12g (%s)\n', ...
    diagnostics.accounting.max_identity_residual, diagnostics.accounting.max_identity_name);
fprintf('  Recruiting filled-job recursion maximum: %.12g\n', ...
    diagnostics.accounting.max_job_value_residual);
fprintf('  Recruiting vacancy-FOC maximum: %.12g\n', ...
    diagnostics.accounting.max_sectoral_vacancy_foc_residual);
fprintf('  Recruiting resource maximum: %.12g\n', ...
    diagnostics.accounting.max_recruiting_cost_residual);
fprintf('  Employment-flow maximum: %.12g\n', ...
    diagnostics.accounting.max_employment_flow_residual);
fprintf('  Raw Home frozen-cohort term, maximum q1-40: %.12g bp of output\n', ...
    diagnostics.accounting.raw_term_q1_40_max_bps_a);
fprintf('  Raw Foreign frozen-cohort term, maximum q1-40: %.12g bp of output\n', ...
    diagnostics.accounting.raw_term_q1_40_max_bps_b);
fprintf('  Impact frozen-stock change, Home/Foreign: %.12g / %.12g bp of output\n', ...
    diagnostics.accounting.impact_frozen_stock_change_bps_a, ...
    diagnostics.accounting.impact_frozen_stock_change_bps_b);
fprintf('  Impact tax-holding-account change, Home/Foreign: %.12g / %.12g bp of output\n', ...
    diagnostics.accounting.impact_tax_holding_change_bps_a, ...
    diagnostics.accounting.impact_tax_holding_change_bps_b);
fprintf('  Gate 6 raw-flow reconciliation maximum: %.12g\n', ...
    diagnostics.accounting.max_raw_flow_reconciliation_error);
fprintf('  Gate 6 frozen-stock-law maximum: %.12g\n', ...
    diagnostics.accounting.max_frozen_stock_law_error);
fprintf('  Gate 6 augmented residual maximum: %.12g\n', ...
    diagnostics.accounting.max_augmented_resource_residual);
fprintf('  Home NFA-flow identity maximum: %.12g of output\n', ...
    diagnostics.accounting.max_home_nfa_flow_identity);
fprintf('  Foreign NFA-valuation identity maximum: %.12g of output\n', ...
    diagnostics.accounting.max_foreign_nfa_valuation_identity);
fprintf('  Adjusted Walras reconciliation maximum: %.12g of output\n', ...
    diagnostics.accounting.max_walras_reconciliation);
fprintf('  Raw tradable residual impact, Home/Foreign: %.12g / %.12g bp of aggregate output\n', ...
    diagnostics.accounting.raw_tradable_a.impact_bps_aggregate_output, ...
    diagnostics.accounting.raw_tradable_b.impact_bps_aggregate_output);
fprintf('  Raw tradable residual maximum q1-40, Home/Foreign: %.12g / %.12g bp of aggregate output\n', ...
    diagnostics.accounting.raw_tradable_a.q1_40_max_abs_bps_aggregate_output, ...
    diagnostics.accounting.raw_tradable_b.q1_40_max_abs_bps_aggregate_output);
fprintf('  Raw tradable residual maximum full valid path, Home/Foreign: %.12g / %.12g bp of aggregate output\n', ...
    diagnostics.accounting.raw_tradable_a.full_valid_max_abs_bps_aggregate_output, ...
    diagnostics.accounting.raw_tradable_b.full_valid_max_abs_bps_aggregate_output);
fprintf('  Terminal endval boundary stock-law error, Home/Foreign: %.12g / %.12g (reported, not gated)\n', ...
    diagnostics.accounting.terminal_boundary_stock_law_error_a, ...
    diagnostics.accounting.terminal_boundary_stock_law_error_b);
fprintf('  Gate 6 exact tolerance: %.12g; passed: %d\n', ...
    diagnostics.accounting.exact_reconciliation_tolerance, ...
    diagnostics.accounting.exact_gate_pass);
fprintf('  Home investment: impact %.6f%%, q1-40 average %.6f%%, terminal %.6f%%\n', ...
    diagnostics.accounting.home_investment_impact_pct, ...
    diagnostics.accounting.home_investment_q1_40_avg_pct, ...
    diagnostics.accounting.home_investment_terminal_pct);
fprintf('  Home CA q1-40 average: %.6f%% annual output; NFA q40 change: %.6f%% annual output\n', ...
    diagnostics.accounting.home_ca_q1_40_avg_pct_annual_output, ...
    diagnostics.accounting.home_nfa_q40_change_pct_annual_output);
fprintf('  Sector q1-40 averages: NT %.6f%%, NN %.6f%%, relative employment %.6f%%; target distance %.6f\n', ...
    diagnostics.sector.nt_q1_40_avg_pct,diagnostics.sector.nn_q1_40_avg_pct, ...
    diagnostics.sector.rel_emp_a_q1_40_avg_pct,diagnostics.sector.target_distance);
fprintf('  CPI RER impact / q1-4 / q1-40: %.6f%% / %.6f%% / %.6f%%\n', ...
    diagnostics.sector.rer_cpi_impact_pct,diagnostics.sector.rer_cpi_q1_4_avg_pct, ...
    diagnostics.sector.rer_cpi_q1_40_avg_pct);
fprintf('  rel pT impact / q1-4 / q1-40: %.6f%% / %.6f%% / %.6f%%\n', ...
    diagnostics.sector.rel_pT_impact_pct,diagnostics.sector.rel_pT_q1_4_avg_pct, ...
    diagnostics.sector.rel_pT_q1_40_avg_pct);
fprintf('  Export volume impact / q4 / q5-40 / q1-40: %.6f%% / %.6f%% / %.6f%% / %.6f%%\n', ...
    diagnostics.sector.export_volume_impact_pct,diagnostics.sector.export_volume_q4_pct, ...
    diagnostics.sector.export_volume_q5_40_avg_pct, ...
    diagnostics.sector.export_volume_q1_40_avg_pct);
fprintf('  External impact: NX %.6f%% annual output, CA %.6f%% annual output\n', ...
    diagnostics.sector.nx_impact_pct_annual_output,diagnostics.sector.ca_impact_pct_annual_output);

diagnostics.failure_messages = {};
if ~diagnostics.interior_convergence_pass
    diagnostics.failure_messages{end+1} = sprintf([ ...
        'Gate 1 interior convergence failed: rho_hat=%.12g, R^2=%.12g, ' ...
        'gap %.12g to %.12g over [%d, %d].'], ...
        diagnostics.rho_hat, diagnostics.rho_fit_r2, ...
        diagnostics.interior_gap_start, diagnostics.interior_gap_end, ...
        window_start, window_end);
end
if ~diagnostics.nfa_direction_pass
    diagnostics.failure_messages{end+1} = sprintf([ ...
        'Gate 2 NFA direction failed: change at t=160 is %.12g and ' ...
        'peak change through t=%d is %.12g at t=%d.'], ...
        diagnostics.nfa_change_160, peak_end, diagnostics.nfa_peak_change, ...
        diagnostics.nfa_peak_period);
end
if ~diagnostics.boundary_layer_pass
    diagnostics.failure_messages{end+1} = sprintf([ ...
        'Gate 3 boundary localization failed: t_turn=%d, required t_turn>%d.'], ...
        diagnostics.nfa_turn_period, window_end);
end
if ~diagnostics.existence_pass
    diagnostics.failure_messages{end+1} = sprintf([ ...
        'Consumption existence gate failed: pre gap=%.12g, post gap=%.12g.'], ...
        diagnostics.pre_existence_gap, diagnostics.post_existence_gap);
end
if ~diagnostics.accounting.identity_pass
    diagnostics.failure_messages{end+1} = sprintf([ ...
        'Gate 5 repaired accounting failed: maximum identity residual %.12g ' ...
        'in %s exceeds %.12g.'], diagnostics.accounting.max_identity_residual, ...
        diagnostics.accounting.max_identity_name, diagnostics.accounting.identity_tolerance);
end
if ~diagnostics.accounting.job_value_gate_pass
    diagnostics.failure_messages{end+1} = sprintf( ...
        'Filled-job recursion residual %.12g exceeds its recruiting-cost tolerance.', ...
        diagnostics.accounting.max_job_value_residual);
end
if ~diagnostics.accounting.sectoral_vacancy_foc_gate_pass
    diagnostics.failure_messages{end+1} = sprintf( ...
        'Vacancy-FOC residual %.12g exceeds its recruiting-cost tolerance.', ...
        diagnostics.accounting.max_sectoral_vacancy_foc_residual);
end
if ~diagnostics.accounting.recruiting_cost_gate_pass
    diagnostics.failure_messages{end+1} = sprintf( ...
        'Recruiting-resource residual %.12g exceeds its recruiting-cost tolerance.', ...
        diagnostics.accounting.max_recruiting_cost_residual);
end
if ~diagnostics.accounting.employment_flow_gate_pass
    diagnostics.failure_messages{end+1} = sprintf( ...
        'Employment-flow residual %.12g exceeds its recruiting-cost tolerance.', ...
        diagnostics.accounting.max_employment_flow_residual);
end
if ~diagnostics.accounting.exact_gate_pass
    diagnostics.failure_messages{end+1} = sprintf([ ...
        'Gate 6 exact frozen-cohort reconciliation failed: augmented %.12g, ' ...
        'raw-flow error %.12g, stock-law error %.12g, Home NFA flow %.12g, ' ...
        'Foreign valuation %.12g, adjusted Walras %.12g; tolerance %.12g.'], ...
        diagnostics.accounting.max_augmented_resource_residual, ...
        diagnostics.accounting.max_raw_flow_reconciliation_error, ...
        diagnostics.accounting.max_frozen_stock_law_error, ...
        diagnostics.accounting.max_home_nfa_flow_identity, ...
        diagnostics.accounting.max_foreign_nfa_valuation_identity, ...
        diagnostics.accounting.max_walras_reconciliation, ...
        diagnostics.accounting.exact_reconciliation_tolerance);
end
if ~diagnostics.sector.positivity_pass
    diagnostics.failure_messages{end+1} = sprintf( ...
        'Sector positivity failed: minimum %.12g for %s.', ...
        diagnostics.sector.minimum_level,diagnostics.sector.minimum_level_name);
end
if ~diagnostics.sector.signs_pass
    diagnostics.failure_messages{end+1} = sprintf([ ...
        'Employment/external gate failed: relative employment q1-40 %.12g, ' ...
        'NT q1-40 %.12g, NN q1-40 %.12g, CPI RER q1-40 %.12g, ' ...
        'export volume q5-40 %.12g, NX impact %.12g, CA impact %.12g, ' ...
        'CA-NX gap %.12g. rel pT impact %.12g and export impact %.12g ' ...
        'are diagnostics only.'], ...
        diagnostics.sector.rel_emp_a_q1_40_avg_pct, ...
        diagnostics.sector.nt_q1_40_avg_pct,diagnostics.sector.nn_q1_40_avg_pct, ...
        diagnostics.sector.rer_cpi_q1_40_avg_pct, ...
        diagnostics.sector.export_volume_q5_40_avg_pct, ...
        diagnostics.sector.nx_impact_pct_annual_output, ...
        diagnostics.sector.ca_impact_pct_annual_output,diagnostics.sector.ca_nx_impact_gap, ...
        diagnostics.sector.rel_pT_impact_pct,diagnostics.sector.export_volume_impact_pct);
end
