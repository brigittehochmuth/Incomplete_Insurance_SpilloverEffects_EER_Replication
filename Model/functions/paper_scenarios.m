function [registry,metadata] = paper_scenarios(specification)
% Scenarios used in the main paper and online appendix.

if nargin < 1 || isempty(specification)
    specification = model_parameters();
end
base = specification.baseline;
targets = specification.targets;
modes = specification.modes;
registry = repmat(empty_entry(),0,1);

preferred = set_mode(base,modes.STU1,'STU1',1.0);
registry(end+1) = make_entry('preferred_baseline', ...
    'Maintained Baseline: STU1','maintained_baseline','none','','',{}, ...
    preferred,NaN,NaN,NaN,targets.relative_tn_employment_pct, ...
    targets.relative_tn_tolerance_pp,true); %#ok<AGROW>

all_u_fixed = set_mode(base,modes.ALL_UNEMPLOYED,'ALL_UNEMPLOYED',1.0);
registry(end+1) = make_entry('all_unemployed_fixed', ...
    'All-Unemployed: Fixed Parameters','bargaining_fixed','none','','', ...
    {'bargaining_mode'},all_u_fixed,NaN,NaN,NaN,NaN,NaN,true); %#ok<AGROW>

labor_force_fixed = set_mode(base,modes.LABOR_FORCE_WEIGHTED, ...
    'LABOR_FORCE_WEIGHTED',1.0);
registry(end+1) = make_entry('labor_force_weighted_fixed', ...
    'Labor-Force-Weighted Collective Bargaining', ...
    'bargaining_fixed','none','','',{'bargaining_mode'}, ...
    labor_force_fixed,NaN,NaN,NaN,NaN,NaN,true); %#ok<AGROW>

low_zeta = set_all_zeta(preferred,0.40);
registry(end+1) = make_entry('zeta_low_040','Worker Bargaining Power 0.40', ...
    'bargaining_power','none','', ...
    '', ...
    {'zeta_pre','zeta_post','reform_cut'},low_zeta, ...
    base.reform_cut,0.05,0.60,targets.relative_tn_employment_pct, ...
    targets.relative_tn_tolerance_pp,true); %#ok<AGROW>
high_zeta = set_all_zeta(preferred,0.60);
registry(end+1) = make_entry('zeta_high_060','Worker Bargaining Power 0.60', ...
    'bargaining_power','none','', ...
    '', ...
    {'zeta_pre','zeta_post','reform_cut'},high_zeta, ...
    base.reform_cut,0.05,0.60,targets.relative_tn_employment_pct, ...
    targets.relative_tn_tolerance_pp,true); %#ok<AGROW>

comparison = specification.insurance_comparison;
complete = set_mode(preferred,modes.STU1,'STU1',1.0);
complete.backend = 'complete';
complete.complete_insurance_sgu = comparison.sgu;
complete.complete_calibration_parameters = ...
    comparison.complete_calibration_parameters;
registry(end+1) = make_entry('complete_insurance', ...
    'Complete Insurance','section_6_6', ...
    'none','','',{'backend','complete_insurance_sgu', ...
    'complete_calibration_parameters'},complete, ...
    NaN,NaN,NaN,NaN,NaN,true); %#ok<AGROW>

incomplete_sgu = set_mode(preferred,modes.STU1,'STU1',1.0);
incomplete_sgu.nfa_sgu = comparison.sgu;
incomplete_sgu.continuation_schedule = [0 0.125 0.25 0.50 0.75 1.0];
registry(end+1) = make_entry('incomplete_insurance_sgu', ...
    'Incomplete Insurance','section_6_6', ...
    'none','','',{'nfa_sgu','continuation_schedule'},incomplete_sgu, ...
    NaN,NaN,NaN,NaN,NaN,true); %#ok<AGROW>

full_reform = preferred;
registry(end+1) = make_entry('full_reform','Full Reform', ...
    'section_6_6','none','','',{},full_reform,NaN,NaN,NaN,NaN,NaN,true); %#ok<AGROW>

entitlement_only = preferred;
entitlement_only.reform_cut = 0.0;
entitlement_only.apply_replacement_cut = false;
entitlement_only.apply_entitlement_cut = true;
registry(end+1) = make_entry('entitlement_only', ...
    'Entitlement-Duration Cut Only','section_6_6','none','','', ...
    {'reform_cut','apply_replacement_cut'},entitlement_only, ...
    NaN,NaN,NaN,NaN,NaN,true); %#ok<AGROW>

separation_immediate = preferred;
separation_immediate.separation_multiplier_a = 0.78;
separation_immediate.separation_transition_start_quarter = 0;
separation_immediate.separation_transition_full_effect_quarter = 0;
separation_immediate.reform_cut = 0.40296486910722984;
registry(end+1) = make_entry('separation_decline', ...
    'Immediate Separation Decline','section_6_6','none','','', ...
    {'separation_multiplier_a','separation_transition_start_quarter', ...
    'separation_transition_full_effect_quarter','reform_cut'}, ...
    separation_immediate,NaN,NaN,NaN,targets.relative_tn_employment_pct, ...
    targets.relative_tn_tolerance_pp,true);

foreign_ui = preferred;
foreign_ui.rrs_b = 0.45;
foreign_ui.rrl_b = 0.40;
registry(end+1) = make_entry('asymmetric_foreign_ui', ...
    'Asymmetric Foreign UI: Short 0.45 And Long 0.40','section_6_6', ...
    'none','','',{'rrs_b','rrl_b'},foreign_ui, ...
    NaN,NaN,NaN,NaN,NaN,true); %#ok<AGROW>

labor_tax = preferred;
labor_tax.labor_tax_closure = true;
registry(end+1) = make_entry('labor_tax_closure', ...
    'Labor-Tax Fiscal Closure With Lump-Sum Taxes Fixed','section_6_6', ...
    'none','','',{'labor_tax_closure'},labor_tax, ...
    NaN,NaN,NaN,NaN,NaN,true); %#ok<AGROW>

wage_moderation = preferred;
wage_moderation.reform_cut = 0.0;
wage_moderation.entitlement_cut_periods = 0;
wage_moderation.apply_replacement_cut = false;
wage_moderation.apply_entitlement_cut = false;
wage_moderation.bargaining_power_pre_a = base.bargaining_power;
wage_moderation.bargaining_power_post_a = 0.2848786961505812;
wage_moderation.bargaining_power_pre_b = base.bargaining_power;
wage_moderation.bargaining_power_post_b = base.bargaining_power;
registry(end+1) = make_entry('wage_moderation_post_only', ...
    'Wage Moderation: Permanent Post-Reform Bargaining-Power Decline', ...
    'section_6_7','zeta_to_unemployment','bargaining_power_post_a', ...
    'home_unemployment_q1_40_to_preferred_ui', ...
    {'reform_cut','entitlement_cut_periods','apply_replacement_cut', ...
    'apply_entitlement_cut','bargaining_power_post_a'},wage_moderation, ...
    0.45,0.05,base.bargaining_power,NaN,0.01,true); %#ok<AGROW>

metadata = struct('preferred_mode','STU1','fixed_published_parameters',true);

end


function entry = empty_entry()
entry = struct('scenario_id','','scenario_label','','panel','','backend','', ...
    'base_scenario_id','', ...
    'calibration_policy','', ...
    'calibration_parameter','','calibration_target','', ...
    'declared_changes',{{}},'calibration_initial_value',NaN, ...
    'calibration_lower_bound',NaN,'calibration_upper_bound',NaN, ...
    'target_value',NaN,'target_tolerance_pp',NaN,'paper_facing',false, ...
    'config',struct());
end


function entry = make_entry(id,label,group,policy,parameter,target,changes, ...
        config,initial_value,lower_bound,upper_bound,target_value,tolerance, ...
        paper_facing)
entry = empty_entry();
entry.scenario_id = id;
entry.scenario_label = label;
entry.panel = group;
entry.backend = config.backend;
entry.calibration_policy = policy;
entry.calibration_parameter = parameter;
entry.calibration_target = target;
entry.declared_changes = changes;
entry.calibration_initial_value = initial_value;
entry.calibration_lower_bound = lower_bound;
entry.calibration_upper_bound = upper_bound;
entry.target_value = target_value;
entry.target_tolerance_pp = tolerance;
entry.paper_facing = paper_facing;
entry.config = config;
end


function config = set_mode(config,mode,name,continuation_weight)
config.bargaining_mode = mode;
config.bargaining_mode_a = mode;
config.bargaining_mode_b = mode;
config.bargaining_mode_name_a = name;
config.bargaining_mode_name_b = name;
config.bargaining_continuation_weight = continuation_weight;
config.bargaining_continuation_weight_a = continuation_weight;
config.bargaining_continuation_weight_b = continuation_weight;
end


function config = set_all_zeta(config,value)
config.bargaining_power = value;
config.bargaining_power_pre_a = value;
config.bargaining_power_post_a = value;
config.bargaining_power_pre_b = value;
config.bargaining_power_post_b = value;
end


