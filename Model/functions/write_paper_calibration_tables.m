function output = write_paper_calibration_tables(run_dir,table_dir)
%WRITE_PAPER_CALIBRATION_TABLES Paper-ready calibration inputs from a solved run.
%   The parameter values are read from the saved pre-reform calibration.
%   The two transition targets are paired with their achieved q1-q40 values
%   in the CSV audit file; the TeX table reports the paper's target values.

arguments
    run_dir (1,:) char
    table_dir (1,:) char
end

if ~isfolder(table_dir), mkdir(table_dir); end
parameter_path = fullfile(run_dir,'Param_init.mat');
map_path = fullfile(run_dir,'Param_init.mod');
metadata_path = fullfile(run_dir,'run_metadata.mat');
assert(isfile(parameter_path) && isfile(map_path) && isfile(metadata_path), ...
    'PaperCalibration:MissingRunArtifact', ...
    'The saved baseline run is missing Param_init or run_metadata artifacts.');

loaded_parameters = load(parameter_path,'Param_init');
Param_init = loaded_parameters.Param_init; %#ok<NASGU>
eval(fileread(map_path)); %#ok<EVLDIR>
loaded_metadata = load(metadata_path,'result');
result = loaded_metadata.result;
configuration = result.configuration;

foreign_home_bias = 1-hb1_b;
parameter_rows = { ...
    'Country Size','$rs$',size_a,1-size_a,'externally_set'; ...
    'Discount Factor','$\beta$',betta_a,betta_b,'home_set_foreign_internal'; ...
    'Risk Aversion','$\sigma_c$',sigmac,sigmac,'externally_set'; ...
    'Home Bias','$\gamma^C$',hb1_a,foreign_home_bias,'home_set_foreign_internal'; ...
    'EOS, Home and Foreign Goods','$\eta^C$',eta_c,eta_c,'externally_set'; ...
    'EOS, Tradable and Non-Tradable Goods','$\phi^T$',phi_t,phi_t,'externally_set'; ...
    'Share of Tradables in Consumption','$\alpha^T$',alpha_a_t,alpha_b_t,'externally_set'; ...
    'Matching Elasticity','$\eta$',alphaa_a,alphaa_b,'externally_set'; ...
    'Workers'' Bargaining Power','$\zeta$',configuration.bargaining_power_pre_a,configuration.bargaining_power_pre_b,'externally_set'; ...
    'Recruiting Curvature, Tradable','$\chi_T$',chi_sector_T_a,chi_sector_T_b,'externally_set'; ...
    'Investment Adjustment Cost','$\psi_I$',iac_a,iac_b,'externally_set'; ...
    'Capital Depreciation','$\delta$',delta_a,delta_b,'externally_set'; ...
    'Weight on Capital in Production','$\alpha$',cp_a,cp_b,'externally_set'; ...
    'Productivity (SS)','$e^z$',gamman_a,gamman_b,'externally_set'; ...
    'Max. Short-Term Entitlement (Quarters)','$K$',8,8,'externally_set'; ...
    'Replacement Rate, Short-Term Unemployed','$rr^s$',rrs_a,rrs_b,'externally_set'; ...
    'Replacement Rate, Long-Term Unemployed','$rr^l$',rrl_a,rrl_b,'externally_set'; ...
    'Persistence of Lump-Sum Tax','$\rho^\tau$',rhoto_a,rhoto_b,'externally_set'; ...
    'Elasticity of Tax Rate to Debt Deviations','$\chi^b$',xi_b_a,xi_b_b,'externally_set'; ...
    'Target Government Debt to Output Ratio','$\omega^b$',omega_ba,omega_bb,'externally_set'; ...
    'Share of Assets Retained by Employed Family Pool','$\tau^F$',tax_f_a,tax_f_b,'externally_set'; ...
    'Additional Asset-Withholding Wedge','$\tau^A$',tax_f2_a,tax_f2_b,'externally_set'; ...
    'Pre-Reform Steady-State Lump-Sum Tax','$\bar\tau$',tau_a_ts,tau_b_ts,'externally_set'; ...
    'Job-Filling Rate (Vacancy-Scale Normalization)','$q$',q_a_ts,q_b_ts,'externally_set'; ...
    'Recruiting Curvature, Non-Tradable','$\chi_N$',chi_sector_N_a,chi_sector_N_b,'internally_calibrated'; ...
    'Recruiting Cost Scale, Tradable','$\kappa^{\upsilon}_T$',kappavT_a,kappavT_b,'internally_calibrated'; ...
    'Recruiting Cost Scale, Non-Tradable','$\kappa^{\upsilon}_N$',kappavN_a,kappavN_b,'internally_calibrated'; ...
    'Matching Efficiency','$\kappa^e$',kappae_a,kappae_b,'internally_calibrated'; ...
    'Separation Rate','$s$',s_a,s_b,'internally_calibrated'};
parameter_table = cell2table(parameter_rows, ...
    'VariableNames',{'ParameterName','Symbol','Home','Foreign','CalibrationStatus'});
parameter_csv = fullfile(table_dir,'Table_2_Baseline_Model_Parameters.csv');
writetable(parameter_table,parameter_csv);

tnt = result.measurement.tnt_row;
target_rows = { ...
    'Relative Reaction of Tradable to Non-Tradable Employment','',0.027,NaN,tnt.rel_emp_a_q1_40_avg_pct/100; ...
    'Non-Tradable Employment Response','',-0.006,NaN,tnt.NN_a_q1_40_avg_pct/100; ...
    'Unemployment Rate','$u$',0.089,0.096,NaN; ...
    'Job-Finding Rate','$\rho$',p_a_ts,p_b_ts,NaN; ...
    'Tradable Producer Price','$p^T_H$',TPI_a_ts,TPI_b_ts,NaN; ...
    'CPI','$P$',CPI_a_ts,CPI_b_ts,NaN; ...
    'Real Exchange Rate','$\mathrm{RER}$',1,1,NaN; ...
    'Debt-to-GDP Ratio','$b/Y$',omega_ba,omega_bb,NaN; ...
    'Pre-Reform Net Foreign Assets','$NFA/Y$',clean_zero(NFA_a_ts),clean_zero(NFA_b_ts),NaN};
target_table = cell2table(target_rows, ...
    'VariableNames',{'Target','Symbol','HomeTarget','ForeignTarget','AchievedHome'});
target_csv = fullfile(table_dir,'Table_3_Calibration_Targets.csv');
writetable(target_table,target_csv);

parameter_tex = fullfile(table_dir,'Table_2_Baseline_Model_Parameters.tex');
write_parameter_tex(parameter_tex,parameter_table,betta_a,betta_b,hb1_a, ...
    foreign_home_bias);
target_tex = fullfile(table_dir,'Table_3_Calibration_Targets.tex');
write_target_tex(target_tex,target_table,tnt);

output = struct('parameter_tex',parameter_tex,'parameter_csv',parameter_csv, ...
    'target_tex',target_tex,'target_csv',target_csv, ...
    'baseline_run_dir',run_dir,'reporting_only',true);
end


function write_parameter_tex(path,t,betta_a,betta_b,hb1_a,foreign_home_bias)
fid = fopen(path,'w');
assert(fid>=0,'PaperCalibration:Open','Could not write %s.',path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'\\begin{table}[ht]\n');
fprintf(fid,'  \\centering\n');
fprintf(fid,'  \\caption{Baseline Model Parameters}\n');
fprintf(fid,'  \\label{tab:calib}\n');
fprintf(fid,'  \\resizebox{0.9\\textwidth}{!}{%%\n');
fprintf(fid,'    \\begin{tabular}{lllll}\n');
fprintf(fid,'      \\toprule\n');
fprintf(fid,'      \\multicolumn{2}{c}{Parameter Name} & Symbol & \\multicolumn{2}{c}{Value} \\\\\n');
fprintf(fid,'      & & & Home & Foreign \\\\\n');
fprintf(fid,'      \\midrule\n');
fprintf(fid,'      \\multicolumn{5}{l}{\\textit{Panel A: Externally Set}} \\\\\n');
external = find(~strcmp(t.CalibrationStatus,'internally_calibrated'));
for i = external(:)'
    if strcmp(t.ParameterName{i},'Additional Asset-Withholding Wedge')
        fprintf(fid,['%%      & Additional Asset-Withholding Wedge & $\\tau^A$ ' ...
            '& 0 & 0 \\\\\n']);
        continue
    end
    home = tex_number(t.Home(i)); foreign = tex_number(t.Foreign(i));
    if strcmp(t.ParameterName{i},'Discount Factor')
        home = sprintf('%.4f',betta_a); foreign = 'See Panel B';
    elseif strcmp(t.ParameterName{i},'Home Bias')
        home = sprintf('%.3f',hb1_a); foreign = 'See Panel B';
    end
    fprintf(fid,'      & %s & %s & %s & %s \\\\\n', ...
        t.ParameterName{i},t.Symbol{i},home,foreign);
end
fprintf(fid,'      \\midrule\n');
fprintf(fid,'      \\multicolumn{5}{l}{\\textit{Panel B: Calibrated Internally}} \\\\\n');
fprintf(fid,'      & Discount Factor & $\\beta_F$ & See Panel A & %.4f \\\\\n',betta_b);
fprintf(fid,'      & Home Bias & $\\gamma_F^C$ & See Panel A & %.3f \\\\\n',foreign_home_bias);
internal = find(strcmp(t.CalibrationStatus,'internally_calibrated'));
for i = internal(:)'
    fprintf(fid,'      & %s & %s & %s & %s \\\\\n', ...
        t.ParameterName{i},t.Symbol{i},tex_number(t.Home(i)), ...
        tex_number(t.Foreign(i)));
end
fprintf(fid,'      \\bottomrule\n');
fprintf(fid,'    \\end{tabular}%%\n');
fprintf(fid,'  }\n');
fprintf(fid,'  \\begin{flushleft}\n');
fprintf(fid,['  \\footnotesize \\textit{Notes:} The frequency is quarterly. ' ...
    'Panel A lists parameters set outside the model, from data or the literature. ' ...
    'Panel B lists parameters implied by steady-state and transition targets, ' ...
    'normalizations, and equilibrium conditions. The non-tradable recruiting ' ...
    'curvature $\\chi_N$ is calibrated jointly with the replacement-rate cut ' ...
    'to the sectoral employment targets. The foreign discount factor matches ' ...
    'the zero pre-reform net foreign asset position of the home country.\n']);
fprintf(fid,'  \\end{flushleft}\n');
fprintf(fid,'\\end{table}\n');
end


function write_target_tex(path,t,tnt)
fid = fopen(path,'w');
assert(fid>=0,'PaperCalibration:Open','Could not write %s.',path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'\\begin{table}[htbp]\n');
fprintf(fid,'  \\caption{Targets}\n');
fprintf(fid,'  \\label{tab:targets}\n');
fprintf(fid,'  \\centering\n');
fprintf(fid,'  \\begin{small}\n');
fprintf(fid,'  \\resizebox{0.8\\textwidth}{!}{\\begin{tabular}{llll}\n');
fprintf(fid,'    \\toprule\n');
fprintf(fid,'    Target & Symbol & \\multicolumn{2}{c}{Value} \\\\\n');
fprintf(fid,'           &        & Home & Foreign \\\\\n');
fprintf(fid,'    \\midrule\n');
for i = 1:height(t)
    home = tex_number(t.HomeTarget(i));
    foreign = tex_number(t.ForeignTarget(i));
    if isnan(t.ForeignTarget(i)), foreign = '--'; end
    fprintf(fid,'    %s & %s & %s & %s \\\\\n', ...
        t.Target{i},t.Symbol{i},home,foreign);
end
fprintf(fid,'    \\bottomrule\n');
fprintf(fid,'  \\end{tabular}}\n');
fprintf(fid,'  \\end{small}\n');
fprintf(fid,'  \\begin{flushleft}\n');
fprintf(fid,['  \\footnotesize \\textit{Notes:} Steady-state and transition ' ...
    'targets of the calibration. The sectoral employment responses are averages ' ...
    'over the first 40 quarters and refer to the full reform, that is, both the ' ...
    'replacement-rate cut and the entitlement-duration cut. They are matched ' ...
    'jointly by the replacement-rate cut and the non-tradable recruiting ' ...
    'curvature $\\chi_N$. The zero pre-reform net foreign asset position is ' ...
    'matched by the foreign discount factor. The job-filling rate $q=0.7$ is ' ...
    'used as a normalization of the vacancy scale and is reported in ' ...
    'Table~\\ref{tab:calib}.\n']);
fprintf(fid,'  \\end{flushleft}\n');
fprintf(fid,'\\end{table}\n');
end


function text = tex_number(value)
if isnan(value)
    text = '--';
elseif abs(value) < 1e-12
    text = '0';
elseif abs(value-round(value)) < 1e-12
    text = sprintf('%.0f',value);
elseif abs(value) < 0.02
    text = sprintf('%.4f',value);
elseif abs(value) < 1
    text = sprintf('%.3f',value);
else
    text = sprintf('%.3f',value);
end
end


function value = clean_zero(value)
if abs(value) < 1e-12
    value = 0;
end
end
