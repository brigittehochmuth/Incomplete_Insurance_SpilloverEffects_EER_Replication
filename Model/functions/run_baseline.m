function write_json_evidence(run_dir, result)
manifest = struct('timestamp',result.timestamp,'run_dir',result.run_dir, ...
    'complete',result.complete,'phase',result.phase);
if isfield(result,'configuration')
    manifest.configuration = result.configuration;
end
if isfield(result,'actual_reform_cut')
    manifest.actual_reform_cut = result.actual_reform_cut;
end
gates = struct('complete',result.complete,'phase',result.phase);
for field = {'gate0','stage_checks','anchor','diagnostics'}
    name = field{1};
    if isfield(result,name)
        gates.(name) = result.(name);
    end
end
if isfield(gates,'diagnostics') && isfield(gates.diagnostics,'accounting')
    accounting = gates.diagnostics.accounting;
    removable = intersect(fieldnames(accounting), {'cohort_a','cohort_b'});
    if ~isempty(removable)
        gates.diagnostics.accounting = rmfield(accounting, removable);
    end
end
if isfield(result,'anchor_validation')
    gates.anchor_validation = result.anchor_validation;
end
write_json(fullfile(run_dir,'run_manifest.json'),manifest);
write_json(fullfile(run_dir,'gate_report.json'),gates);
end

