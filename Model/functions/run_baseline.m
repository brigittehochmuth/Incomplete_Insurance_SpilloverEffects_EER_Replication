function history = run_reform_continuation(baseline,run_dir,rrl_before)
% Solve the maintained reform from lambda zero to one with path warm starts.
global M_ oo_ options_

stage_dir = fullfile(run_dir,'continuation');
if ~isfolder(stage_dir); mkdir(stage_dir); end
history = struct([]);
last_lambda = NaN;
last_path = [];
last_names = {};
schedule = baseline.continuation_schedule(:)';

for target = schedule
    candidate = target;
    halvings = 0;
    reached_target = false;
    while ~reached_target
        stage = struct('requested_lambda',target,'lambda',candidate, ...
            'reform_cut',baseline.reform_cut*candidate, ...
            'rrl_a',rrl_before*(1-baseline.reform_cut*candidate), ...
            'H4_shock',candidate,'halvings',halvings,'success',false, ...
            'solver_status',false,'finite_path',false,'maximum_error',NaN, ...
            'failure_identifier','','failure_message','', ...
            'timestamp',datestr(now,30),'artifact','');
        try
            purge_dynare_package('Simul_Hartz_4_v2');
            command = transition_command(stage.reform_cut, ...
                baseline.entitlement_cut_periods,baseline.simulation_periods, ...
                baseline.investment_adjustment_cost,baseline.fix_capital_financing, ...
                baseline.hall_persistence_a,baseline.hall_persistence_b, ...
                baseline.alpha_I,baseline.sector_recruiting_congestion_T, ...
                baseline.sector_recruiting_congestion_N, ...
                baseline.government_tradable_share,baseline.nfa_anchor_mode, ...
                baseline.nfa_sgu, ...
                baseline.vacancy_adjustment_cost,baseline.eta_c,baseline.phi_t, ...
                baseline.sigmac,baseline.alpha_a_t,baseline.betta_a, ...
                baseline.chiv_equations,baseline.depreciation_rate, ...
                baseline.rrs_a,baseline.rrl_a,baseline.rrs_b,baseline.rrl_b, ...
                baseline.bargaining_power_pre_a,baseline.bargaining_power_pre_b, ...
                baseline.bargaining_power_post_a,baseline.bargaining_power_post_b, ...
                baseline.bargaining_mode_a,baseline.bargaining_mode_b, ...
                baseline.bargaining_continuation_weight_a, ...
                baseline.bargaining_continuation_weight_b, ...
                baseline.separation_multiplier_a,baseline.separation_multiplier_b, ...
                baseline.separation_transition_start_quarter, ...
                baseline.separation_transition_full_effect_quarter, ...
                stage.rrl_a,baseline.rrl_post_b_value, ...
                baseline.labor_tax_closure,baseline.convex_ltu_weight, ...
                baseline.recruiting_cost_form,candidate,1);
            eval(command);

            names = strtrim(cellstr(M_.endo_names));
            if ~isempty(last_path)
                assert(isequal(names,last_names), ...
                    'RecruitingCosts:WarmStartOrdering', ...
                    'Dynare endogenous ordering changed between continuation stages.');
                assert(isequal(size(oo_.endo_simul),size(last_path)), ...
                    'RecruitingCosts:WarmStartDimensions', ...
                    'Continuation path dimensions changed between stages.');
                oo_.endo_simul(:,2:end-1) = last_path(:,2:end-1);
            end
            options_.stack_solve_algo = 6;
            options_.maxit_ = baseline.continuation_solver_maxit;
            options_.solve_tolf = baseline.continuation_solver_tolf;
            perfect_foresight_solver;
            if isfield(oo_,'deterministic_simulation') ...
                    && isfield(oo_.deterministic_simulation,'status')
                stage.solver_status = logical(oo_.deterministic_simulation.status);
            end
            stage.finite_path = isfield(oo_,'endo_simul') ...
                && isreal(oo_.endo_simul) && all(isfinite(oo_.endo_simul(:)));
            if isfield(oo_,'deterministic_simulation') ...
                    && isfield(oo_.deterministic_simulation,'error')
                stage.maximum_error = oo_.deterministic_simulation.error;
            end
            stage.success = stage.solver_status && stage.finite_path;
            if ~stage.success
                error('RecruitingCosts:ContinuationStageFailed', ...
                    'Continuation lambda %.12g returned status=%d, finite=%d.', ...
                    candidate,stage.solver_status,stage.finite_path);
            end
        catch ME
            stage.failure_identifier = ME.identifier;
            stage.failure_message = one_line_message(ME);
        end

        artifact_name = sprintf('lambda_%0.12f_attempt_%03d.mat', ...
            candidate,numel(history)+1);
        artifact_name = strrep(artifact_name,'.','p');
        artifact_name = strrep(artifact_name,'pmat','.mat');
        stage.artifact = fullfile(stage_dir,artifact_name);
        save_continuation_stage(stage.artifact,stage,M_,oo_);
        if isempty(history); history = stage; else; history(end+1) = stage; end %#ok<AGROW>

        if stage.success
            last_lambda = candidate;
            last_path = oo_.endo_simul;
            last_names = strtrim(cellstr(M_.endo_names));
            reached_target = abs(candidate-target) <= 1e-12;
            if ~reached_target
                candidate = target;
                halvings = 0;
            end
        else
            if isnan(last_lambda) || abs(candidate-last_lambda) <= 1e-12 ...
                    || halvings >= baseline.continuation_max_halvings
                error('RecruitingCosts:ContinuationExhausted', ...
                    ['Continuation failed at lambda %.12g after %d consecutive ' ...
                     'step halvings. Inspect %s.'],candidate,halvings,stage.artifact);
            end
            candidate = last_lambda+(candidate-last_lambda)/2;
            halvings = halvings+1;
        end
    end
end
writetable(struct2table(history,'AsArray',true), ...
    fullfile(stage_dir,'continuation_history.csv'));
end

function save_continuation_stage(path,stage,M_,oo_)
% Preserve the complete last iterate, including failed finite iterates.
endo_simul = [];
exo_simul = [];
steady_state = [];
parameter_vector = [];
parameter_names = {};
endogenous_names = {};
deterministic_simulation = struct();
if isstruct(oo_)
    if isfield(oo_,'endo_simul'); endo_simul = oo_.endo_simul; end
    if isfield(oo_,'exo_simul'); exo_simul = oo_.exo_simul; end
    if isfield(oo_,'steady_state'); steady_state = oo_.steady_state; end
    if isfield(oo_,'deterministic_simulation')
        deterministic_simulation = oo_.deterministic_simulation;
    end
end
if isstruct(M_)
    if isfield(M_,'params'); parameter_vector = M_.params; end
    if isfield(M_,'param_names'); parameter_names = M_.param_names; end
    if isfield(M_,'endo_names'); endogenous_names = M_.endo_names; end
end
save(path,'stage','endo_simul','exo_simul','steady_state', ...
    'parameter_vector','parameter_names','endogenous_names', ...
    'deterministic_simulation','-v7.3');
end

