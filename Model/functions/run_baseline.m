function comparison = compare_horizon_paths(short_path,long_path,M_,horizon,tolerance)
names = strtrim(cellstr(M_.endo_names));
required = {'w_a_t','N_a_t','NT_a_t','NN_a_t','C_a_t','I_a_t', ...
    'EXVOL_a_t','IMVOL_a_t','NX_a_t','CA_a_t','NFA_a_t','rer_cpi_t'};
assert(size(short_path,2) >= horizon+1 && size(long_path,2) >= horizon+1, ...
    'BaselineModel:HorizonPathLength', ...
    'Both paths must contain the initial condition and q1-q%d.',horizon);
variable = strings(0,1);
maximum_scaled_difference = zeros(0,1);
quarter = zeros(0,1);
passed = false(0,1);
for i = 1:numel(required)
    index = require_name(names,required{i});
    short = short_path(index,2:horizon+1);
    long = long_path(index,2:horizon+1);
    scaled = abs(long-short)./(1+abs(short));
    [maximum,index_q] = max(scaled);
    variable(end+1,1) = string(required{i}); %#ok<AGROW>
    maximum_scaled_difference(end+1,1) = maximum; %#ok<AGROW>
    quarter(end+1,1) = index_q; %#ok<AGROW>
    passed(end+1,1) = maximum <= tolerance; %#ok<AGROW>
end

% Saving rates are derived accounting objects rather than Dynare variables.
short_accounts = savings_accounts(short_path,M_.endo_names,M_.params,M_.param_names,'a');
long_accounts = savings_accounts(long_path,M_.endo_names,M_.params,M_.param_names,'a');
derived = { ...
    'HouseholdCashSavingRate',short_accounts.household_cash_rate,long_accounts.household_cash_rate; ...
    'NationalSavingRate',short_accounts.national_saving_rate,long_accounts.national_saving_rate};
for i = 1:size(derived,1)
    short = derived{i,2}(2:horizon+1);
    long = derived{i,3}(2:horizon+1);
    scaled = abs(long-short)./(1+abs(short));
    [maximum,index_q] = max(scaled);
    variable(end+1,1) = string(derived{i,1}); %#ok<AGROW>
    maximum_scaled_difference(end+1,1) = maximum; %#ok<AGROW>
    quarter(end+1,1) = index_q; %#ok<AGROW>
    passed(end+1,1) = maximum <= tolerance; %#ok<AGROW>
end

comparison.table = table(variable,maximum_scaled_difference,quarter,passed, ...
    'VariableNames',{'Variable','MaximumScaledDifference','Quarter','Pass'});
[comparison.maximum,index] = max(maximum_scaled_difference);
comparison.variable = char(variable(index));
comparison.period = quarter(index);
comparison.pass = all(passed);
end


