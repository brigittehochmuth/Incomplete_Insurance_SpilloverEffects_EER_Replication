function result = run_baseline(baseline)
%RUN_BASELINE Run the one maintained pre-reform steady state and transition.

global M_ oo_ options_ %#ok<NUSED>

if ~isfield(baseline, 'nfa_anchor_mode')
    baseline.nfa_anchor_mode = false;
end
if ~isfield(baseline,'sector_recruiting_congestion')
    baseline.sector_recruiting_congestion = 0.5;
end
if ~isfield(baseline,'sector_recruiting_congestion_T')
    baseline.sector_recruiting_congestion_T = ...
        baseline.sector_recruiting_congestion;
end
if ~isfield(baseline,'sector_recruiting_congestion_N')
    baseline.sector_recruiting_congestion_N = ...
        baseline.sector_recruiting_congestion;
end
defaults = struct('vacancy_adjustment_cost',0,'eta_c',6.0,'phi_t',0.5, ...
    'sigmac',2.3,'alpha_a_t',0.79,'betta_a',0.985, ...
    'single_tau_mode',false,'tax_f',0.70,'tax_f2',0.10, ...
    'government_tradable_share',0,'nfa_sgu',0,'horizon_tolerance',1e-6, ...
    'chiv_equations',true,'steady_solver_seed',[], ...
    'depreciation_rate',0.05,'rrs_a',0.6,'rrl_a',0.5, ...
    'rrs_b',0.6,'rrl_b',0.5,'bargaining_power',0.5,'bargaining_mode',0, ...
    'bargaining_continuation_weight',1.0,'steady_state_only',false, ...
    'backend','incomplete','scenario_id','baseline','throw_on_failure',true, ...
    'target_relative_employment_pct',2.7,'target_tolerance_pct',0.01, ...
    'bargaining_power_pre_a',NaN,'bargaining_power_pre_b',NaN, ...
    'bargaining_power_post_a',NaN,'bargaining_power_post_b',NaN, ...
    'bargaining_mode_a',NaN,'bargaining_mode_b',NaN, ...
    'bargaining_continuation_weight_a',NaN, ...
    'bargaining_continuation_weight_b',NaN, ...
    'separation_multiplier_a',1.0,'separation_multiplier_b',1.0, ...
    'separation_transition_start_quarter',0, ...
    'separation_transition_full_effect_quarter',0, ...
    'rrl_post_a_value',NaN,'rrl_post_b_value',NaN, ...
    'labor_tax_closure',false,'convex_ltu_weight',0.25, ...
    'recruiting_cost_form',0,'continuation_schedule',[], ...
    'continuation_max_halvings',3,'continuation_solver_maxit',50, ...
    'continuation_solver_tolf',1e-8,'result_parent_dir','', ...
    'pre_reform_cache',struct());
default_names = fieldnames(defaults);
for i_default = 1:numel(default_names)
    if ~isfield(baseline, default_names{i_default})
        baseline.(default_names{i_default}) = defaults.(default_names{i_default});
    end
end
if isnan(baseline.bargaining_power_pre_a)
    baseline.bargaining_power_pre_a = baseline.bargaining_power;
end
if isnan(baseline.bargaining_power_pre_b)
    baseline.bargaining_power_pre_b = baseline.bargaining_power;
end
if isnan(baseline.bargaining_power_post_a)
    baseline.bargaining_power_post_a = baseline.bargaining_power_pre_a;
end
if isnan(baseline.bargaining_power_post_b)
    baseline.bargaining_power_post_b = baseline.bargaining_power_pre_b;
end
if isnan(baseline.bargaining_mode_a)
    baseline.bargaining_mode_a = baseline.bargaining_mode;
end
if isnan(baseline.bargaining_mode_b)
    baseline.bargaining_mode_b = baseline.bargaining_mode;
end
if isnan(baseline.bargaining_continuation_weight_a)
    baseline.bargaining_continuation_weight_a = ...
        baseline.bargaining_continuation_weight;
end
if isnan(baseline.bargaining_continuation_weight_b)
    baseline.bargaining_continuation_weight_b = ...
        baseline.bargaining_continuation_weight;
end
if isnan(baseline.rrl_post_a_value)
    baseline.rrl_post_a_value = baseline.rrl_a*(1-baseline.reform_cut);
end
if isnan(baseline.rrl_post_b_value)
    baseline.rrl_post_b_value = baseline.rrl_b;
end
required = {'reform_cut', 'entitlement_cut_periods', ...
    'investment_adjustment_cost', 'hall_persistence_a', ...
    'hall_persistence_b', 'alpha_I', 'fix_capital_financing', ...
    'simulation_periods', 'terminal_tolerance', 'horizon_tolerance', ...
    'horizon_check', 'horizon_check_extra', 'nfa_anchor_mode','nfa_sgu', ...
    'vacancy_adjustment_cost','eta_c','phi_t','sigmac', ...
    'alpha_a_t','betta_a','single_tau_mode','tax_f','tax_f2', ...
    'sector_recruiting_congestion', ...
    'sector_recruiting_congestion_T','sector_recruiting_congestion_N', ...
    'government_tradable_share','chiv_equations','steady_solver_seed', ...
    'bargaining_power','bargaining_mode', ...
    'bargaining_continuation_weight','steady_state_only', ...
    'bargaining_power_pre_a','bargaining_power_pre_b', ...
    'bargaining_power_post_a','bargaining_power_post_b', ...
    'bargaining_mode_a','bargaining_mode_b', ...
    'bargaining_continuation_weight_a', ...
    'bargaining_continuation_weight_b','separation_multiplier_a', ...
    'separation_multiplier_b','separation_transition_start_quarter', ...
    'separation_transition_full_effect_quarter', ...
    'rrl_post_a_value','rrl_post_b_value', ...
    'labor_tax_closure','throw_on_failure','target_relative_employment_pct', ...
    'target_tolerance_pct','recruiting_cost_form','continuation_schedule', ...
    'continuation_max_halvings','continuation_solver_maxit', ...
    'continuation_solver_tolf','result_parent_dir'};
assert(all(isfield(baseline, required)), ...
    'BaselineModel:Configuration', 'Incomplete baseline configuration.');
validateattributes(baseline.reform_cut, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 0, '<', 1});
validateattributes(baseline.entitlement_cut_periods, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'integer', '>=', 0, '<=', 8});
validateattributes(baseline.recruiting_cost_form, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'integer', '>=', 0, '<=', 2});
if isfield(baseline,'apply_replacement_cut') ...
        && ~logical(baseline.apply_replacement_cut)
    assert(baseline.reform_cut == 0, ...
        'BaselineModel:ReplacementPolicyFlag', ...
        ['apply_replacement_cut=false requires reform_cut=0; policy flags ' ...
         'may not disagree with the executable reform mapping.']);
end
if isfield(baseline,'apply_entitlement_cut') ...
        && ~logical(baseline.apply_entitlement_cut)
    assert(baseline.entitlement_cut_periods == 0, ...
        'BaselineModel:EntitlementPolicyFlag', ...
        ['apply_entitlement_cut=false requires entitlement_cut_periods=0; ' ...
         'policy flags may not disagree with the executable state mapping.']);
end
validateattributes(baseline.investment_adjustment_cost, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'nonnegative'});
validateattributes(baseline.hall_persistence_a, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 0, '<', 1});
validateattributes(baseline.hall_persistence_b, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 0, '<', 1});
validateattributes(baseline.alpha_I, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>', 0, '<=', 1});
validateattributes(baseline.sector_recruiting_congestion, {'numeric'}, ...
    {'scalar','real','finite','nonnegative'});
validateattributes(baseline.sector_recruiting_congestion_T, {'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(baseline.sector_recruiting_congestion_N, {'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(baseline.continuation_schedule, {'numeric'}, ...
    {'vector','real','finite','>=',0,'<=',1});
if ~isempty(baseline.continuation_schedule)
    assert(abs(baseline.continuation_schedule(1)) <= 1e-12 ...
        && abs(baseline.continuation_schedule(end)-1) <= 1e-12 ...
        && all(diff(baseline.continuation_schedule) > 0), ...
        'RecruitingCosts:ContinuationSchedule', ...
        'Continuation must be strictly increasing from lambda=0 to lambda=1.');
end
validateattributes(baseline.continuation_max_halvings, {'numeric'}, ...
    {'scalar','integer','>=',0,'<=',3});
validateattributes(baseline.continuation_solver_maxit, {'numeric'}, ...
    {'scalar','integer','positive'});
validateattributes(baseline.continuation_solver_tolf, {'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(baseline.government_tradable_share, {'numeric'}, ...
    {'scalar','real','finite','>=',0,'<=',1});
validateattributes(baseline.fix_capital_financing, {'logical'}, {'scalar'});
validateattributes(baseline.simulation_periods, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'integer', 'positive'});
validateattributes(baseline.terminal_tolerance, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(baseline.horizon_tolerance, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(baseline.horizon_check, {'logical'}, {'scalar'});
validateattributes(baseline.horizon_check_extra, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'integer', 'positive'});
validateattributes(baseline.nfa_anchor_mode, {'logical'}, {'scalar'});
validateattributes(baseline.nfa_sgu, {'numeric'}, ...
    {'scalar','real','finite','nonnegative'});
validateattributes(baseline.vacancy_adjustment_cost, {'numeric'}, ...
    {'scalar','real','finite','nonnegative'});
validateattributes(baseline.eta_c, {'numeric'}, {'scalar','real','finite','>',1});
validateattributes(baseline.phi_t, {'numeric'}, {'scalar','real','finite','>',0});
validateattributes(baseline.sigmac, {'numeric'}, ...
    {'scalar','real','finite','>',0,'<=',2.6});
validateattributes(baseline.alpha_a_t, {'numeric'}, ...
    {'scalar','real','finite','>',0,'<',1});
validateattributes(baseline.betta_a, {'numeric'}, ...
    {'scalar','real','finite','>=',0.9825,'<=',0.985});
validateattributes(baseline.single_tau_mode, {'logical'}, {'scalar'});
validateattributes(baseline.tax_f, {'numeric'}, ...
    {'scalar','real','finite','>=',0,'<',1});
validateattributes(baseline.tax_f2, {'numeric'}, ...
    {'scalar','real','finite','>=',0,'<',1});
assert(baseline.tax_f+baseline.tax_f2 < 1, ...
    'OneTau:AssetShare', ...
    'tax_f + tax_f2 must leave a strictly positive unemployment asset share.');
if baseline.single_tau_mode
    assert(baseline.tax_f2 == 0, ...
        'OneTau:Restriction', ...
        'single_tau_mode requires tax_f2=0 exactly.');
end
validateattributes(baseline.chiv_equations, {'logical'}, {'scalar'});
validateattributes(baseline.bargaining_power, {'numeric'}, ...
    {'scalar','real','finite','>',0,'<',1});
validateattributes(baseline.bargaining_mode, {'numeric'}, ...
    {'scalar','real','finite','integer','>=',0,'<=',3});
validateattributes(baseline.bargaining_continuation_weight, {'numeric'}, ...
    {'scalar','real','finite','>=',0,'<=',1});
for power_name = {'bargaining_power_pre_a','bargaining_power_pre_b', ...
        'bargaining_power_post_a','bargaining_power_post_b'}
    validateattributes(baseline.(power_name{1}), {'numeric'}, ...
        {'scalar','real','finite','>',0,'<',1});
end
for mode_name = {'bargaining_mode_a','bargaining_mode_b'}
    validateattributes(baseline.(mode_name{1}), {'numeric'}, ...
        {'scalar','real','finite','integer','>=',0,'<=',3});
end
for weight_name = {'bargaining_continuation_weight_a', ...
        'bargaining_continuation_weight_b'}
    validateattributes(baseline.(weight_name{1}), {'numeric'}, ...
        {'scalar','real','finite','>=',0,'<=',1});
end
validateattributes(baseline.convex_ltu_weight, {'numeric'}, ...
    {'scalar','real','finite','>=',0,'<=',1});
validateattributes(baseline.separation_multiplier_a, {'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(baseline.separation_multiplier_b, {'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(baseline.separation_transition_start_quarter, {'numeric'}, ...
    {'scalar','real','finite','integer','nonnegative'});
validateattributes(baseline.separation_transition_full_effect_quarter, {'numeric'}, ...
    {'scalar','real','finite','integer','nonnegative'});
assert((baseline.separation_transition_start_quarter == 0 ...
        && baseline.separation_transition_full_effect_quarter == 0) ...
        || (baseline.separation_transition_start_quarter == 12 ...
        && baseline.separation_transition_full_effect_quarter == 24), ...
    'BaselineModel:SeparationTiming', ...
    ['Separation timing must be immediate (0,0) or unchanged through ' ...
     'quarter 12 and linear to its full effect in quarter 24.']);
validateattributes(baseline.rrl_post_a_value, {'numeric'}, ...
    {'scalar','real','finite','>=',0,'<=',1});
validateattributes(baseline.rrl_post_b_value, {'numeric'}, ...
    {'scalar','real','finite','>=',0,'<=',1});
validateattributes(baseline.labor_tax_closure, {'logical'}, {'scalar'});
validateattributes(baseline.throw_on_failure, {'logical'}, {'scalar'});
validateattributes(baseline.target_relative_employment_pct, {'numeric'}, ...
    {'scalar','real','finite'});
validateattributes(baseline.target_tolerance_pct, {'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(baseline.steady_state_only, {'logical'}, {'scalar'});
validateattributes(baseline.depreciation_rate, {'numeric'}, ...
    {'scalar','real','finite','>',0,'<',1});
for replacement_rate = {'rrs_a','rrl_a','rrs_b','rrl_b'}
    validateattributes(baseline.(replacement_rate{1}), {'numeric'}, ...
        {'scalar','real','finite','>=',0,'<=',1});
end
if ~isempty(baseline.steady_solver_seed)
    validateattributes(baseline.steady_solver_seed, {'numeric'}, ...
        {'vector','numel',8,'real','finite'});
end
assert(strcmpi(char(string(baseline.backend)),'incomplete'), ...
    'BaselineModel:Backend', ...
    'run_baseline supports the incomplete-insurance backend only.');

reported_configuration = baseline;
if isfield(reported_configuration,'pre_reform_cache')
    reported_configuration = rmfield(reported_configuration,'pre_reform_cache');
end

benefit_mapping = entitlement_mapping(baseline.entitlement_cut_periods);
if baseline.entitlement_cut_periods == 4
    assert(isequal(benefit_mapping.long_term_states,5:8), ...
        'BaselineModel:EntitlementMapping', ...
        'A four-quarter entitlement cut must switch states 5 through 8.');
end

paths = workflow_paths();
% Keep the physical folder name short enough for MATLAB on Windows. The
% complete configuration remains in run_manifest.json and run_metadata.mat.
scenario_tag = regexprep(char(string(baseline.scenario_id)),'[^A-Za-z0-9_-]','_');
if baseline.recruiting_cost_form == 0
    % Preserve the maintained current-form folder convention for regression.
    run_name = sprintf( ...
        '%s_b%d%d_x%s_ss%d_cut%03d_chiN%s_%s', ...
        scenario_tag,baseline.bargaining_mode_a,baseline.bargaining_mode_b, ...
        value_tag(baseline.bargaining_power_pre_a),baseline.steady_state_only, ...
        round(100*baseline.reform_cut), ...
        value_tag(baseline.sector_recruiting_congestion_N), ...
        datestr(now, 'yyyymmddTHHMMSS'));
else
    run_name = sprintf( ...
        '%s_f%d_b%d%d_x%s_ss%d_cut%03d_chiT%s_chiN%s_%s', ...
        scenario_tag,baseline.recruiting_cost_form,baseline.bargaining_mode_a, ...
        baseline.bargaining_mode_b,value_tag(baseline.bargaining_power_pre_a), ...
        baseline.steady_state_only,round(100*baseline.reform_cut), ...
        value_tag(baseline.sector_recruiting_congestion_T), ...
        value_tag(baseline.sector_recruiting_congestion_N), ...
        datestr(now, 'yyyymmddTHHMMSS'));
end
if isempty(baseline.result_parent_dir)
    result_parent_dir = paths.results_dir;
else
    result_parent_dir = char(string(baseline.result_parent_dir));
    if ~isfolder(result_parent_dir); mkdir(result_parent_dir); end
end
run_dir = fullfile(result_parent_dir, run_name);
mkdir(run_dir);

old_dir = pwd;
cleanup_dir = onCleanup(@() cd(old_dir)); %#ok<NASGU>
cd(paths.code_dir);

log_path = fullfile(run_dir, 'run.log');
diary(log_path);
cleanup_diary = onCleanup(@() diary('off')); %#ok<NASGU>

phase = 'initialization';
fprintf('BASELINE START %s\n', datestr(now, 30));
fprintf('Output: %s\n', run_dir);
fprintf('Replacement-rate cut: %.6f%%\n', 100 * baseline.reform_cut);
fprintf('Entitlement cut periods: %d\n', baseline.entitlement_cut_periods);
fprintf('Post-reform short-term-benefit states: %s\n', ...
    mat2str(benefit_mapping.short_term_states));
fprintf('Post-reform long-term-benefit states: %s\n', ...
    mat2str(benefit_mapping.long_term_states));
fprintf('Bargaining modes, Home/Foreign: %d (%s) / %d (%s)\n', ...
    baseline.bargaining_mode_a,bargaining_mode_label(baseline.bargaining_mode_a), ...
    baseline.bargaining_mode_b,bargaining_mode_label(baseline.bargaining_mode_b));
fprintf('Bargaining continuation weights, Home/Foreign: %.12g / %.12g\n', ...
    baseline.bargaining_continuation_weight_a, ...
    baseline.bargaining_continuation_weight_b);
fprintf('Worker bargaining power, Home pre/post: %.12g / %.12g\n', ...
    baseline.bargaining_power_pre_a,baseline.bargaining_power_post_a);
fprintf('Worker bargaining power, Foreign pre/post: %.12g / %.12g\n', ...
    baseline.bargaining_power_pre_b,baseline.bargaining_power_post_b);
fprintf('Post-reform separation multipliers, Home/Foreign: %.12g / %.12g\n', ...
    baseline.separation_multiplier_a,baseline.separation_multiplier_b);
fprintf('Home separation transition, unchanged/full-effect quarter: %d / %d\n', ...
    baseline.separation_transition_start_quarter, ...
    baseline.separation_transition_full_effect_quarter);
fprintf('Labor-tax fiscal closure: %d\n',baseline.labor_tax_closure);
fprintf('Steady-state-only run: %d\n',baseline.steady_state_only);
fprintf('Investment adjustment cost: %.12g\n', ...
    baseline.investment_adjustment_cost);
fprintf('Hall persistence, home: %.12g\n', baseline.hall_persistence_a);
fprintf('Hall persistence, foreign: %.12g\n', baseline.hall_persistence_b);
fprintf('Tradable share of investment: %.12g\n', baseline.alpha_I);
fprintf('Tradable recruiting curvature: %.12g\n', ...
    baseline.sector_recruiting_congestion_T);
fprintf('Nontradable recruiting curvature: %.12g\n', ...
    baseline.sector_recruiting_congestion_N);
fprintf('Recruiting-cost form: %d\n',baseline.recruiting_cost_form);
fprintf('Government tradable expenditure share: %.12g\n', ...
    baseline.government_tradable_share);
fprintf('Pre-reform empirical NFA anchor mode: %d\n', baseline.nfa_anchor_mode);
fprintf('Vacancy adjustment cost chiV: %.12g\n', baseline.vacancy_adjustment_cost);
fprintf('Trade elasticity eta_c: %.12g\n', baseline.eta_c);
fprintf('T/NT elasticity phi_t: %.12g\n', baseline.phi_t);
fprintf('Consumption curvature sigmac: %.12g\n', baseline.sigmac);
fprintf('Consumption tradable share alpha_a_t: %.12g\n', baseline.alpha_a_t);
fprintf('Home discount factor betta_a: %.12g\n', baseline.betta_a);
fprintf('Single-tau mode: %d\n', baseline.single_tau_mode);
fprintf('Asset wedge tau / auxiliary wedge: %.12g / %.12g\n', ...
    baseline.tax_f,baseline.tax_f2);
fprintf('Depreciation rate delta: %.12g\n', baseline.depreciation_rate);
fprintf('Replacement rates (rrs_a, rrl_a, rrs_b, rrl_b): %.12g, %.12g, %.12g, %.12g\n', ...
    baseline.rrs_a,baseline.rrl_a,baseline.rrs_b,baseline.rrl_b);
fprintf('chiV equations enabled: %d\n', baseline.chiv_equations);
fprintf('Simulation periods: %d\n', baseline.simulation_periods);

global steady_solver_seed_override recruiting_ss_share_a_guess recruiting_ss_share_b_guess
steady_solver_seed_override = baseline.steady_solver_seed(:)';
recruiting_ss_share_a_guess = 0.7878951514;
recruiting_ss_share_b_guess = 0.7878828624;

gate0 = struct('max_static_residual', NaN, 'unstable_roots', NaN, ...
    'forward_variables', NaN, 'named_equations', NaN, ...
    'named_variables', NaN, 'total_equations', NaN, ...
    'total_variables', NaN, 'static_jacobian_rank', NaN, ...
    'static_jacobian_full_rank', false, 'pass', false);
anchor = struct();
anchor_validation = validate_zero_nfa_anchor(anchor, baseline.nfa_anchor_mode);
initial = struct();
stage_checks = struct('pre_static_residual',NaN,'post_static_residual',NaN, ...
    'pre_bk_pass',false,'post_bk_pass',false);
pre_reform_cache = struct('attempted',false,'reused',false,'key','', ...
    'source','','message','No validated pre-reform cache was supplied.');
pre_reform_artifacts_ready = false;
try
    pre_reform_cache = restore_pre_reform_cache( ...
        baseline.pre_reform_cache,baseline,paths,run_dir);
    if pre_reform_cache.reused
        gate0 = pre_reform_cache.gate0;
        anchor = pre_reform_cache.anchor;
        anchor_validation = pre_reform_cache.anchor_validation;
        initial = pre_reform_cache.initialization;
        fprintf(['Gate 0 reused from validated pre-reform cache %s ' ...
            '(source %s).\n'],pre_reform_cache.key,pre_reform_cache.source);
    else
        if pre_reform_cache.attempted
            fprintf(2,['Pre-reform cache restore rejected; running a fresh ' ...
                'Gate-0 solve. %s\n'],pre_reform_cache.message);
        end
        fixed_point_rows = struct([]);
        for fixed_point_iteration = 1:8
            purge_dynare_package('preHartz_init');
            eval(pre_command(baseline.investment_adjustment_cost, ...
                baseline.fix_capital_financing, baseline.hall_persistence_a, ...
                baseline.hall_persistence_b, baseline.alpha_I, ...
                baseline.sector_recruiting_congestion_T, ...
                baseline.sector_recruiting_congestion_N, ...
                baseline.government_tradable_share, ...
                baseline.nfa_anchor_mode,baseline.vacancy_adjustment_cost, ...
                baseline.eta_c,baseline.phi_t,baseline.sigmac,baseline.alpha_a_t, ...
                baseline.betta_a,baseline.tax_f,baseline.tax_f2, ...
                baseline.chiv_equations,baseline.depreciation_rate, ...
                baseline.rrs_a,baseline.rrl_a,baseline.rrs_b,baseline.rrl_b, ...
                baseline.bargaining_power_pre_a,baseline.bargaining_power_pre_b, ...
                baseline.bargaining_mode_a,baseline.bargaining_mode_b, ...
                baseline.bargaining_continuation_weight_a, ...
                baseline.bargaining_continuation_weight_b, ...
                baseline.labor_tax_closure,baseline.convex_ltu_weight, ...
                baseline.recruiting_cost_form));
            endo_names_fp = strtrim(cellstr(M_.endo_names));
            parameter_names_fp = strtrim(cellstr(M_.param_names));
            solved_share_a = oo_.steady_state(require_name(endo_names_fp,'NT_a_t')) ...
                /(oo_.steady_state(require_name(endo_names_fp,'NT_a_t')) ...
                +oo_.steady_state(require_name(endo_names_fp,'NN_a_t')));
            solved_share_b = oo_.steady_state(require_name(endo_names_fp,'NT_b_t')) ...
                /(oo_.steady_state(require_name(endo_names_fp,'NT_b_t')) ...
                +oo_.steady_state(require_name(endo_names_fp,'NN_b_t')));
            parameter_share_a = M_.params(require_name(parameter_names_fp,'sT_a_ts'));
            parameter_share_b = M_.params(require_name(parameter_names_fp,'sT_b_ts'));
            fixed_point_gap_a = abs(recruiting_ss_share_a_guess-solved_share_a);
            fixed_point_gap_b = abs(recruiting_ss_share_b_guess-solved_share_b);
            parameter_solution_gap_a = abs(parameter_share_a-solved_share_a);
            parameter_solution_gap_b = abs(parameter_share_b-solved_share_b);
            fp_row = struct('iteration',fixed_point_iteration, ...
                'input_share_a',recruiting_ss_share_a_guess, ...
                'input_share_b',recruiting_ss_share_b_guess, ...
                'parameter_share_a',parameter_share_a, ...
                'parameter_share_b',parameter_share_b, ...
                'solved_share_a',solved_share_a,'solved_share_b',solved_share_b, ...
                'fixed_point_gap_a',fixed_point_gap_a, ...
                'fixed_point_gap_b',fixed_point_gap_b, ...
                'parameter_solution_gap_a',parameter_solution_gap_a, ...
                'parameter_solution_gap_b',parameter_solution_gap_b, ...
                'maximum_gap',max([fixed_point_gap_a,fixed_point_gap_b]), ...
                'kappavT_a',M_.params(require_name(parameter_names_fp,'kappavT_a')), ...
                'kappavN_a',M_.params(require_name(parameter_names_fp,'kappavN_a')), ...
                'kappavT_b',M_.params(require_name(parameter_names_fp,'kappavT_b')), ...
                'kappavN_b',M_.params(require_name(parameter_names_fp,'kappavN_b')));
            if isempty(fixed_point_rows)
                fixed_point_rows = fp_row;
            else
                fixed_point_rows(end+1) = fp_row; %#ok<AGROW>
            end
            fprintf(['Recruiting-scale fixed point %d: employment-share gap ' ...
                '%.12g; auxiliary parameter/solution gap %.12g.\n'], ...
                fixed_point_iteration,fp_row.maximum_gap, ...
                max(parameter_solution_gap_a,parameter_solution_gap_b));
            if fp_row.maximum_gap <= 1e-8
                break
            end
            recruiting_ss_share_a_guess = solved_share_a;
            recruiting_ss_share_b_guess = solved_share_b;
        end
        writetable(struct2table(fixed_point_rows,'AsArray',true), ...
            fullfile(run_dir,'recruiting_scale_fixed_point.csv'));
        if fixed_point_rows(end).maximum_gap > 1e-8
            error('RecruitingCosts:ScaleFixedPoint', ...
                ['Sectoral recruiting-scale employment shares did not converge ' ...
                 'in eight complete pre-reform steady-state solves; gap %.12g.'], ...
                fixed_point_rows(end).maximum_gap);
        end
        unstable_roots = sum(abs(oo_.dr.eigval) > 1.000001);
        forward_variables = M_.nfwrd + M_.nboth;
        [~,pre_static_jacobian] = preHartz_init.static(oo_.steady_state, ...
            zeros(M_.exo_nbr,1),M_.params);
        gate0.static_jacobian_rank = rank(full(pre_static_jacobian));
        gate0.static_jacobian_full_rank = ...
            gate0.static_jacobian_rank == M_.endo_nbr;
        gate0.named_variables = sum(~startsWith( ...
            strtrim(cellstr(M_.endo_names)),'AUX_'));
        gate0.total_variables = M_.endo_nbr;
        gate0.total_equations = M_.eq_nbr;
        gate0.named_equations = gate0.total_equations ...
            -(gate0.total_variables-gate0.named_variables);
        gate0.max_static_residual = oo_.fix_decomposition.pre_static_residual;
        gate0.unstable_roots = unstable_roots;
        gate0.forward_variables = forward_variables;
        gate0.pass = unstable_roots == forward_variables ...
            && gate0.max_static_residual <= 1e-10 ...
            && gate0.named_variables == 325 && gate0.named_equations == 325 ...
            && gate0.total_variables == 672 && gate0.total_equations == 672 ...
            && gate0.static_jacobian_full_rank;
        fprintf('Gate 0 Static Residual: %.12g (limit 1e-10)\n', ...
            gate0.max_static_residual);
        fprintf('\nGate 0 Determinacy: %d unstable roots for %d forward-looking variables\n', ...
            unstable_roots, forward_variables);
        fprintf('Gate 0 Counts: %d named equations / %d named variables; %d total / %d total\n', ...
            gate0.named_equations,gate0.named_variables, ...
            gate0.total_equations,gate0.total_variables);
        fprintf('Gate 0 Static Jacobian Rank: %d / %d\n', ...
            gate0.static_jacobian_rank,gate0.total_variables);
        model_diagnostics(M_,options_,oo_);
        copy_if_present(fullfile(paths.code_dir, 'preHartz_init.log'), ...
            fullfile(run_dir, 'preHartz_init.log'));
        if unstable_roots ~= forward_variables
            error('BaselineModel:BKFailure', ...
                ['Pre-reform rank condition failed: %d unstable roots for %d ' ...
                'forward-looking variables. Transition was not started.'], ...
                unstable_roots, forward_variables);
        end
        if ~gate0.pass
            error('BaselineModel:StructuralGate', ...
                ['Pre-reform structural gate failed: counts %d/%d named and ' ...
                '%d/%d total, Jacobian rank %d/%d, residual %.12g.'], ...
                gate0.named_equations,gate0.named_variables, ...
                gate0.total_equations,gate0.total_variables, ...
                gate0.static_jacobian_rank,gate0.total_variables, ...
                gate0.max_static_residual);
        end
        initial = save_initialization_snapshot(run_dir, M_, oo_);
        copy_if_present(fullfile(paths.results_dir, 'steady_solver_last_run.mat'), ...
            fullfile(run_dir, 'steady_solver_last_run.mat'));
        anchor = load_anchor_diagnostics(fullfile(run_dir, 'steady_solver_last_run.mat'));
        anchor_validation = validate_zero_nfa_anchor(anchor, baseline.nfa_anchor_mode);
        if ~anchor_validation.pass
            error('BaselineModel:ZeroNFAAnchor', '%s', anchor_validation.message);
        end
        save_initialization_snapshot(paths.results_dir, M_, oo_);
        make_mod_files(M_);
        make_mod_param_files(M_);
        copy_pre_reform_generated_files(paths,run_dir);
        copy_if_present(fullfile(paths.code_dir, 'preHartz_init.log'), ...
            fullfile(run_dir, 'preHartz_init.log'));
        pre_reform_cache.source = run_dir;
        pre_reform_cache.message = 'Fresh validated Gate-0 solve.';
    end

    pre_reform_artifacts_ready = validate_pre_reform_artifacts(run_dir);
    if ~pre_reform_artifacts_ready
        error('BaselineModel:PreReformArtifacts', ...
            'Validated Gate-0 evidence is missing one or more required artifacts.');
    end

    if baseline.steady_state_only
        result = struct('complete',true,'phase','steady_state_only', ...
            'timestamp',datestr(now,30),'run_dir',run_dir, ...
            'configuration',reported_configuration,'gate0',gate0,'anchor',anchor, ...
            'anchor_validation',anchor_validation,'initialization',initial, ...
            'stage_checks',stage_checks,'steady_state_solved',true, ...
            'transition_solved',false,'accounting_pass',false, ...
            'bargaining_identity_pass',false,'target_pass',false, ...
            'horizon_pass',false,'economic_validation_pass',false, ...
            'benefit_mapping',benefit_mapping,'message','', ...
            'pre_reform_cache_reused',pre_reform_cache.reused, ...
            'pre_reform_cache_key',pre_reform_cache.key, ...
            'pre_reform_cache_source',pre_reform_cache.source, ...
            'pre_reform_cache_restore_message',pre_reform_cache.message, ...
            'pre_reform_artifacts_ready',pre_reform_artifacts_ready);
        if isfield(anchor,'w_ts')
            result.steady_solver_seed = reshape(anchor.w_ts,1,[]);
        else
            result.steady_solver_seed = [];
        end
        save(fullfile(run_dir,'run_metadata.mat'),'result');
        write_json_evidence(run_dir,result);
        fprintf('BASELINE END %s complete=1 (steady state only)\n',result.timestamp);
        return
    end

    rrl_before = cached_pre_reform_parameter(run_dir,'rrl_a');

    phase = 'transition';
    continuation_history = struct([]);
    if isempty(baseline.continuation_schedule)
        purge_dynare_package('Simul_Hartz_4_v2');
        command = transition_command(baseline.reform_cut, ...
            baseline.entitlement_cut_periods, baseline.simulation_periods, ...
            baseline.investment_adjustment_cost, baseline.fix_capital_financing, ...
            baseline.hall_persistence_a, baseline.hall_persistence_b, ...
            baseline.alpha_I, baseline.sector_recruiting_congestion_T, ...
            baseline.sector_recruiting_congestion_N, ...
            baseline.government_tradable_share, baseline.nfa_anchor_mode, ...
            baseline.nfa_sgu, ...
            baseline.vacancy_adjustment_cost,baseline.eta_c,baseline.phi_t, ...
            baseline.sigmac,baseline.alpha_a_t,baseline.betta_a, ...
            baseline.chiv_equations,baseline.depreciation_rate, ...
            baseline.rrs_a,baseline.rrl_a,baseline.rrs_b,baseline.rrl_b, ...
            baseline.bargaining_power_pre_a,baseline.bargaining_power_pre_b, ...
            baseline.bargaining_power_post_a,baseline.bargaining_power_post_b, ...
            baseline.bargaining_mode_a,baseline.bargaining_mode_b, ...
            baseline.bargaining_continuation_weight_a, ...
            baseline.bargaining_continuation_weight_b, ...
            baseline.separation_multiplier_a,baseline.separation_multiplier_b, ...
            baseline.separation_transition_start_quarter, ...
            baseline.separation_transition_full_effect_quarter, ...
            baseline.rrl_post_a_value,baseline.rrl_post_b_value, ...
            baseline.labor_tax_closure,baseline.convex_ltu_weight, ...
            baseline.recruiting_cost_form,1,0);
        eval(command);
    else
        continuation_history = run_reform_continuation( ...
            baseline,run_dir,rrl_before);
    end

    if isfield(oo_, 'fix_decomposition')
        stage_checks = collect_stage_checks(oo_.fix_decomposition);
    end
    [~,post_static_jacobian] = Simul_Hartz_4_v2.static( ...
        oo_.steady_state,zeros(M_.exo_nbr,1),M_.params);
    stage_checks.post_static_jacobian_rank = rank(full(post_static_jacobian));
    stage_checks.post_static_jacobian_full_rank = ...
        stage_checks.post_static_jacobian_rank == M_.endo_nbr;
    model_diagnostics(M_,options_,oo_);
    if ~stage_checks.pre_bk_pass || ~stage_checks.post_bk_pass
        error('BaselineModel:BKFailure', ...
            'Transition-stage BK check failed: pre=%d, post=%d.', ...
            stage_checks.pre_bk_pass, stage_checks.post_bk_pass);
    end
    if ~stage_checks.post_static_jacobian_full_rank
        error('BaselineModel:StaticJacobianRank', ...
            'Post-reform static Jacobian rank %d is below %d.', ...
            stage_checks.post_static_jacobian_rank,M_.endo_nbr);
    end

    transition = save_transition_snapshot(run_dir, M_, oo_);
    copy_if_present(fullfile(paths.code_dir, 'Simul_Hartz_4_v2.log'), ...
        fullfile(run_dir, 'Simul_Hartz_4_v2.log'));

    transition_status = NaN;
    if isfield(oo_, 'deterministic_simulation') && ...
            isfield(oo_.deterministic_simulation, 'status')
        transition_status = oo_.deterministic_simulation.status;
    end
    if ~isequal(transition_status, true)
        error('BaselineModel:TransitionFailed', ...
            'Perfect-foresight transition status is not true.');
    end
    if any(~isfinite(transition.endo_simul(:)))
        error('BaselineModel:NonFinitePath', ...
            'The simulated transition contains non-finite values.');
    end

    transition_param_names = strtrim(cellstr(M_.param_names));
    rrl_after = M_.params(require_name(transition_param_names, 'rrl_a'));
    actual_cut = 1 - rrl_after / rrl_before;
    if abs(actual_cut - baseline.reform_cut) > 1e-10
        error('BaselineModel:WrongCut', ...
            'Requested cut %.12g but actual cut is %.12g.', ...
            baseline.reform_cut, actual_cut);
    end

    phase = 'validation';
    diagnostics = validate_baseline_results(run_dir, baseline.terminal_tolerance, ...
        baseline.horizon_tolerance);
    diagnostics.horizon_check_enabled = baseline.horizon_check;
    diagnostics.horizon_check_extra = baseline.horizon_check_extra;
    diagnostics.horizon_transition_status = NaN;
    diagnostics.horizon_insensitivity_max = NaN;
    diagnostics.horizon_insensitivity_variable = '';
    diagnostics.horizon_insensitivity_period = NaN;
    diagnostics.horizon_insensitivity_pass = NaN;
    diagnostics.horizon_failure_message = '';

    if baseline.horizon_check
        phase = 'horizon_check';
        short_path = transition.endo_simul;
        long_periods = baseline.simulation_periods + baseline.horizon_check_extra;
        fprintf('\nGate 4 Horizon Check\n');
        fprintf('  Long simulation periods: %d\n', long_periods);
        try
            purge_dynare_package('Simul_Hartz_4_v2');
            eval(transition_command(baseline.reform_cut, ...
                baseline.entitlement_cut_periods, long_periods, ...
                baseline.investment_adjustment_cost, ...
                baseline.fix_capital_financing, ...
                baseline.hall_persistence_a, baseline.hall_persistence_b, ...
                baseline.alpha_I, baseline.sector_recruiting_congestion_T, ...
                baseline.sector_recruiting_congestion_N, ...
                baseline.government_tradable_share, baseline.nfa_anchor_mode, ...
                baseline.nfa_sgu, ...
                baseline.vacancy_adjustment_cost,baseline.eta_c, ...
                baseline.phi_t,baseline.sigmac,baseline.alpha_a_t, ...
                baseline.betta_a,baseline.chiv_equations,baseline.depreciation_rate, ...
                baseline.rrs_a,baseline.rrl_a,baseline.rrs_b,baseline.rrl_b, ...
                baseline.bargaining_power_pre_a,baseline.bargaining_power_pre_b, ...
                baseline.bargaining_power_post_a,baseline.bargaining_power_post_b, ...
                baseline.bargaining_mode_a,baseline.bargaining_mode_b, ...
                baseline.bargaining_continuation_weight_a, ...
                baseline.bargaining_continuation_weight_b, ...
                baseline.separation_multiplier_a,baseline.separation_multiplier_b, ...
                baseline.separation_transition_start_quarter, ...
                baseline.separation_transition_full_effect_quarter, ...
                baseline.rrl_post_a_value,baseline.rrl_post_b_value, ...
                baseline.labor_tax_closure,baseline.convex_ltu_weight, ...
                baseline.recruiting_cost_form,1,0));
            if isfield(oo_, 'deterministic_simulation') && ...
                    isfield(oo_.deterministic_simulation, 'status')
                diagnostics.horizon_transition_status = ...
                    oo_.deterministic_simulation.status;
            end
            if isfield(oo_, 'endo_simul') && ~isempty(oo_.endo_simul)
                Sim_H42_EB_long = oo_.endo_simul; %#ok<NASGU>
                save(fullfile(run_dir, 'Sim_H42_EB_long.mat'), ...
                    'Sim_H42_EB_long');
            end
            copy_if_present(fullfile(paths.code_dir, 'Simul_Hartz_4_v2.log'), ...
                fullfile(run_dir, 'Simul_Hartz_4_v2_long.log'));
            long_path_finite = isfield(oo_, 'endo_simul') ...
                && all(isfinite(oo_.endo_simul(:)));
            if isequal(diagnostics.horizon_transition_status, true) ...
                    && long_path_finite
                comparison_horizon = 50;
                comparison = compare_horizon_paths(short_path,oo_.endo_simul, ...
                    M_,comparison_horizon,baseline.horizon_tolerance);
                diagnostics.horizon_insensitivity_max = comparison.maximum;
                diagnostics.horizon_insensitivity_variable = comparison.variable;
                diagnostics.horizon_insensitivity_period = comparison.period;
                diagnostics.horizon_insensitivity_pass = comparison.pass;
                diagnostics.horizon_comparison_csv = fullfile(run_dir, ...
                    'horizon_q1_50_comparison.csv');
                writetable(comparison.table,diagnostics.horizon_comparison_csv);
                if ~diagnostics.horizon_insensitivity_pass
                    diagnostics.horizon_failure_message = sprintf([ ...
                        'Gate 4 q1-q50 horizon insensitivity failed: maximum ' ...
                        'scaled difference=%.12g for %s at q%d, ' ...
                        'tolerance=%.12g.'], ...
                        diagnostics.horizon_insensitivity_max, ...
                        diagnostics.horizon_insensitivity_variable, ...
                        diagnostics.horizon_insensitivity_period, ...
                        baseline.horizon_tolerance);
                end
            elseif ~isequal(diagnostics.horizon_transition_status, true)
                diagnostics.horizon_failure_message = sprintf([ ...
                    'Gate 4 horizon insensitivity failed: long-run solver ' ...
                    'status=%g.'], diagnostics.horizon_transition_status);
            else
                diagnostics.horizon_failure_message = [ ...
                    'Gate 4 horizon insensitivity failed: long-run path ' ...
                    'contains non-finite values.'];
            end
        catch horizon_error
            diagnostics.horizon_failure_message = sprintf([ ...
                'Gate 4 horizon insensitivity failed: long-run solver ' ...
                'status=%g; %s: %s'], diagnostics.horizon_transition_status, ...
                horizon_error.identifier, horizon_error.message);
            copy_if_present(fullfile(paths.code_dir, 'Simul_Hartz_4_v2.log'), ...
                fullfile(run_dir, 'Simul_Hartz_4_v2_long.log'));
        end
        fprintf('  Long-run solver status: %g\n', ...
            diagnostics.horizon_transition_status);
        fprintf('  Horizon-insensitivity maximum: %.12g (tolerance %.3g)\n', ...
            diagnostics.horizon_insensitivity_max, baseline.horizon_tolerance);
        if ~isequal(diagnostics.horizon_insensitivity_pass, true)
            diagnostics.failure_messages{end+1} = ...
                diagnostics.horizon_failure_message;
        end
    end
    diagnostics.all_pass = isempty(diagnostics.failure_messages);

    phase = 'measurement_reporting';
    measurement = struct();
    reporting_messages = strings(0,1);
    try
        measurement = write_measurement_outputs(run_dir, diagnostics, run_dir);
    catch reporting_error
        reporting_messages(end+1,1) = "measurement: " + ...
            string(one_line_message(reporting_error)); %#ok<AGROW>
    end

    result = struct();
    result.complete = diagnostics.all_pass;
    if result.complete
        result.phase = 'complete';
    else
        result.phase = 'validation_failed';
    end
    result.timestamp = datestr(now, 30);
    result.run_dir = run_dir;
    result.configuration = reported_configuration;
    result.actual_reform_cut = actual_cut;
    result.rrl_before = rrl_before;
    result.rrl_after = rrl_after;
    result.transition_status = transition_status;
    result.gate0 = gate0;
    result.stage_checks = stage_checks;
    result.anchor = anchor;
    result.anchor_validation = anchor_validation;
    result.diagnostics = diagnostics;
    result.measurement = measurement;
    result.initialization = initial;
    result.continuation_history = continuation_history;
    result.benefit_mapping = benefit_mapping;
    result.pre_reform_cache_reused = pre_reform_cache.reused;
    result.pre_reform_cache_key = pre_reform_cache.key;
    result.pre_reform_cache_source = pre_reform_cache.source;
    result.pre_reform_cache_restore_message = pre_reform_cache.message;
    result.pre_reform_artifacts_ready = pre_reform_artifacts_ready;
    result.message = '';
    result.steady_state_solved = gate0.pass;
    result.transition_solved = isequal(transition_status,true);
    result.accounting_pass = diagnostics.accounting.exact_gate_pass;
    result.bargaining_identity_pass = false; % populated by run_scenario
    result.target_pass = abs( ...
        diagnostics.sector.rel_emp_a_q1_40_avg_pct ...
        -baseline.target_relative_employment_pct) <= baseline.target_tolerance_pct;
    result.horizon_pass = baseline.horizon_check ...
        && isequal(diagnostics.horizon_insensitivity_pass,true);
    result.economic_validation_pass = diagnostics.sector.external_adjustment_pass ...
        && diagnostics.sector.positivity_pass;
    result.reporting_status = if_else(isempty(reporting_messages), ...
        'available','partial');
    result.reporting_message = char(strjoin(reporting_messages,' | '));
    try
        write_report(fullfile(run_dir, 'RUN_REPORT.txt'), result);
    catch reporting_error
        reporting_messages(end+1,1) = "run report: " + ...
            string(one_line_message(reporting_error)); %#ok<AGROW>
    end
    try
        write_json_evidence(run_dir, result);
    catch reporting_error
        reporting_messages(end+1,1) = "JSON evidence: " + ...
            string(one_line_message(reporting_error)); %#ok<AGROW>
    end
    result.reporting_status = if_else(isempty(reporting_messages), ...
        'available','partial');
    result.reporting_message = char(strjoin(reporting_messages,' | '));
    try
        save(fullfile(run_dir, 'run_metadata.mat'), 'result');
    catch reporting_error
        result.reporting_status = 'partial';
        result.reporting_message = char(strjoin([reporting_messages; ...
            "MAT metadata: "+string(one_line_message(reporting_error))],' | '));
    end
    fprintf('MODEL SOLUTION END %s: steady=%d transition=%d accounting=%d\n', ...
        result.timestamp,result.steady_state_solved,result.transition_solved, ...
        result.accounting_pass && diagnostics.accounting.identity_pass);
    % The paper route checks its required gates in run_paper_outputs.
    % Additional economic and tail diagnostics remain in the saved report.
    if ~result.steady_state_solved || ~result.transition_solved ...
            || ~result.accounting_pass || ~diagnostics.accounting.identity_pass
        fprintf(2,'Required numerical checks failed. See %s\n', ...
            fullfile(run_dir,'RUN_REPORT.txt'));
        for i = 1:numel(diagnostics.failure_messages)
            fprintf(2,'%s\n',diagnostics.failure_messages{i});
        end
    elseif ~result.complete
        fprintf('Additional economic and tail diagnostics: %s\n', ...
            fullfile(run_dir,'RUN_REPORT.txt'));
    end
catch ME
    if ~pre_reform_cache.reused
        copy_if_present(fullfile(paths.results_dir, 'steady_solver_last_run.mat'), ...
            fullfile(run_dir, 'steady_solver_last_run.mat'));
    end
    transition_was_solved = exist('transition_status','var') == 1 ...
        && isequal(transition_status,true);
    accounting_was_solved = false;
    target_was_matched = false;
    horizon_was_validated = false;
    economic_profile_passed = false;
    if exist('diagnostics','var') == 1 && isstruct(diagnostics)
        if isfield(diagnostics,'accounting')
            accounting_was_solved = logical(field_or( ...
                diagnostics.accounting,'exact_gate_pass',false));
        end
        if isfield(diagnostics,'sector')
            target_gap = field_or(diagnostics.sector, ...
                'rel_emp_a_q1_40_avg_pct',NaN) ...
                -baseline.target_relative_employment_pct;
            target_was_matched = isfinite(target_gap) ...
                && abs(target_gap) <= baseline.target_tolerance_pct;
            economic_profile_passed = logical(field_or( ...
                diagnostics.sector,'external_adjustment_pass',false)) ...
                && logical(field_or(diagnostics.sector,'positivity_pass',false));
        end
        horizon_was_validated = baseline.horizon_check ...
            && logical(field_or(diagnostics,'horizon_insensitivity_pass',false));
    end
    result = struct('complete', false, 'phase', phase, ...
        'timestamp', datestr(now, 30), 'run_dir', run_dir, ...
        'message', getReport(ME, 'extended', 'hyperlinks', 'off'), ...
        'gate0', gate0, 'configuration', reported_configuration, ...
        'stage_checks', stage_checks, 'anchor', anchor, ...
        'anchor_validation', anchor_validation,'initialization',initial, ...
        'benefit_mapping',benefit_mapping, ...
        'pre_reform_cache_reused',pre_reform_cache.reused, ...
        'pre_reform_cache_key',pre_reform_cache.key, ...
        'pre_reform_cache_source',pre_reform_cache.source, ...
        'pre_reform_cache_restore_message',pre_reform_cache.message, ...
        'pre_reform_artifacts_ready',pre_reform_artifacts_ready, ...
        'steady_state_solved',gate0.pass, ...
        'transition_solved',transition_was_solved, ...
        'accounting_pass',accounting_was_solved, ...
        'bargaining_identity_pass',false,'target_pass',target_was_matched, ...
        'horizon_pass',horizon_was_validated, ...
        'economic_validation_pass',economic_profile_passed, ...
        'reporting_status','failed','reporting_message', ...
        getReport(ME,'basic','hyperlinks','off'));
    save(fullfile(run_dir, 'run_metadata.mat'), 'result');
    write_json_evidence(run_dir, result);
    fprintf(2, 'BASELINE FAILED IN %s\n%s\n', phase, result.message);
    if baseline.throw_on_failure
        rethrow(ME);
    end
end
end

function status = restore_pre_reform_cache(cache,baseline,paths,run_dir)
% Restore a complete, hash-matched Gate-0 state without invoking Dynare.
[expected_key,expected_payload] = configuration_hash(baseline);
status = struct('attempted',false,'reused',false,'key',expected_key, ...
    'source','','message','No validated pre-reform cache was supplied.', ...
    'gate0',struct(),'anchor',struct(),'anchor_validation',struct(), ...
    'initialization',struct());
if ~isstruct(cache) || ~isscalar(cache) || isempty(fieldnames(cache))
    return
end
status.attempted = true;
try
    required_fields = {'schema_version','key','payload','source_run_dir', ...
        'artifact_dir','artifacts','gate0','anchor','anchor_validation', ...
        'initialization'};
    assert(all(isfield(cache,required_fields)), ...
        'BaselineModel:PreReformCacheSchema', ...
        'The pre-reform cache payload is incomplete.');
    assert(isequal(cache.schema_version,2), ...
        'BaselineModel:PreReformCacheSchema', ...
        'Unsupported pre-reform cache schema version.');
    assert(strcmp(char(string(cache.key)),expected_key) ...
        && strcmp(char(string(cache.payload)),expected_payload), ...
        'BaselineModel:PreReformCacheHash', ...
        'The pre-reform cache hash does not match the current structural inputs.');
    assert(isstruct(cache.gate0) && isscalar(cache.gate0) ...
        && isfield(cache.gate0,'pass') && isequal(cache.gate0.pass,true), ...
        'BaselineModel:PreReformCacheGate', ...
        'The cached Gate-0 evidence is not validated.');
    assert(isstruct(cache.anchor_validation) ...
        && isscalar(cache.anchor_validation) ...
        && isfield(cache.anchor_validation,'pass') ...
        && isequal(cache.anchor_validation.pass,true), ...
        'BaselineModel:PreReformCacheAnchor', ...
        'The cached anchor evidence is not validated.');
    validate_cache_artifact_manifest(cache.artifact_dir,cache.artifacts);
    validate_cached_initialization(cache.artifact_dir,cache.initialization);

    required = required_pre_reform_artifacts();
    for i = 1:numel(required)
        source = fullfile(cache.artifact_dir,required{i});
        if endsWith(required{i},'.mod')
            destination = fullfile(paths.code_dir,required{i});
        else
            destination = fullfile(paths.results_dir,required{i});
        end
        copyfile(source,destination,'f');
        copyfile(source,fullfile(run_dir,required{i}),'f');
    end
    assert(validate_pre_reform_artifacts(run_dir), ...
        'BaselineModel:PreReformCacheRestore', ...
        'Restored pre-reform artifacts failed their structural validation.');
    status.reused = true;
    status.source = char(string(cache.source_run_dir));
    status.message = sprintf('Validated cache restored from %s.', ...
        char(string(cache.artifact_dir)));
    status.gate0 = cache.gate0;
    status.anchor = cache.anchor;
    status.anchor_validation = cache.anchor_validation;
    status.initialization = cache.initialization;
    pre_reform_cache_evidence = cache; %#ok<NASGU>
    save(fullfile(run_dir,'pre_reform_cache_evidence.mat'), ...
        'pre_reform_cache_evidence','-v7.3');
catch ME
    status.reused = false;
    status.source = '';
    status.message = sprintf('%s: %s',ME.identifier,ME.message);
end
end


function validate_cache_artifact_manifest(artifact_dir,manifest)
required = required_pre_reform_artifacts();
assert(isfolder(artifact_dir),'BaselineModel:PreReformCacheArtifacts', ...
    'The cached artifact directory is missing.');
assert(isstruct(manifest) && numel(manifest) == numel(required), ...
    'BaselineModel:PreReformCacheManifest', ...
    'The cached artifact manifest has the wrong size.');
manifest_names = cellstr(string({manifest.name}));
assert(numel(unique(manifest_names)) == numel(required) ...
    && all(ismember(required,manifest_names)), ...
    'BaselineModel:PreReformCacheManifest', ...
    'The cached artifact manifest does not contain the required file set.');
for i = 1:numel(required)
    index = find(strcmp(manifest_names,required{i}),1);
    path = fullfile(artifact_dir,required{i});
    info = dir(path);
    assert(exist(path,'file') == 2 && isscalar(info) ...
        && info.bytes == manifest(index).bytes, ...
        'BaselineModel:PreReformCacheArtifact', ...
        'Cached artifact %s is missing or has the wrong size.',required{i});
    assert(strcmp(file_sha256(path),char(string(manifest(index).sha256))), ...
        'BaselineModel:PreReformCacheArtifact', ...
        'Cached artifact %s failed its content hash.',required{i});
end
end


