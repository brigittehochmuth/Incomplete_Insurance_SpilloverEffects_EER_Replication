function measurement = write_measurement_outputs(run_dir, diagnostics, output_dir)
%WRITE_MEASUREMENT_OUTPUTS Write reconciled CA, saving, and T/NT evidence.

if nargin < 3 || isempty(output_dir)
    output_dir = run_dir;
end
if ~isfolder(output_dir)
    mkdir(output_dir);
end
s = load(fullfile(run_dir, 'Sim_H42_EB.mat'), 'Sim_H42_EB');
n = load(fullfile(run_dir, 'Names_H42_EB.mat'), ...
    'var_names', 'param_names', 'param_values');

ca = decompose_ca_path(run_dir, output_dir);
accounts = savings_accounts(s.Sim_H42_EB, n.var_names, ...
    n.param_values, n.param_names, 'a');
savings_summary_path = fullfile(output_dir, 'savings_measures_summary.csv');
writetable(accounts.summary, savings_summary_path);
savings_path = fullfile(output_dir, 'savings_accounts_q0_end.csv');
period_table = table(accounts.period', accounts.household_cash_saving', ...
    accounts.household_cash_rate', accounts.net_financial_saving', ...
    accounts.net_financial_rate', accounts.corporate_saving', ...
    accounts.corporate_saving_rate', accounts.consolidated_private_saving', ...
    accounts.consolidated_private_rate', accounts.national_saving', ...
    accounts.national_saving_rate', accounts.legacy_household_saving', ...
    accounts.legacy_household_rate', accounts.reconciliation', ...
    accounts.national_identity_residual', ...
    'VariableNames', {'Quarter','HouseholdCashSaving','HouseholdCashRate', ...
    'HouseholdNetFinancialSaving','HouseholdNetFinancialRate', ...
    'CorporateSaving','CorporateSavingRate','ConsolidatedPrivateSaving', ...
    'ConsolidatedPrivateRate','NationalSaving','NationalSavingRate', ...
    'LegacyContaminatedSaving','LegacyContaminatedRate','Reconciliation', ...
    'NationalIdentityResidual'});
writetable(period_table, savings_path);

alpha_I = parameter(n.param_names, n.param_values, 'alpha_I_a');
tnt_row = summarize_investment_tnt_run(run_dir, alpha_I, diagnostics);
tnt_path = fullfile(output_dir, 'sector_equilibrium_measurement.csv');
writetable(struct2table(tnt_row, 'AsArray', true), tnt_path);

measurement = struct('ca',ca,'savings',accounts, ...
    'savings_summary_path',savings_summary_path,'savings_path',savings_path, ...
    'tnt_row',tnt_row,'tnt_path',tnt_path);
end

function value = parameter(names, values, name)
names = strtrim(cellstr(names));
index = find(strcmp(names, name), 1);
if isempty(index)
    error('BaselineModel:MissingName', 'Required parameter not found: %s', name);
end
value = values(index);
end
