function mapping = entitlement_mapping(cut_periods)
validateattributes(cut_periods,{'numeric'}, ...
    {'scalar','integer','>=',0,'<=',8});
last_short_term_state = 8-cut_periods;
mapping = struct('cut_periods',cut_periods, ...
    'short_term_states',1:last_short_term_state, ...
    'long_term_states',(last_short_term_state+1):8);
end


function validate_specification(specification)
b = specification.baseline;
t = specification.targets;
assert(abs(b.rrl_a*(1-b.reform_cut)-0.310541406715) <= ...
    specification.validation.policy_mapping_tolerance, ...
    'ReviewerSuite:ReplacementRateMapping', ...
    ['The promoted 37.891718657 percent starting cut must imply ' ...
     'post-reform rrl_a=0.310541406715.']);
assert(b.alpha_I == 1 && b.entitlement_cut_periods == 4, ...
    'ReviewerSuite:MaintainedCalibration', ...
    'The maintained alpha_I and entitlement cut changed unexpectedly.');
assert(b.single_tau_mode && b.tax_f == 0.80 && b.tax_f2 == 0.0 ...
        && b.betta_a == 0.9840625 && b.depreciation_rate == 0.03, ...
    'ReviewerSuite:OneTauCalibration', ...
    'The promoted one-tau calibration changed unexpectedly.');
assert(t.window_start == 1 && t.window_end == 40, ...
    'ReviewerSuite:TargetWindow','The maintained target window is q1-q40.');
assert(numel(unique(specification.scenario_hash_fields)) == ...
    numel(specification.scenario_hash_fields), ...
    'ReviewerSuite:HashFields','Scenario hash fields must be unique.');
assert(strcmp(specification.insurance_comparison.wage_setting,'STU1') ...
        && specification.insurance_comparison.bargaining_mode == ...
            specification.modes.STU1, ...
    'ReviewerSuite:InsuranceWageSetting', ...
    'The promoted insurance comparison must use the STU1 wage setting.');
end
