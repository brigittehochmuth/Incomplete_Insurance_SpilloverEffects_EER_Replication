function [output_dir,suite_result] = run_paper_scenarios( ...
        insurance_comparison_sgu,options)
% Run the published model scenarios at their fixed parameter values.

close all;
if nargin < 1 || isempty(insurance_comparison_sgu)
    insurance_comparison_sgu = 0.001;
end
if nargin < 2 || isempty(options)
    options = struct();
end
code_dir = fileparts(fileparts(mfilename('fullpath')));
cd(code_dir);
addpath(fullfile(code_dir,'functions'));

paths = workflow_paths();
options = requested_suite_options(options,code_dir,paths);
output_dir = options.output_dir;
ensure_directory(output_dir);
ensure_directory(fullfile(output_dir,'scenario_mat'));
ensure_directory(fullfile(output_dir,'logs'));
ensure_directory(options.result_parent_dir);

specification = model_parameters(insurance_comparison_sgu);
[registry,registry_metadata] = paper_scenarios(specification);
registry = registry(:);
context = suite_context(output_dir,specification,options);
diary_cleanup = onCleanup(@() diary('off')); %#ok<NASGU>

% These are fixed-parameter robustness checks. In particular, the low- and
% high-zeta cases reproduce the original workflow: zeta changes to 0.40 or
% 0.60 while the maintained 37.891718657 percent reform cut stays fixed.
requested_ids = { ...
    'preferred_baseline'; 'all_unemployed_fixed'; ...
    'labor_force_weighted_fixed'; 'zeta_low_040'; 'zeta_high_060'; ...
    'complete_insurance'; 'incomplete_insurance_sgu'; 'entitlement_only'; ...
    'asymmetric_foreign_ui'; 'labor_tax_closure'};

outcomes = cell(0,1);
scenarios = cell(0,1);
for i = 1:numel(requested_ids)
    scenario = find_scenario(registry,requested_ids{i});
    scenario = apply_run_options( ...
        scenario,options,options.final_horizon_check);
    if any(strcmp(scenario.scenario_id,{'zeta_low_040','zeta_high_060'}))
        scenario.calibration_policy = 'none';
        scenario.calibration_parameter = '';
        scenario.target_metric = '';
        scenario.declared_changes = {'zeta_pre','zeta_post'};
    end
    outcomes{end+1,1} = run_scenario(scenario,context); %#ok<AGROW>
    scenarios{end+1,1} = scenario; %#ok<AGROW>
end
assert_insurance_comparison_contract( ...
    scenarios,outcomes,specification.insurance_comparison);

baseline_index = find(strcmp(requested_ids,'preferred_baseline'),1);
baseline_outcome = outcomes{baseline_index};
assert(required_baseline_gates( ...
        baseline_outcome,options.final_horizon_check), ...
    'RequestedSuite:Baseline', ...
    'The maintained STU1 checkpoint does not pass the required numerical gates.');

% Full reform is exactly the maintained baseline and therefore reuses that
    % solved path rather than launching a duplicate transition.
full_reform = find_scenario(registry,'full_reform');
full_reform = apply_run_options( ...
        full_reform,options,options.final_horizon_check);
outcomes{end+1,1} = baseline_outcome;
scenarios{end+1,1} = full_reform;

% Wage moderation contains no UI reform and changes only post-reform Home
% bargaining power to match the maintained reform's q1-q40 unemployment
% decline.
wage = find_scenario(registry,'wage_moderation_post_only');
wage = apply_run_options(wage,options,false);
unemployment_target = unemployment_q1_40_change(baseline_outcome);
wage_settings = struct('parameter','bargaining_power_post_a', ...
    'target_metric','unemployment_q1_40_change_pp', ...
    'target',unemployment_target, ...
    'tolerance',wage.target_tolerance_pp);
    wage.config.bargaining_power_post_a = ...
        options.frozen_wage_moderation_bargaining_power;
    wage = apply_run_options(wage,options,false);
    wage_outcome = run_scenario(wage,context);
    wage_response = unemployment_q1_40_change(wage_outcome);
    [wage_selection,wage_history] = check_published_parameter( ...
        wage,wage_outcome,wage_settings,wage_response);
assert(wage_selection.target_pass,'RequestedSuite:WageModeration', ...
    'The frozen wage-moderation value no longer matches its paper target.');
outcomes{end+1,1} = wage_outcome;
scenarios{end+1,1} = wage;

% Online appendix: immediate 22 percent decline in separations.
immediate = find_scenario(registry,'separation_decline');
immediate.paper_facing = true;
immediate = apply_run_options(immediate,options,false);
immediate_outcome = run_scenario(immediate,context);
immediate_settings = struct('parameter','reform_cut', ...
    'target_metric','relative_employment_pct', ...
    'target',specification.targets.relative_tn_employment_pct, ...
    'tolerance',specification.targets.relative_tn_tolerance_pp);
[immediate_selection,immediate_history] = check_published_parameter( ...
    immediate,immediate_outcome,immediate_settings, ...
    immediate_outcome.status.relative_employment_pct);
assert(immediate_selection.target_pass,'PaperReplication:SeparationTarget', ...
    'The fixed separation scenario does not meet the published employment target.');
outcomes{end+1,1} = immediate_outcome;
scenarios{end+1,1} = immediate;

wage_history.TargetTolerance = repmat(wage_settings.tolerance,height(wage_history),1);
if ~isempty(immediate_history)
    immediate_history.TargetTolerance = repmat( ...
        immediate_settings.tolerance,height(immediate_history),1);
end
calibration_history = [wage_history;immediate_history];
rows = repmat(struct(),0,1);
collector_options = struct( ...
    'target_value_pct',specification.targets.relative_tn_employment_pct, ...
    'target_tolerance_pct',specification.targets.relative_tn_tolerance_pp, ...
    'accounting_tolerance', ...
        specification.validation.accounting_residual_tolerance, ...
    'bargaining_tolerance',specification.validation.bargaining_identity_tolerance, ...
    'calibration_history',calibration_history);
for i = 1:numel(outcomes)
    row = collect_scenario_results( ...
        scenarios{i},outcomes{i},collector_options);
    if isempty(rows), rows = row; else, rows(end+1,1) = row; end %#ok<AGROW>
end
rows = scenario_checks(rows,calibration_history);
used_registry = concatenate_scenarios(scenarios);

suite = struct('name','requested_paper_robustness', ...
    'maintained_reform_cut',specification.baseline.reform_cut, ...
    'simulation_periods',specification.baseline.simulation_periods, ...
    'paper_outputs_only',options.paper_outputs_only, ...
    'main_paper_only',options.main_paper_only, ...
    'fixed_published_parameters',true, ...
    'final_horizon_checks',options.final_horizon_check, ...
    'fresh_output_root',output_dir, ...
    'wage_moderation_scale_match',true, ...
    'requested_scenario_ids',{cellfun(@(x) x.scenario_id, ...
        scenarios,'UniformOutput',false)});
save(fullfile(output_dir,'requested_paper_robustness_results.mat'), ...
    'suite','specification','registry_metadata','used_registry', ...
    'outcomes','rows','calibration_history','-v7.3');

write_scenario_results(output_dir,used_registry,rows, ...
    calibration_history,struct('make_plots',true,'plot_horizon',50));
output_scope = 'all';
write_paper_outputs( ...
    output_dir,rows,code_dir,output_scope,options.paper_output_dir);
write_requested_manifest(output_dir,suite,rows,wage_selection,immediate_selection);

fprintf('REQUESTED PAPER ROBUSTNESS SUITE END %s\n',datestr(now,30));
fprintf('Unified outputs: %s\n',output_dir);
suite_result = struct('output_dir',output_dir, ...
    'paper_output_dir',options.paper_output_dir, ...
    'suite',suite,'rows',rows,'outcomes',{outcomes}, ...
    'scenarios',{scenarios},'calibration_history',calibration_history, ...
    'wage_selection',wage_selection, ...
    'immediate_separation_selection',immediate_selection);
end


function assert_insurance_comparison_contract(scenarios,outcomes,comparison)
ids = cellfun(@(x) x.scenario_id,scenarios,'UniformOutput',false);
complete_index = find(strcmp(ids,'complete_insurance'),1);
incomplete_index = find(strcmp(ids,'incomplete_insurance_sgu'),1);
assert(~isempty(complete_index) && ~isempty(incomplete_index), ...
    'RequestedSuite:InsuranceComparison', ...
    'Both matched insurance-comparison scenarios are required.');
complete = outcomes{complete_index}.configuration;
incomplete = outcomes{incomplete_index}.configuration;
tolerance = 10*eps(max(1,comparison.sgu));
assert(abs(complete.complete_insurance_sgu-comparison.sgu) <= tolerance ...
        && abs(incomplete.nfa_sgu-comparison.sgu) <= tolerance ...
        && abs(complete.complete_insurance_sgu-incomplete.nfa_sgu) <= tolerance, ...
    'RequestedSuite:MatchedSGU', ...
    'Complete and incomplete insurance must use the selected matched SGU.');
assert(complete.bargaining_mode == 0 ...
        && complete.bargaining_mode_a == 0 ...
        && complete.bargaining_mode_b == 0, ...
    'RequestedSuite:STU1WageSetting', ...
    'The complete-insurance comparison must use the STU1 wage setting.');
end


function context = suite_context(output_dir,specification,options)
context = struct('output_dir',output_dir, ...
    'resume',options.resume,'force',options.force, ...
    'master_log_path',fullfile(output_dir,'logs', ...
        'requested_paper_robustness_suite.log'), ...
    'cache_dir',fullfile(output_dir,'steady_state_cache'), ...
    'scenario_mat_dir',fullfile(output_dir,'scenario_mat'), ...
    'target_relative_employment_pct', ...
        specification.targets.relative_tn_employment_pct, ...
    'target_tolerance_pct',specification.targets.relative_tn_tolerance_pp, ...
    'identity_tolerance', ...
        specification.validation.bargaining_identity_tolerance);
diary(context.master_log_path);
end


function scenario = find_scenario(registry,id)
index = find(strcmp({registry.scenario_id},id),1);
assert(~isempty(index),'RequestedSuite:MissingScenario', ...
    'Missing requested scenario %s.',id);
scenario = registry(index);
end


function ensure_directory(path)
if ~isfolder(path)
    [created,message] = mkdir(path);
    assert(created,'RequestedSuite:Directory', ...
        'Could not create %s: %s',path,message);
end
end


function combined = concatenate_scenarios(scenarios)
% A calibrated scenario may carry additional top-level provenance fields.
% Harmonize the metadata schema without changing any numerical config.
all_fields = {};
for i = 1:numel(scenarios)
    all_fields = union(all_fields,fieldnames(scenarios{i}),'stable');
end
for i = 1:numel(scenarios)
    missing = setdiff(all_fields,fieldnames(scenarios{i}),'stable');
    for j = 1:numel(missing)
        scenarios{i}.(missing{j}) = [];
    end
    scenarios{i} = orderfields(scenarios{i},all_fields);
end
combined = vertcat(scenarios{:});
end


function pass = required_baseline_gates(outcome,require_horizon)
pass = isfield(outcome,'status') ...
    && logical(outcome.status.steady_state_solved) ...
    && logical(outcome.status.transition_solved) ...
    && logical(outcome.status.accounting_pass) ...
    && logical(outcome.status.bargaining_identity_pass);
if require_horizon
    pass = pass && logical(outcome.status.horizon_pass);
end
end


function target = unemployment_q1_40_change(outcome)
run_dir = outcome.result.run_dir;
simulation = load(fullfile(run_dir,'Sim_H42_EB.mat'),'Sim_H42_EB');
names = load(fullfile(run_dir,'Names_H42_EB.mat'),'var_names');
variable_names = strtrim(cellstr(names.var_names));
index = find(strcmp(variable_names,'N_a_t'),1);
assert(~isempty(index),'RequestedSuite:EmploymentSeries', ...
    'N_a_t is missing from the maintained baseline transition.');
employment = simulation.Sim_H42_EB(index,:);
target = mean(100*((1-employment(2:41))-(1-employment(1))));
end


function write_requested_manifest(output_dir,suite,rows,wage_selection, ...
        immediate_selection)
manifest = struct('created',datestr(now,30),'suite',suite, ...
    'wage_moderation_calibration_status',wage_selection.status, ...
    'wage_moderation_post_reform_bargaining_power', ...
        wage_selection.best_value, ...
    'wage_moderation_target_gap_pp',wage_selection.gap, ...
    'immediate_separation_calibration_status', ...
        immediate_selection.status, ...
    'immediate_separation_reform_cut', ...
        immediate_selection.best_value, ...
    'immediate_separation_target_gap_pp', ...
        immediate_selection.gap, ...
    'scenario_status',{arrayfun(@manifest_row,rows)});
path = fullfile(output_dir,'requested_paper_robustness_manifest.json');
fid = fopen(path,'w');
assert(fid>=0,'RequestedSuite:Manifest','Could not write %s.',path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(manifest,'PrettyPrint',true));
end


function options = requested_suite_options(options,code_dir,paths)
defaults = struct( ...
    'output_dir',fullfile(paths.results_dir,'paper_replication_suite'), ...
    'result_parent_dir',paths.results_dir, ...
    'short_result_parent_dir',fullfile(paths.results_dir,'pr'), ...
    'paper_output_dir',fullfile(code_dir,'paper_outputs'), ...
    'resume',true, ...
    'force',false, ...
    'main_paper_only',false, ...
    'paper_outputs_only',true, ...
    'reuse_existing_horizon_checkpoints',false, ...
    'frozen_wage_moderation_bargaining_power',0.2848786961505812, ...
    'final_horizon_check',false);
names = fieldnames(defaults);
for i = 1:numel(names)
    if ~isfield(options,names{i}) || isempty(options.(names{i}))
        options.(names{i}) = defaults.(names{i});
    end
end
options.output_dir = char(string(options.output_dir));
options.result_parent_dir = char(string(options.result_parent_dir));
options.short_result_parent_dir = char(string( ...
    options.short_result_parent_dir));
options.paper_output_dir = char(string(options.paper_output_dir));
options.resume = logical(options.resume);
options.force = logical(options.force);
options.main_paper_only = logical(options.main_paper_only);
options.paper_outputs_only = logical(options.paper_outputs_only);
assert(~options.main_paper_only || options.paper_outputs_only, ...
    'RequestedSuite:MainPaperScope', ...
    'main_paper_only requires fixed accepted paper values.');
options.reuse_existing_horizon_checkpoints = logical( ...
    options.reuse_existing_horizon_checkpoints);
options.final_horizon_check = logical(options.final_horizon_check);
end


function [selection,history] = check_published_parameter( ...
        scenario,outcome,settings,response)
value = scenario.config.(settings.parameter);
gap = response-settings.target;
solved = logical(outcome.status.steady_state_solved) ...
    && logical(outcome.status.transition_solved) ...
    && logical(outcome.status.accounting_pass) ...
    && logical(outcome.status.bargaining_identity_pass);
target_pass = solved && isfinite(gap) && abs(gap) <= settings.tolerance;
status = 'frozen_paper_value_target_failed';
if target_pass
    status = 'frozen_paper_value';
end
selection = struct('scenario',scenario,'outcome',outcome, ...
    'status',status,'target_pass',target_pass,'best_value',value, ...
    'response',response,'gap',gap,'settings',settings, ...
    'failure_provenance',struct());
run_dir = string(outcome.result.run_dir);
checkpoint_path = "";
if isfield(outcome,'checkpoint_path')
    checkpoint_path = string(outcome.checkpoint_path);
elseif isfield(outcome.result,'checkpoint_path')
    checkpoint_path = string(outcome.result.checkpoint_path);
end
history = table(string(scenario.scenario_id), ...
    string(scenario.scenario_id),string(settings.parameter),value, ...
    string(settings.target_metric),settings.target,response,gap, ...
    logical(outcome.status.steady_state_solved), ...
    logical(outcome.status.transition_solved), ...
    logical(outcome.status.accounting_pass), ...
    logical(outcome.status.bargaining_identity_pass),false,"","","","", ...
    solved,run_dir,checkpoint_path, ...
    "Published parameter value.", ...
    'VariableNames',{'ScenarioID','AttemptID','Parameter','AttemptedValue', ...
    'TargetMetric','Target','Response','Gap','SteadyStateSolved', ...
    'TransitionSolved','AccountingPass','BargainingIdentityPass', ...
    'IntrinsicPrestateFailure','FailurePhase','FailureIdentifier', ...
    'FailureIdentifierSource','FailureMessage','Solved','RunDir', ...
    'CheckpointPath','Message'});
end


function scenario = apply_run_options(scenario,options,horizon_check)
scenario.config.horizon_check = logical(horizon_check);
    legacy_horizon_ids = { ...
        'preferred_baseline'; ...
        'complete_insurance'; ...
    'entitlement_only'; ...
    'labor_tax_closure'};
if options.paper_outputs_only ...
        && options.reuse_existing_horizon_checkpoints ...
        && any(strcmp(scenario.scenario_id,legacy_horizon_ids))
    scenario.config.horizon_check = true;
end
scenario.config.result_parent_dir = options.result_parent_dir;
short_path_ids = { ...
    'all_unemployed_fixed'; ...
    'labor_force_weighted_fixed'; ...
    'incomplete_insurance_sgu'; ...
    'asymmetric_foreign_ui'; ...
    'wage_moderation_post_only'; ...
    'separation_decline'};
if options.paper_outputs_only ...
        && any(strcmp(scenario.scenario_id,short_path_ids))
    ensure_directory(options.short_result_parent_dir);
    scenario.config.result_parent_dir = options.short_result_parent_dir;
end
end


function item = manifest_row(row)
item = struct('scenario_id',char(string(row.scenario_id)), ...
    'status',char(string(row.status)), ...
    'run_dir',char(string(row.run_dir)), ...
    'target_status',char(string(row.gates.target_status)), ...
    'horizon_status',char(string(row.gates.horizon_status)));
end
