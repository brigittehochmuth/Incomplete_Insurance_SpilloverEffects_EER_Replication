function summary = raw_tradable_summary(level, sector_output, qT, ...
        aggregate_output_value, valid_period)
share_sector = level./abs(sector_output);
bps_aggregate = 1e4*qT.*level./abs(aggregate_output_value);
q1_40 = 1:min(40,numel(level));
valid = find(valid_period);
summary = struct();
summary.level = level;
summary.share_sector_output = share_sector;
summary.bps_aggregate_output = bps_aggregate;
summary.impact_level = level(1);
summary.impact_share_sector_output = share_sector(1);
summary.impact_bps_aggregate_output = bps_aggregate(1);
summary.q1_40_max_abs_level = max(abs(level(q1_40)));
summary.q1_40_max_abs_share_sector_output = max(abs(share_sector(q1_40)));
summary.q1_40_max_abs_bps_aggregate_output = max(abs(bps_aggregate(q1_40)));
summary.full_valid_max_abs_level = max(abs(level(valid)));
summary.full_valid_max_abs_share_sector_output = max(abs(share_sector(valid)));
summary.full_valid_max_abs_bps_aggregate_output = max(abs(bps_aggregate(valid)));
end

