function audit = audit_repaired_accounting(sim, names, param_values, param_names)
%AUDIT_REPAIRED_ACCOUNTING Check the repaired accounting and capital-q block.

names = strtrim(cellstr(names));
param_names = strtrim(cellstr(param_names));
v = @(name, columns) sim(require_name(names, name), columns);
p = @(name) param_values(require_name(param_names, name));

c = 2:size(sim, 2)-1;
lag = c-1;
lead = c+1;
q40 = 2:min(41, size(sim, 2)-1);

residuals = struct();
for land = {'a', 'b'}
    x = land{1};
    qY = v(['qY_' x '_t'], c);
    qI = v(['qI_' x '_t'], c);
    qT = v(['qT_' x '_t'], c);
    qN = v(['qN_' x '_t'], c);
    growth = v(['I_' x '_t'], c)./v(['I_' x '_t'], lag);
    growth_lead = v(['I_' x '_t'], lead)./v(['I_' x '_t'], c);
    phi = 1-p(['iac_' x])/2.*(growth-1).^2;

    residuals.(['ca_change_nfa_' x]) = v(['CA_' x '_t'], c) ...
        -(v(['NFA_' x '_t'], c)-v(['NFA_' x '_t'], lag));
    residuals.(['ces_consumption_' x]) = v(['TPI_' x '_t'], c).*v(['cT_' x '_t'], c) ...
        -v('pH_t', c).*v(['cH_' x '_t'], c)-v('pF_t', c).*v(['cF_' x '_t'], c);
    residuals.(['consumption_upper_tier_' x]) = v(['CPI_' x '_t'], c).*v(['C_' x '_t'], c) ...
        -v(['TPI_' x '_t'], c).*v(['cT_' x '_t'], c)-v(['pN_' x '_t'], c).*v(['cN_' x '_t'], c);
    residuals.(['ces_investment_tradable_' x]) = v(['TPI_' x '_t'], c).*v(['iT_' x '_t'], c) ...
        -v('pH_t', c).*v(['iH_' x '_t'], c)-v('pF_t', c).*v(['iF_' x '_t'], c);
    residuals.(['investment_upper_tier_' x]) = v(['IPI_' x '_t'], c).*v(['I_' x '_t'], c) ...
        -v(['TPI_' x '_t'], c).*v(['iT_' x '_t'], c) ...
        -v(['pN_' x '_t'], c).*v(['iN_' x '_t'], c);
    output_value = qT.*v(['YT_' x '_t'], c)+qN.*v(['YN_' x '_t'], c);
    residuals.(['output_price_' x]) = qY-output_value./v(['Y_' x '_t'], c);
    residuals.(['investment_price_' x]) = qI-v(['IPI_' x '_t'], c)./v(['CPI_' x '_t'], c);
    residuals.(['tradable_price_' x]) = qT-v(['EXVAL_' x '_t'], c)./v(['EXVOL_' x '_t'], c);
    residuals.(['nontradable_price_' x]) = qN-v(['pN_' x '_t'], c)./v(['CPI_' x '_t'], c);
    residuals.(['capital_law_' x]) = v(['k_' x '_t'], c) ...
        -(1-p(['delta_' x])).*v(['k_' x '_t'], lag)-phi.*v(['I_' x '_t'], c);
    residuals.(['capital_foc_' x]) = v('R_w_t', c).*v(['TQ_' x '_t'], c) ...
        -v(['RK_' x '_t'], lead) ...
        -(1-p(['delta_' x])).*v(['TQ_' x '_t'], lead);
    residuals.(['investment_foc_' x]) = qI-v(['TQ_' x '_t'], c) ...
        .*(phi-p(['iac_' x]).*(growth-1).*growth) ...
        -v(['TQ_' x '_t'], lead)./v('R_w_t', c).*p(['iac_' x]) ...
        .*(growth_lead-1).*growth_lead.^2;

    j_formula = p(['tax_f2_' x]).*(v(['k_' x '_t'], lag)+v(['b_' x '_t'], lag) ...
        +v(['NFA_' x '_t'], lag))./v(['mue_' x '_t'], lag).*v('R_w_t', lag) ...
        .*(v(['p_' x '_t'], c).*(1-v(['mue_' x '_t'], lag)-v(['muuu_' x '_t'], lag) ...
        -v(['mueu8_' x '_t'], lag))+v(['mueu8_' x '_t'], lag));
    residuals.(['named_transfer_' x]) = v(['J_' x '_t'], c)-j_formula;

    residuals.(['employment_add_' x]) = v(['NT_' x '_t'], c)+v(['NN_' x '_t'], c)-v(['N_' x '_t'], c);
    residuals.(['output_add_' x]) = v(['YT_' x '_t'], c)+v(['YN_' x '_t'], c)-v(['Y_' x '_t'], c);
    residuals.(['vacancy_add_' x]) = v(['VT_' x '_t'], c)+v(['VN_' x '_t'], c)-v(['V_' x '_t'], c);
    residuals.(['match_add_' x]) = v(['q_' x '_t'], c).*v(['VT_' x '_t'], c) ...
        +v(['q_' x '_t'], c).*v(['VN_' x '_t'], c)-v(['M_' x '_t'], c);
    separation_denominator = (1-v(['p_' x '_t'],c)) ...
        .*v(['mue_' x '_t'],lag);
    assert(all(isfinite(separation_denominator)) ...
            && all(separation_denominator > 0), ...
        'RepairedAccounting:SeparationDenominator', ...
        'Country %s has an invalid separation-rate denominator.',x);
    effective_separation = v(['mueu1_' x '_t'],c) ...
        ./separation_denominator;
    assert(all(isfinite(effective_separation)) ...
            && all(effective_separation >= -1e-10) ...
            && all(effective_separation <= 1+1e-10), ...
        'RepairedAccounting:SeparationPath', ...
        'Country %s has an invalid effective separation-rate path.',x);
    effective_separation = min(max(effective_separation,0),1);
    residuals.(['employment_law_T_' x]) = v(['NT_' x '_t'], c) ...
        -(1-effective_separation).*v(['NT_' x '_t'], lag) ...
        -v(['q_' x '_t'], c).*v(['VT_' x '_t'], c);
    residuals.(['employment_law_N_' x]) = v(['NN_' x '_t'], c) ...
        -(1-effective_separation).*v(['NN_' x '_t'], lag) ...
        -v(['q_' x '_t'], c).*v(['VN_' x '_t'], c);
    residuals.(['capital_add_' x]) = v(['KTuse_' x '_t'], c)+v(['KNuse_' x '_t'], c)-v(['k_' x '_t'], lag);
    residuals.(['production_T_' x]) = v(['YT_' x '_t'], c) ...
        -v(['TS_' x '_t'], c).*v(['KTuse_' x '_t'], c).^p(['cp_' x]) ...
        .*v(['NT_' x '_t'], c).^(1-p(['cp_' x]));
    residuals.(['production_N_' x]) = v(['YN_' x '_t'], c) ...
        -v(['TS_' x '_t'], c).*v(['KNuse_' x '_t'], c).^p(['cp_' x]) ...
        .*v(['NN_' x '_t'], c).^(1-p(['cp_' x]));
    residuals.(['rental_T_' x]) = qT.*v(['MPKT_' x '_t'], c)-v(['RK_' x '_t'], c);
    residuals.(['rental_N_' x]) = qN.*v(['MPKN_' x '_t'], c)-v(['RK_' x '_t'], c);

    chi_sector_T = p(['chi_sector_T_' x]);
    chi_sector_N = p(['chi_sector_N_' x]);
    form = p('recruiting_cost_form');
    kappa = p(['kappav_' x]);
    kappa_t = p(['kappavT_' x]);
    kappa_n = p(['kappavN_' x]);
    if form == 0
        expected_rct = kappa*p(['VT_' x '_ts'])/(1+chi_sector_T) ...
            .*(v(['VT_' x '_t'], c)/p(['VT_' x '_ts'])).^(1+chi_sector_T) ...
            +chi_sector_T/(1+chi_sector_T)*kappa*p(['VT_' x '_ts']);
        expected_rcn = kappa*p(['VN_' x '_ts'])/(1+chi_sector_N) ...
            .*(v(['VN_' x '_t'], c)/p(['VN_' x '_ts'])).^(1+chi_sector_N) ...
            +chi_sector_N/(1+chi_sector_N)*kappa*p(['VN_' x '_ts']);
        foc_t = qT.*kappa.*(v(['VT_' x '_t'], c)/p(['VT_' x '_ts'])).^chi_sector_T./v(['q_' x '_t'], c);
        foc_n = qN.*kappa.*(v(['VN_' x '_t'], c)/p(['VN_' x '_ts'])).^chi_sector_N./v(['q_' x '_t'], c);
        capacity_t = zeros(size(c));
        capacity_n = zeros(size(c));
    elseif form == 1
        x_t = v(['VT_' x '_t'], c)./v(['NT_' x '_t'], lag);
        x_n = v(['VN_' x '_t'], c)./v(['NN_' x '_t'], lag);
        xbar_t = p(['VT_' x '_ts'])/p(['NT_' x '_ts']);
        xbar_n = p(['VN_' x '_ts'])/p(['NN_' x '_ts']);
        expected_rct = kappa_t*xbar_t/(1+chi_sector_T).*v(['NT_' x '_t'], c-1) ...
            .*(x_t/xbar_t).^(1+chi_sector_T);
        expected_rcn = kappa_n*xbar_n/(1+chi_sector_N).*v(['NN_' x '_t'], c-1) ...
            .*(x_n/xbar_n).^(1+chi_sector_N);
        foc_t = qT.*kappa_t.*(x_t/xbar_t).^chi_sector_T./v(['q_' x '_t'], c);
        foc_n = qN.*kappa_n.*(x_n/xbar_n).^chi_sector_N./v(['q_' x '_t'], c);
        x_t_lead = v(['VT_' x '_t'], lead)./v(['NT_' x '_t'], c);
        x_n_lead = v(['VN_' x '_t'], lead)./v(['NN_' x '_t'], c);
        capacity_t = v(['qT_' x '_t'], lead).*chi_sector_T/(1+chi_sector_T) ...
            .*kappa_t.*xbar_t.*(x_t_lead/xbar_t).^(1+chi_sector_T);
        capacity_n = v(['qN_' x '_t'], lead).*chi_sector_N/(1+chi_sector_N) ...
            .*kappa_n.*xbar_n.*(x_n_lead/xbar_n).^(1+chi_sector_N);
    elseif form == 2
        h_t = v(['q_' x '_t'], c).*v(['VT_' x '_t'], c)./v(['NT_' x '_t'], lag);
        h_n = v(['q_' x '_t'], c).*v(['VN_' x '_t'], c)./v(['NN_' x '_t'], lag);
        hbar_t = p(['q_' x '_ts'])*p(['VT_' x '_ts'])/p(['NT_' x '_ts']);
        hbar_n = p(['q_' x '_ts'])*p(['VN_' x '_ts'])/p(['NN_' x '_ts']);
        expected_rct = kappa_t*hbar_t/(1+chi_sector_T).*v(['NT_' x '_t'], lag) ...
            .*(h_t/hbar_t).^(1+chi_sector_T);
        expected_rcn = kappa_n*hbar_n/(1+chi_sector_N).*v(['NN_' x '_t'], lag) ...
            .*(h_n/hbar_n).^(1+chi_sector_N);
        foc_t = qT.*kappa_t.*(h_t/hbar_t).^chi_sector_T;
        foc_n = qN.*kappa_n.*(h_n/hbar_n).^chi_sector_N;
        h_t_lead = v(['q_' x '_t'], lead).*v(['VT_' x '_t'], lead) ...
            ./v(['NT_' x '_t'], c);
        h_n_lead = v(['q_' x '_t'], lead).*v(['VN_' x '_t'], lead) ...
            ./v(['NN_' x '_t'], c);
        capacity_t = v(['qT_' x '_t'], lead).*chi_sector_T/(1+chi_sector_T) ...
            .*kappa_t.*hbar_t.*(h_t_lead/hbar_t).^(1+chi_sector_T);
        capacity_n = v(['qN_' x '_t'], lead).*chi_sector_N/(1+chi_sector_N) ...
            .*kappa_n.*hbar_n.*(h_n_lead/hbar_n).^(1+chi_sector_N);
    else
        error('RecruitingCosts:UnknownForm','Unknown recruiting_cost_form %g.',form);
    end
    residuals.(['recruiting_cost_T_' x]) = v(['RCT_' x '_t'], c)-expected_rct;
    residuals.(['recruiting_cost_N_' x]) = v(['RCN_' x '_t'], c)-expected_rcn;
    residuals.(['recruiting_cost_add_' x]) = v(['RCT_' x '_t'], c)+v(['RCN_' x '_t'], c)-v(['CV_' x '_t'], c);
    residuals.(['surplus_add_' x]) = v(['Sf_' x '_t'], c) ...
        -(v(['NT_' x '_t'], c).*v(['SfT_' x '_t'], c)+v(['NN_' x '_t'], c).*v(['SfN_' x '_t'], c))./v(['N_' x '_t'], c);
    residuals.(['vacancy_foc_T_' x]) = foc_t-v(['SfT_' x '_t'], c);
    residuals.(['vacancy_foc_N_' x]) = foc_n-v(['SfN_' x '_t'], c);
    job_rhs_t = qT.*v(['MPLT_' x '_t'], c)-v(['w_' x '_t'], c) ...
        +1./v('R_w_t',c).*((1-effective_separation).*v(['SfT_' x '_t'],lead) ...
        +capacity_t);
    job_rhs_n = qN.*v(['MPLN_' x '_t'], c)-v(['w_' x '_t'], c) ...
        +1./v('R_w_t',c).*((1-effective_separation).*v(['SfN_' x '_t'],lead) ...
        +capacity_n);
    residuals.(['job_value_T_' x]) = v(['SfT_' x '_t'],c)-job_rhs_t;
    residuals.(['job_value_N_' x]) = v(['SfN_' x '_t'],c)-job_rhs_n;

    if x == 'a'
        external_income = (v('Rf_a_t', c)-1).*v('NFA_a_t', lag);
    else
        external_income = (v('R_w_t', lag)-1).*v('NFA_b_t', lag)+v('nfa_spread_b_t', c);
    end
    audit.(['output_value_' x]) = output_value;
    audit.(['external_income_' x]) = external_income;
    audit.(['ca_' x]) = v(['CA_' x '_t'], c);
    audit.(['nx_' x]) = v(['NX_' x '_t'], c);
    residuals.(['gnp_' x]) = v(['GNP_' x '_t'], c)-output_value-external_income;
    audit.(['ca_nx_income_' x]) = v(['CA_' x '_t'], c) ...
        -v(['NX_' x '_t'], c)-external_income;

    cohort = cohort_asset_accounting(sim, names, param_values, ...
        param_names, x);
    audit.(['cohort_' x]) = cohort;
    % The raw residual is an economic object: frozen claims plus the tax_f2
    % holding account. Only the unexplained augmented residual is gated.
    corr = cohort.raw_resource_residual;
    audit.(['corr_' x]) = corr;
    audit.(['corr_scaled_' x]) = abs(corr)./(1+abs(output_value));
    q40_count = min(40, numel(corr));
    audit.(['corr_q1_40_max_share_' x]) = max(abs(corr(1:q40_count))./abs(output_value(1:q40_count)));
    audit.(['corr_full_max_share_' x]) = max(abs(corr)./abs(output_value));
    audit.(['raw_term_q1_40_max_bps_' x]) = 1e4*max(abs( ...
        cohort.raw_resource_residual_share_output(1:q40_count)));
    audit.(['impact_frozen_stock_change_' x]) = cohort.frozen_stock_change(1);
    audit.(['impact_frozen_stock_change_bps_' x]) = 1e4* ...
        cohort.frozen_stock_change_share_output(1);
    audit.(['impact_tax_holding_change_' x]) = cohort.tax_holding_account_change(1);
    audit.(['impact_tax_holding_change_bps_' x]) = 1e4* ...
        cohort.tax_holding_account_change_share_output(1);
    audit.(['max_raw_flow_reconciliation_error_' x]) = max(abs( ...
        cohort.raw_flow_reconciliation_error_share_output));
    valid = cohort.stock_law_valid_period;
    audit.(['max_frozen_stock_law_error_' x]) = max(abs( ...
        cohort.frozen_stock_law_error_share_output(valid)));
    audit.(['max_augmented_resource_residual_' x]) = max(abs( ...
        cohort.augmented_resource_residual_share_output(valid)));
    audit.(['terminal_boundary_stock_law_error_' x]) = ...
        cohort.frozen_stock_law_error_share_output(end);
    audit.(['terminal_boundary_augmented_residual_' x]) = ...
        cohort.augmented_resource_residual_share_output(end);
end

size_a = p('size_a');
audit.goods_T_a = v('YT_a_t', c)-v('cH_a_t', c)-v('iH_a_t', c) ...
    -(1-size_a)/size_a.*(v('cH_b_t', c)+v('iH_b_t', c))-v('RCT_a_t', c)-p('FCT_a') ...
    -p('alpha_G_T_a').*v('DG_a_t', c)./v('qT_a_t', c);
audit.goods_N_a = v('YN_a_t', c)-v('cN_a_t', c)-v('iN_a_t', c) ...
    -v('RCN_a_t', c)-p('FCN_a')-(1-p('alpha_G_T_a')).*v('DG_a_t', c)./v('qN_a_t', c);
audit.goods_T_b = v('YT_b_t', c)-v('cF_b_t', c)-v('iF_b_t', c) ...
    -size_a/(1-size_a).*(v('cF_a_t', c)+v('iF_a_t', c))-v('RCT_b_t', c)-p('FCT_b') ...
    -p('alpha_G_T_b').*v('DG_b_t', c)./v('qT_b_t', c);
audit.goods_N_b = v('YN_b_t', c)-v('cN_b_t', c)-v('iN_b_t', c) ...
    -v('RCN_b_t', c)-p('FCN_b')-(1-p('alpha_G_T_b')).*v('DG_b_t', c)./v('qN_b_t', c);

% Only the two retained nontradable market equations are direct zero gates.
% The omitted tradable markets remain physical residuals and enter the
% value-weighted Walras reconciliation below.
residuals.goods_N_a = audit.goods_N_a;
residuals.goods_N_b = audit.goods_N_b;

audit.goods_value_a = v('qT_a_t', c).*audit.goods_T_a ...
    +v('qN_a_t', c).*audit.goods_N_a;
audit.goods_value_b = v('qT_b_t', c).*audit.goods_T_b ...
    +v('qN_b_t', c).*audit.goods_N_b;

relative_cpi = v('CPI_a_t', c)./v('CPI_b_t', c);
relative_cpi_lag = v('CPI_a_t', lag)./v('CPI_b_t', lag);
audit.valuation_b = v('R_w_t', lag).*v('NFA_b_t', lag) ...
    .*(relative_cpi./relative_cpi_lag-1);

audit.home_nfa_flow_identity = audit.ca_nx_income_a;
audit.foreign_nfa_valuation_identity = audit.ca_nx_income_b-audit.valuation_b;
audit.walras_reconciliation_a = audit.goods_value_a ...
    -audit.cohort_a.raw_flow_term-audit.ca_nx_income_a;
audit.walras_reconciliation_b = audit.goods_value_b ...
    -audit.cohort_b.raw_flow_term-audit.ca_nx_income_b;

audit.home_nfa_flow_identity_share_output = ...
    audit.home_nfa_flow_identity./abs(audit.output_value_a);
audit.foreign_nfa_valuation_identity_share_output = ...
    audit.foreign_nfa_valuation_identity./abs(audit.output_value_b);
audit.walras_reconciliation_a_share_output = ...
    audit.walras_reconciliation_a./abs(audit.output_value_a);
audit.walras_reconciliation_b_share_output = ...
    audit.walras_reconciliation_b./abs(audit.output_value_b);

audit.raw_tradable_a = raw_tradable_summary(audit.goods_T_a, ...
    v('YT_a_t', c),v('qT_a_t', c),audit.output_value_a, ...
    audit.cohort_a.stock_law_valid_period);
audit.raw_tradable_b = raw_tradable_summary(audit.goods_T_b, ...
    v('YT_b_t', c),v('qT_b_t', c),audit.output_value_b, ...
    audit.cohort_b.stock_law_valid_period);

residuals.export_volume_a = v('EXVOL_a_t', c)-(1-size_a)/size_a.*(v('cH_b_t', c)+v('iH_b_t', c));
residuals.export_value_a = v('EXVAL_a_t', c)-v('qT_a_t', c).*v('EXVOL_a_t', c);
residuals.import_volume_a = v('IMVOL_a_t', c)-v('cF_a_t', c)-v('iF_a_t', c);
residuals.import_value_a = v('IMVAL_a_t', c)-v('pF_t', c)./v('CPI_a_t', c).*v('IMVOL_a_t', c);

residuals.nfa_law_a = v('NFA_a_t', c)-v('Rf_a_t', c).*v('NFA_a_t', lag)-v('NX_a_t', c);
residuals.nfa_clearing = p('size_a').*v('CPI_a_t', c).*v('NFA_a_t', c) ...
    +(1-p('size_a')).*v('CPI_b_t', c).*v('NFA_b_t', c);
residuals.spread_rebate = p('size_a').*v('CPI_a_t', c).*v('nfa_spread_a_t', c) ...
    +(1-p('size_a')).*v('CPI_b_t', c).*v('nfa_spread_b_t', c);

fields = fieldnames(residuals);
audit.max_identity_residual = 0;
audit.max_identity_name = '';
for i = 1:numel(fields)
    value = max(abs(residuals.(fields{i})));
    audit.residual_max.(fields{i}) = value;
    if value > audit.max_identity_residual
        audit.max_identity_residual = value;
        audit.max_identity_name = fields{i};
    end
end
tolerances = recruiting_validation_tolerances();
audit.identity_tolerance = tolerances.identity;
audit.identity_pass = audit.max_identity_residual <= audit.identity_tolerance;
audit.max_recruiting_cost_residual = max([ ...
    audit.residual_max.recruiting_cost_T_a, ...
    audit.residual_max.recruiting_cost_N_a, ...
    audit.residual_max.recruiting_cost_T_b, ...
    audit.residual_max.recruiting_cost_N_b]);
audit.max_sectoral_vacancy_foc_residual = max([ ...
    audit.residual_max.vacancy_foc_T_a, ...
    audit.residual_max.vacancy_foc_N_a, ...
    audit.residual_max.vacancy_foc_T_b, ...
    audit.residual_max.vacancy_foc_N_b]);
audit.max_job_value_residual = max([ ...
    audit.residual_max.job_value_T_a, ...
    audit.residual_max.job_value_N_a, ...
    audit.residual_max.job_value_T_b, ...
    audit.residual_max.job_value_N_b]);
audit.max_employment_flow_residual = max([ ...
    audit.residual_max.employment_law_T_a, ...
    audit.residual_max.employment_law_N_a, ...
    audit.residual_max.employment_law_T_b, ...
    audit.residual_max.employment_law_N_b]);
audit.max_nontradable_goods_market_residual = max([ ...
    audit.residual_max.goods_N_a,audit.residual_max.goods_N_b]);
audit.recruiting_cost_gate_pass = ...
    audit.max_recruiting_cost_residual <= tolerances.resource;
audit.sectoral_vacancy_foc_gate_pass = ...
    audit.max_sectoral_vacancy_foc_residual <= tolerances.vacancy_foc;
audit.job_value_gate_pass = ...
    audit.max_job_value_residual <= tolerances.job_value;
audit.employment_flow_gate_pass = ...
    audit.max_employment_flow_residual <= tolerances.employment_flow;
audit.nontradable_goods_market_gate_pass = ...
    audit.max_nontradable_goods_market_residual <= 1e-10;
audit.corr_q1_40_max_share = max(audit.corr_q1_40_max_share_a, audit.corr_q1_40_max_share_b);
