function cohort = cohort_asset_accounting(sim, names, param_values, param_names, land)
%COHORT_ASSET_ACCOUNTING Exact frozen-cohort stock-flow accounting.
% Columns 2:end-1 are transition periods. Missing pre-transition lags are
% clamped to column 1, matching the maintained saved-path conventions.

if nargin < 5 || isempty(land)
    land = 'a';
end
land = char(land);
assert(any(strcmp(land, {'a','b'})), 'BaselineModel:Country', ...
    'Country must be ''a'' or ''b''; received %s.', land);
assert(size(sim,2) >= 3, 'BaselineModel:ShortPath', ...
    'Cohort accounting requires initial, transition, and terminal columns.');

names = strtrim(cellstr(names));
param_names = strtrim(cellstr(param_names));
v = @(name, columns) sim(require_name(names, name), columns);
p = @(name) param_values(require_name(param_names, name));

columns = 2:size(sim,2)-1;
periods = numel(columns);
all_columns = 1:size(sim,2);
x = v('R_w_t', all_columns).*v(['ae_' land '_t'], all_columns);
tax_f = p(['tax_f_' land]);
tax_f2 = p(['tax_f2_' land]);
g = 1-tax_f;
chi = 1-tax_f-tax_f2;

O = zeros(1, periods);
F = zeros(1, periods);
D = zeros(1, periods);
Z_open = zeros(1, periods);
Z_close = zeros(1, periods);

for t = 1:periods
    c = columns(t);
    x_lag = x(clamp_column(c-1, size(sim,2)));
    u1 = v(['mueu1_' land '_t'], c);
    rho = v(['p_' land '_t'], c);
    O(t) = g*u1*x_lag;

    for state = 1:8
        u = v(sprintf('mueu%d_%s_t', state, land), c);
        share = v(sprintf('share%d_%s_t', state, land), c);
        asset_column = clamp_column(c-state, size(sim,2));
        D(t) = D(t)+chi*u*share*x(asset_column);
    end

    for state = 1:7
        u_lag = v(sprintf('mueu%d_%s_t', state, land), ...
            clamp_column(c-1, size(sim,2)));
        rest_open = v(sprintf('Rest%d_%s_t', state, land), c);
        asset_column = clamp_column(c-state-1, size(sim,2));
        opening_claim = chi*u_lag*rest_open*x(asset_column);
        Z_open(t) = Z_open(t)+opening_claim;
        F(t) = F(t)+rho*opening_claim;

        u = v(sprintf('mueu%d_%s_t', state, land), c);
        rest_close = v(sprintf('Rest%d_%s_t', state, land), c+1);
        closing_asset_column = clamp_column(c-state, size(sim,2));
        Z_close(t) = Z_close(t) ...
            +chi*u*rest_close*x(closing_asset_column);
    end
end

J = v(['J_' land '_t'], columns);
delta_Z = Z_close-Z_open;
delta_Z_from_flows = chi*v(['mueu1_' land '_t'], columns) ...
    .*x(columns-1)-F-D;
delta_E = tax_f2*v(['mueu1_' land '_t'], columns).*x(columns-1)-J;
raw_flow = O-F-D-J;

qI = v(['qI_' land '_t'], columns);
qT = v(['qT_' land '_t'], columns);
qN = v(['qN_' land '_t'], columns);
sector_resource_cost = qT.*(v(['RCT_' land '_t'], columns)+p(['FCT_' land])) ...
    +qN.*(v(['RCN_' land '_t'], columns)+p(['FCN_' land]));
raw_resource = v(['GNP_' land '_t'], columns) ...
    -v(['C_' land '_t'], columns)-qI.*v(['I_' land '_t'], columns) ...
    -v(['DG_' land '_t'], columns) ...
    -sector_resource_cost ...
    -v(['CA_' land '_t'], columns);
augmented = raw_resource-delta_Z-delta_E;
output_value = qT.*v(['YT_' land '_t'], columns) ...
    +qN.*v(['YN_' land '_t'], columns);
assert(all(isfinite(output_value)) && all(abs(output_value) > eps), ...
    'BaselineModel:OutputScale', ...
    'Output values must be finite and nonzero for cohort scaling.');

cohort = struct();
cohort.period = 1:periods;
cohort.gross_new_unemployment_asset_outflow = O;
cohort.returned_frozen_assets = F;
cohort.unemployed_asset_consumption = D;
cohort.tax_f2_transfer = J;
cohort.raw_flow_term = raw_flow;
cohort.frozen_stock_open = Z_open;
cohort.frozen_stock_close = Z_close;
cohort.frozen_stock_change = delta_Z;
cohort.frozen_stock_change_from_flows = delta_Z_from_flows;
cohort.tax_holding_account_change = delta_E;
cohort.derived_cohort_timing_term = delta_Z+delta_E;
cohort.raw_resource_residual = raw_resource;
cohort.augmented_resource_residual = augmented;
cohort.raw_flow_reconciliation_error = raw_resource-raw_flow;
cohort.frozen_stock_law_error = delta_Z-delta_Z_from_flows;
cohort.cumulative_identity_error = cumsum(raw_resource) ...
    -cumsum(delta_Z+delta_E);
cohort.output_value = output_value;
% The final simulated column points to Dynare's separately imposed endval.
% Rest_{T+1} is therefore not generated by the Rest recursion at T+1. Keep
% that boundary observation in the output, but do not treat it as a valid
% stock-law period. All earlier transition columns have an endogenous lead.
cohort.stock_law_valid_period = true(1, periods);
cohort.stock_law_valid_period(end) = false;

scaled_fields = fieldnames(cohort);
for i = 1:numel(scaled_fields)
    field = scaled_fields{i};
    value = cohort.(field);
    if isnumeric(value) && isrow(value) && numel(value) == periods ...
            && ~strcmp(field, 'period') && ~strcmp(field, 'output_value')
        cohort.([field '_share_output']) = value./abs(output_value);
    end
end
end

function column = clamp_column(column, final_column)
column = min(max(column, 1), final_column);
end

function index = require_name(names, name)
index = find(strcmp(names, name), 1);
if isempty(index)
    error('BaselineModel:MissingName', ...
        'Required model name not found: %s', name);
end
end
