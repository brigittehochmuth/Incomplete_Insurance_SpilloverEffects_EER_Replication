function entries = build_manifest(root_dir,relative_paths,root_kind)
template = struct('root_kind','','relative_path','','absolute_path','', ...
    'exists',false,'bytes',NaN,'sha256','__MISSING__');
entries = repmat(template,numel(relative_paths),1);
for i = 1:numel(relative_paths)
    relative_path = normalize_relative_path(relative_paths{i});
    absolute_path = fullfile(root_dir,strrep(relative_path,'/',filesep));
    entries(i).root_kind = root_kind;
    entries(i).relative_path = relative_path;
    entries(i).absolute_path = canonical_path(absolute_path);
    info = dir(absolute_path);
    if exist(absolute_path,'file') == 2 && isscalar(info)
        entries(i).exists = true;
        entries(i).bytes = info.bytes;
        entries(i).sha256 = file_sha256(absolute_path);
    end
end
end


function fingerprint = manifest_fingerprint(entries)
% Deliberately omit absolute_path: it is provenance, not source content.
payload_entries = repmat(struct('root_kind','','relative_path','', ...
    'exists',false,'bytes',NaN,'sha256',''),numel(entries),1);
for i = 1:numel(entries)
    payload_entries(i).root_kind = entries(i).root_kind;
    payload_entries(i).relative_path = entries(i).relative_path;
    payload_entries(i).exists = entries(i).exists;
    payload_entries(i).bytes = entries(i).bytes;
    payload_entries(i).sha256 = entries(i).sha256;
end
fingerprint = text_sha256(jsonencode(payload_entries));
end


function fingerprint = file_sha256(path)
fid = fopen(path,'rb');
assert(fid >= 0,'ReviewerSuite:SourceFingerprintRead', ...
    'Could not read source dependency %s.',path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
bytes = fread(fid,Inf,'*uint8');
fingerprint = bytes_sha256(bytes);
end


function fingerprint = text_sha256(value)
fingerprint = bytes_sha256(uint8(char(value)));
end


function fingerprint = bytes_sha256(bytes)
try
    engine = java.security.MessageDigest.getInstance('SHA-256');
    engine.update(bytes);
    digest = typecast(engine.digest(),'uint8');
    fingerprint = ['sha256_' lower(reshape(dec2hex(digest,2).',1,[]))];
catch
    codes = double(bytes(:)');
    indices = 1:numel(codes);
    first = mod(sum(codes.*indices),4294967291);
    second = mod(sum(codes.*mod(indices.^2,4294967279)),4294967279);
    fingerprint = sprintf('fallback_%08x_%08x',uint32(first),uint32(second));
end
end


function value = normalize_relative_path(value)
value = strrep(char(string(value)),'\','/');
while startsWith(value,'./')
    value = value(3:end);
end
end


function value = canonical_path(value)
value = char(string(value));
try
    value = char(java.io.File(value).getCanonicalPath());
catch
    % Retain the supplied path in a no-JVM diagnostic session.
end
end
