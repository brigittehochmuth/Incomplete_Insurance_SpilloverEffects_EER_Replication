function result = run_complete_insurance_backend(configuration,run_dir,code_dir)
%RUN_COMPLETE_INSURANCE_BACKEND Run the corrected representative-agent model.

arguments
    configuration (1,1) struct
    run_dir (1,:) char
    code_dir (1,:) char
end

global M_ oo_ options_ %#ok<NUSED>

ensure_folder(run_dir);
scratch_dir = fullfile(run_dir,'scratch');
ensure_folder(scratch_dir);
ensure_folder(fullfile(scratch_dir,'Results'));
assert(value(configuration,'bargaining_mode',0) == 0 ...
        && value(configuration,'bargaining_mode_a',0) == 0 ...
        && value(configuration,'bargaining_mode_b',0) == 0, ...
    'CompleteInsurance:STU1WageSetting', ...
    'The baseline complete-insurance comparison requires STU1 wage setting.');
write_calibration_overrides(scratch_dir,configuration);

baseline_dir = fullfile(code_dir,'Inputs','complete_insurance');
assert(isfile(fullfile(baseline_dir,'SS_init.mat')) ...
    && isfile(fullfile(baseline_dir,'Param_init.mat')), ...
    'CompleteInsurance:BaselineInitialization', ...
    'The maintained STU1 initialization is missing from %s.',baseline_dir);

backend_dir = fullfile(code_dir,'complete_insurance_backend');
copy_required(backend_dir,scratch_dir,{ ...
    'Rep_agent_corrected.mod','model_equations_general_RA_corrected.m', ...
    'model_equations_linkages_TNT_RA_corrected.m','RA_initss.mod'});
copy_required(code_dir,scratch_dir,{ ...
    'var_params.m','fiscal_rule.m','newss.mod'});
copy_required(baseline_dir,scratch_dir,{'SS_init.mod','Param_init.mod'});
copy_required(baseline_dir,fullfile(scratch_dir,'Results'), ...
    {'SS_init.mat','Param_init.mat'});

command = dynare_command(configuration);
old_dir = pwd;
cleanup_dir = onCleanup(@() cd(old_dir)); %#ok<NASGU>
cd(scratch_dir);
diary_path = fullfile(run_dir,'complete_insurance_run.log');
diary(diary_path);
cleanup_diary = onCleanup(@() diary('off')); %#ok<NASGU>
fprintf('CORRECTED REPRESENTATIVE-AGENT RUN START %s\n',datestr(now,30));
fprintf('Command: %s\n',command);
eval(command);

solution_path = fullfile(scratch_dir,'Results','RA_solution.mat');
assert(isfile(solution_path),'CompleteInsurance:SolutionBundle', ...
    'Dynare did not write the representative-agent solution bundle.');
solution = load(solution_path, ...
    'RA_initss','RA_pre_params','newss','M_','oo_','options_');
RA_initss = solution.RA_initss;
RA_pre_params = solution.RA_pre_params;
newss = solution.newss;
M_ = solution.M_;
oo_ = solution.oo_;
options_ = solution.options_;

assert(exist('M_','var') == 1 && exist('oo_','var') == 1, ...
    'CompleteInsurance:DynareOutput','Dynare returned no M_ or oo_ output.');
assert(exist('RA_initss','var') == 1 && exist('newss','var') == 1, ...
    'CompleteInsurance:SteadyStates', ...
    'The representative-agent steady-state vectors were not created.');
assert(exist('RA_pre_params','var') == 1, ...
    'CompleteInsurance:PreParameters', ...
    'The pre-reform parameter vector was not created.');

NN = size(M_.endo_names,1);
Sim_H42_EB = oo_.endo_simul(1:NN,:); %#ok<NASGU>
var_names = cellstr(M_.endo_names); %#ok<NASGU>
param_names = cellstr(M_.param_names); %#ok<NASGU>
param_values = M_.params(:)'; %#ok<NASGU>
SS_init = RA_initss; %#ok<NASGU>
Param_init = RA_pre_params; %#ok<NASGU>
SS_H42_EB = newss; %#ok<NASGU>

save(fullfile(run_dir,'Sim_H42_EB.mat'),'Sim_H42_EB','-v7.3');
save(fullfile(run_dir,'Names_H42_EB.mat'), ...
    'var_names','param_names','param_values');
save(fullfile(run_dir,'Names.mat'), ...
    'var_names','param_names','param_values');
save(fullfile(run_dir,'SS_init.mat'),'SS_init');
save(fullfile(run_dir,'Param_init.mat'),'Param_init');
save(fullfile(run_dir,'SS_H42_EB.mat'),'SS_H42_EB');

copy_if_present(fullfile(scratch_dir,'Rep_agent_corrected.log'), ...
    fullfile(run_dir,'Rep_agent_corrected.log'));
copy_if_present(fullfile(scratch_dir,'Rep_agent_corrected_results.mat'), ...
    fullfile(run_dir,'Rep_agent_corrected_results.mat'));
copy_if_present(solution_path,fullfile(run_dir,'RA_solution.mat'));

diagnostics = validate_run(Sim_H42_EB,var_names,param_names,param_values, ...
    RA_initss,newss,oo_,configuration);
write_json(fullfile(run_dir,'complete_insurance_diagnostics.json'),diagnostics);

metadata = struct('created',datestr(now,30), ...
    'backend','corrected_representative_agent', ...
    'model_source',backend_dir, ...
    'production_search_international_blocks','maintained_STU1_KK', ...
    'household_block','representative_agent_complete_insurance', ...
    'wage_setting','STU1', ...
    'bargaining_threat_point', ...
        'duration_state_income_values_under_common_marginal_utility', ...
    'configuration',configuration,'dynare_command',command, ...
    'diagnostics',diagnostics);
write_json(fullfile(run_dir,'complete_insurance_backend.json'),metadata);

result = struct('complete',diagnostics.all_pass, ...
    'phase','complete_insurance_transition', ...
    'timestamp',datestr(now,30),'run_dir',run_dir, ...
    'configuration',configuration, ...
    'steady_state_solved',diagnostics.steady_state_solved, ...
    'transition_solved',diagnostics.transition_solved, ...
    'accounting_pass',diagnostics.accounting_pass, ...
    'bargaining_identity_pass',diagnostics.bargaining_identity_pass, ...
    'target_pass',diagnostics.target_metric_available, ...
    'horizon_pass',diagnostics.horizon_pass, ...
    'economic_validation_pass',diagnostics.economic_validation_pass, ...
    'actual_reform_cut',diagnostics.actual_reform_cut, ...
    'rrl_before',diagnostics.rrl_before, ...
    'rrl_after',diagnostics.rrl_after, ...
    'gate0',struct('pass',diagnostics.steady_state_solved, ...
        'max_static_residual',diagnostics.max_static_residual), ...
    'diagnostics',diagnostics,'message',diagnostics.message);
save(fullfile(run_dir,'run_metadata.mat'),'result','-v7.3');
fprintf('CORRECTED REPRESENTATIVE-AGENT RUN END %s\n',datestr(now,30));
end


function command = dynare_command(c)
command = sprintf([ ...
    'dynare Rep_agent_corrected.mod nowarn nostrict noclearall ' ...
    '-Dreform_cut=%.12g -Dentitlement_cut_periods=%d ' ...
    '-Dsimulation_periods=%d -Diac_value=%.12g ' ...
    '-Dfix_capital_financing=%d -Dgammaw_a_value=%.12g ' ...
    '-Dgammaw_b_value=%.12g -Dalpha_I_value=%.12g ' ...
    '-Dchi_sector_T_value=%.12g -Dchi_sector_N_value=%.12g ' ...
    '-Dalpha_G_T_value=%.12g -Dnfa_anchor_mode=%d ' ...
    '-DchiV_value=%.12g -Deta_c_value=%.12g -Dphi_t_value=%.12g ' ...
    '-Dsigmac_value=%.12g -Dalpha_a_t_value=%.12g ' ...
    '-Dbetta_a_value=%.12g -Dchiv_equations=%d -Ddelta_value=%.12g ' ...
    '-Drrs_a_value=%.12g -Drrl_a_value=%.12g ' ...
    '-Drrs_b_value=%.12g -Drrl_b_value=%.12g ' ...
    '-Dxoui_value=%.12g -Dxoui_a_value=%.12g -Dxoui_b_value=%.12g ' ...
    '-Dxoui_post_a_value=%.12g -Dxoui_post_b_value=%.12g ' ...
    '-Dbargaining_mode=%d -Dbargaining_mode_a=%d -Dbargaining_mode_b=%d ' ...
    '-Dbargaining_continuation_weight=%.12g ' ...
    '-Dbargaining_continuation_weight_a=%.12g ' ...
    '-Dbargaining_continuation_weight_b=%.12g ' ...
    '-Dseparation_multiplier_a=%.12g -Dseparation_multiplier_b=%.12g ' ...
    '-Drrl_post_a_value=%.12g -Drrl_post_b_value=%.12g ' ...
    '-Dlabor_tax_closure=%d -Dconvex_ltu_weight=%.12g ' ...
    '-Drecruiting_cost_form=%d -Dreform_lambda=1 ' ...
    '-Ddefer_perfect_foresight=0 -Dphi_SGU_value=%.12g'], ...
    value(c,'reform_cut',0.37891718657), ...
    round(value(c,'entitlement_cut_periods',4)), ...
    round(value(c,'simulation_periods',800)), ...
    value(c,'investment_adjustment_cost',8.7), ...
    logical_value(c,'fix_capital_financing',true), ...
    value(c,'hall_persistence_a',0),value(c,'hall_persistence_b',0), ...
    value(c,'alpha_I',1), ...
    value(c,'sector_recruiting_congestion_T',1.0), ...
    value(c,'sector_recruiting_congestion_N',3.5), ...
    value(c,'government_tradable_share',0), ...
    logical_value(c,'nfa_anchor_mode',true), ...
    value(c,'vacancy_adjustment_cost',0),value(c,'eta_c',6), ...
    value(c,'phi_t',0.5),value(c,'sigmac',2), ...
    value(c,'alpha_a_t',0.79),value(c,'betta_a',0.985), ...
    logical_value(c,'chiv_equations',true), ...
    value(c,'depreciation_rate',0.03), ...
    value(c,'rrs_a',0.6),value(c,'rrl_a',0.5), ...
    value(c,'rrs_b',0.6),value(c,'rrl_b',0.5), ...
    value(c,'bargaining_power_pre_a',0.5), ...
    value(c,'bargaining_power_pre_a',0.5), ...
    value(c,'bargaining_power_pre_b',0.5), ...
    value(c,'bargaining_power_post_a',0.5), ...
    value(c,'bargaining_power_post_b',0.5), ...
    round(value(c,'bargaining_mode_a',0)), ...
    round(value(c,'bargaining_mode_a',0)), ...
    round(value(c,'bargaining_mode_b',0)), ...
    value(c,'bargaining_continuation_weight_a',1), ...
    value(c,'bargaining_continuation_weight_a',1), ...
    value(c,'bargaining_continuation_weight_b',1), ...
    value(c,'separation_multiplier_a',1), ...
    value(c,'separation_multiplier_b',1), ...
    finite_or(c,'rrl_post_a_value',-1), ...
    finite_or(c,'rrl_post_b_value',-1), ...
    logical_value(c,'labor_tax_closure',false), ...
    value(c,'convex_ltu_weight',0.25), ...
    round(value(c,'recruiting_cost_form',1)), ...
    value(c,'complete_insurance_sgu',0.001));
end


function write_calibration_overrides(scratch_dir,configuration)
path = fullfile(scratch_dir,'complete_calibration_overrides.mod');
fid = fopen(path,'w');
assert(fid>=0,'CompleteInsurance:CalibrationOverrides', ...
    'Could not write %s.',path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'// Generated complete-insurance calibration overrides.\n');
parameters = complete_calibration_parameters(configuration);
names = fieldnames(parameters);
for i = 1:numel(names)
    parameter = names{i};
    parameter_value = parameters.(parameter);
    fprintf(fid,'%s = %.17g;\n',parameter,parameter_value);
end
end


function d = validate_run(sim,names,param_names,param_values,pre_ss,post_ss,oo,c)
names = strtrim(cellstr(names));
param_names = strtrim(cellstr(param_names));
v = @(name) sim(require_name(names,name),:);
p = @(name) param_values(require_name(param_names,name));
finite_paths = all(isfinite(sim(:)));
positive_names = {'C_a_t','C_b_t','Y_a_t','Y_b_t','N_a_t','N_b_t', ...
    'NT_a_t','NT_b_t','NN_a_t','NN_b_t','k_a_t','k_b_t'};
positive_paths = all(cellfun(@(name) all(v(name)>0),positive_names));

mass_a = v('mue_a_t'); mass_b = v('mue_b_t');
for state = 1:8
    mass_a = mass_a+v(sprintf('mueu%d_a_t',state));
    mass_b = mass_b+v(sprintf('mueu%d_b_t',state));
end
mass_a = mass_a+v('muuu_a_t'); mass_b = mass_b+v('muuu_b_t');
mass_residual = max([abs(mass_a-1),abs(mass_b-1)],[],'all');

insurance_gap = 0;
for land = {'a','b'}
    suffix = land{1}; C = v(['C_' suffix '_t']);
    insurance_gap = max(insurance_gap,max(abs(v(['Ce_' suffix '_t'])-C)));
    insurance_gap = max(insurance_gap,max(abs(v(['Cuu_' suffix '_t'])-C)));
    for state = 1:8
        insurance_gap = max(insurance_gap,max(abs( ...
            v(sprintf('Ceu%d_%s_t',state,suffix))-C)));
    end
end

savings_a = representative_agent_savings_accounts( ...
    sim,names,param_values,param_names,'a');
savings_b = representative_agent_savings_accounts( ...
    sim,names,param_values,param_names,'b');
savings_reconciliation = max( ...
    savings_a.max_reconciliation_relative, ...
    savings_b.max_reconciliation_relative);

bargaining_residual = 0;
for land = {'a','b'}
    suffix = land{1}; zeta = p(['xoui_' suffix]);
    residual = v(['She_' suffix '_t']) ...
        -zeta/(1-zeta)*(1-v(['tauw_' suffix '_t'])) ...
        .*v(['lambdae_' suffix '_t']).*v(['Sf_' suffix '_t']);
    bargaining_residual = max(bargaining_residual,max(abs(residual)));
end

static_pre = field_nested(oo,{'fix_decomposition', ...
    'transition_pre_static_residual'},NaN);
static_post = field_nested(oo,{'fix_decomposition', ...
    'post_static_residual'},NaN);
max_static = max([static_pre,static_post],[],'omitnan');
transition_status = field_nested(oo,{'deterministic_simulation','status'},true);
if isempty(transition_status), transition_status = true; end

terminal_names = {'C_a_t','C_b_t','N_a_t','N_b_t','NT_a_t','NT_b_t', ...
    'NN_a_t','NN_b_t','k_a_t','k_b_t','NFA_a_t','NFA_b_t'};
terminal_gap = 0;
for i = 1:numel(terminal_names)
    index = require_name(names,terminal_names{i});
    scale = 1+abs(post_ss(index));
    terminal_gap = max(terminal_gap,abs(sim(index,end)-post_ss(index))/scale);
end

rrl_before = value(c,'rrl_a',0.5);
rrl_after = p('rrl_a');
actual_cut = 1-rrl_after/rrl_before;
requested_cut = value(c,'reform_cut',0.37891718657);
policy_pass = abs(actual_cut-requested_cut) <= 1e-10 ...
    && round(value(c,'entitlement_cut_periods',4)) == 4;
calibration_pass = abs(p('iac_a')-8.7)<=1e-12 ...
    && abs(p('chi_sector_T_a')-1)<=1e-12 ...
    && abs(p('chi_sector_N_a')-3.5)<=1e-12 ...
    && p('recruiting_cost_form')==1 ...
    && abs(p('delta_a')-value(c,'depreciation_rate',0.03))<=1e-12 ...
    && abs(p('sigmac')-value(c,'sigmac',2))<=1e-12 ...
    && abs(p('betta_b')-p('betta_a'))<=1e-12;

d = struct();
d.steady_state_solved = all(isfinite(pre_ss)) && all(isfinite(post_ss)) ...
    && isfinite(max_static) && max_static < 1e-8;
d.transition_solved = logical(transition_status) && finite_paths;
d.accounting_pass = mass_residual < 1e-8 && insurance_gap < 1e-8 ...
    && savings_reconciliation < 1e-8;
d.bargaining_identity_pass = bargaining_residual < 1e-8;
d.target_metric_available = all(isfinite(v('NT_a_t'))) ...
    && all(isfinite(v('NN_a_t')));
d.horizon_pass = terminal_gap < 1e-5;
d.economic_validation_pass = positive_paths && policy_pass && calibration_pass;
d.max_static_residual = max_static;
d.mass_residual = mass_residual;
d.complete_insurance_consumption_gap = insurance_gap;
d.household_saving_reconciliation = savings_reconciliation;
d.bargaining_threat_point = ...
    'duration_state_income_values_under_common_marginal_utility';
d.bargaining_identity_residual = bargaining_residual;
d.terminal_gap = terminal_gap;
d.policy_pass = policy_pass;
d.calibration_pass = calibration_pass;
d.rrl_before = rrl_before;
d.rrl_after = rrl_after;
d.actual_reform_cut = actual_cut;
d.all_pass = d.steady_state_solved && d.transition_solved ...
    && d.accounting_pass && d.bargaining_identity_pass ...
    && d.target_metric_available && d.horizon_pass ...
    && d.economic_validation_pass;
if d.all_pass
    d.message = 'Corrected representative-agent transition passed all declared gates.';
else
    d.message = 'Corrected representative-agent transition failed at least one declared gate.';
end
end


function copy_required(source_dir,target_dir,names)
ensure_folder(target_dir);
for i = 1:numel(names)
    source = fullfile(source_dir,names{i});
    assert(isfile(source),'CompleteInsurance:Source','Missing source file %s.',source);
    copyfile(source,fullfile(target_dir,names{i}),'f');
end
end


function copy_if_present(source,target)
if isfile(source), copyfile(source,target,'f'); end
end


function ensure_folder(path)
if ~isfolder(path), mkdir(path); end
end


function index = require_name(names,name)
index = find(strcmp(names,name),1);
assert(~isempty(index),'CompleteInsurance:Name','Missing model name %s.',name);
end


function x = value(s,name,default)
if isfield(s,name) && isnumeric(s.(name)) && isscalar(s.(name)) ...
        && isfinite(s.(name))
    x = double(s.(name));
else
    x = default;
end
end


function x = finite_or(s,name,default)
x = value(s,name,default);
if ~isfinite(x), x = default; end
end


function x = logical_value(s,name,default)
if isfield(s,name) && (islogical(s.(name)) || isnumeric(s.(name))) ...
        && isscalar(s.(name))
    x = double(logical(s.(name)));
else
    x = double(logical(default));
end
end


function x = field_nested(s,names,default)
x = s;
for i = 1:numel(names)
    if ~isstruct(x) || ~isfield(x,names{i})
        x = default; return
    end
    x = x.(names{i});
end
end


function write_json(path,value)
fid = fopen(path,'w');
assert(fid>=0,'CompleteInsurance:JSON','Could not write %s.',path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));
end
