function make_paper_style_figure(fig_num, tt, series_spec, y_label, file_name, y_lim, y_ticks, x_lim, x_ticks, FigureDir, legend_pos)
f = figure(fig_num);
clf(f);
set(f, ...
    'Color', [1 1 1], ...
    'Units', 'pixels', ...
    'Position', [100 100 1440 720], ...
    'PaperUnits', 'inches', ...
    'PaperPosition', [0 0 10 5], ...
    'PaperSize', [10 5], ...
    'PaperPositionMode', 'auto', ...
    'InvertHardcopy', 'off');

ax = axes('Parent', f, 'Units', 'normalized', 'Position', [0.16 0.17 0.76 0.70]);
hold(ax, 'on');

h = gobjects(size(series_spec, 1), 1);
for i = 1:size(series_spec, 1)
    h(i) = plot(ax, tt, series_spec{i, 1}, ...
        'Color', [0.35 0.35 0.35], ...
        'LineStyle', series_spec{i, 3}, ...
        'Marker', series_spec{i, 4}, ...
        'LineWidth', series_spec{i, 5}, ...
        'MarkerSize', 5);
end

set(ax, ...
    'FontName', 'Times', ...
    'FontSize', 9, ...
    'LineWidth', 0.9, ...
    'Box', 'on', ...
    'Layer', 'top', ...
    'XColor', [0.25 0.25 0.25], ...
    'YColor', [0.25 0.25 0.25], ...
    'XLim', x_lim, ...
    'YLim', y_lim, ...
    'XTick', x_ticks, ...
    'YTick', y_ticks, ...
    'TickDir', 'in', ...
    'TickLength', [0.01 0.01], ...
    'XMinorTick', 'off', ...
    'YMinorTick', 'off');

xlabel(ax, 'Quarters', 'FontName', 'Times', 'FontSize', 10);
ylabel(ax, y_label, 'FontName', 'Times', 'FontSize', 10);

grid(ax, 'on');
ax.GridColor = [0.85 0.85 0.85];
ax.GridAlpha = 0.8;
ax.MinorGridAlpha = 0.4;

labels = series_spec(:, 2);
lgd = legend(ax, h, labels{:}, ...
    'FontName', 'Times', ...
    'FontSize', 7, ...
    'Box', 'on', ...
    'Color', [1 1 1], ...
    'EdgeColor', [0.35 0.35 0.35], ...
    'Units', 'normalized');
lgd.Position = legend_pos;

print(f, fullfile(FigureDir, file_name), '-painters', '-depsc', '-r300')
print(f, fullfile(FigureDir, file_name), '-painters', '-dpng', '-r300')
end
